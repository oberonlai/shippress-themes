#!/usr/bin/env node
// ROADMAP.md queue section, generated from design-plan.json (the machine queue the pipeline reads and writes; #640).
//   node scripts/sync-roadmap.mjs --write [--root DIR]   # rewrite the block between the roadmap:auto markers
//   node scripts/sync-roadmap.mjs --check [--root DIR]   # exit 1 when that block differs from design-plan.json (CI)
// Everything outside the markers is hand-written and never touched. Output has no timestamps, so --check is stable.
// shippress-pipeline plan-next.sh (new rows) and ship.sh (row → done) run --write in the same commit as design-plan.json.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const START = "<!-- roadmap:auto:start — generated by scripts/sync-roadmap.mjs from design-plan.json; do not edit by hand -->";
export const END = "<!-- roadmap:auto:end -->";
const ORDER = ["done", "todo", "claimed", "rejected"];

export const statusOf = (s) => (String(s ?? "").trim().match(/^[a-z_-]+/i)?.[0] || "unknown").toLowerCase();
const cell = (v) => String(v ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
const batchOf = (id) => (String(id ?? "").match(/^(b\d+)-/) || [])[1] || "other";
const batchNum = (b) => (b === "other" ? Infinity : +b.slice(1));

export function renderQueue(dp) {
  const rows = dp.plan || [];
  const count = {}; for (const r of rows) { const s = statusOf(r.status); count[s] = (count[s] || 0) + 1; }
  const keys = [...ORDER.filter((k) => count[k] !== undefined || k === "done" || k === "todo"), ...Object.keys(count).filter((k) => !ORDER.includes(k)).sort()];
  const todo = rows.filter((r) => statusOf(r.status) === "todo");
  const batches = new Map();
  for (const r of rows) { const b = batchOf(r.id); if (!batches.has(b)) batches.set(b, []); batches.get(b).push(r); }
  const bl = [...batches.keys()].sort((a, b) => batchNum(a) - batchNum(b));
  const out = [
    `Generated from \`design-plan.json\` (the queue the pipeline reads; \`plan-next.sh\` appends rows, \`ship.sh\` marks them done). Do not edit between the markers: run \`node scripts/sync-roadmap.mjs --write\`; CI runs \`--check\`.`,
    "",
    `**${rows.length} rows:** ${keys.map((k) => `${count[k] || 0} ${k}`).join(" · ")}`,
    "",
    `**Next todo (queue order):** ${todo.length ? todo.map((r) => `${cell(r.id)} \`${cell(r.slug)}\``).join(", ") : "none — plan-next.sh plans the next batch"}`,
    "",
    "| Batch | Rows | done | todo | rejected | other |",
    "|---|---|---|---|---|---|",
    ...bl.map((b) => { const rs = batches.get(b); const c = (s) => rs.filter((r) => statusOf(r.status) === s).length;
      return `| ${b} | ${rs.length} | ${c("done")} | ${c("todo")} | ${c("rejected")} | ${rs.length - c("done") - c("todo") - c("rejected")} |`; }),
    "",
    "| # | ID | Name / slug | Industry | Type | Status |",
    "|---|---|---|---|---|---|",
    ...rows.map((r) => { const s = statusOf(r.status);
      return `| ${cell(r.n)} | ${cell(r.id)} | ${cell(r.name)} / \`${cell(r.slug)}\` | ${cell(r.industry)} | ${cell(r.type)} | ${s === "todo" ? "**todo**" : s} |`; }),
  ];
  return out.join("\n");
}

export function syncText(text, dp) {
  const a = text.split(START), parts = a.length === 2 ? a[1].split(END) : [];
  if (a.length !== 2 || parts.length !== 2) throw new Error(`ROADMAP.md needs exactly one ${START} … ${END} markers pair`);
  return `${a[0]}${START}\n${renderQueue(dp)}\n${END}${parts[1]}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2), i = args.indexOf("--root");
  const root = i >= 0 ? args[i + 1] : join(dirname(fileURLToPath(import.meta.url)), "..");
  const mode = args.includes("--write") ? "write" : args.includes("--check") ? "check" : null;
  if (!mode) { console.error("usage: sync-roadmap.mjs --check|--write [--root DIR]"); process.exit(2); }
  const file = join(root, "ROADMAP.md");
  const cur = readFileSync(file, "utf8");
  let next;
  try { next = syncText(cur, JSON.parse(readFileSync(join(root, "design-plan.json"), "utf8"))); }
  catch (e) { console.error(`sync-roadmap: ${e.message}`); process.exit(1); }
  if (mode === "check") {
    if (next !== cur) { console.error("sync-roadmap: ROADMAP.md queue section is out of date with design-plan.json — run: node scripts/sync-roadmap.mjs --write"); process.exit(1); }
    console.log("sync-roadmap: ROADMAP.md in sync");
  } else if (next !== cur) { writeFileSync(file, next); console.log("sync-roadmap: ROADMAP.md updated"); }
  else console.log("sync-roadmap: ROADMAP.md already in sync");
}
