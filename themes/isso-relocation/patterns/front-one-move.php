<!-- wp:paragraph  -->
<p>On Friday at 18:00 our crew arrived at an architecture studio in Ghent to merge forty-two desks from two floors into one. The studio had packed over the previous ten working days, so the crew could go straight to protecting the drafting tables and the catalogued scale drawings.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph  -->
<p>By Saturday morning both upper floors were cleared to the bare walls. Reassembly began on the lower level at sunrise under Kwame Mensah and Ana Ribeiro, while Joanna Kowalczyk connected cables and computers to their numbered workstations.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph  -->
<p>At 16:40 on Sunday the studio manager made the final inspection, more than fourteen hours before opening. All forty-two desks were powered, aligned and clean when the team arrived on Monday.</p>
<!-- /wp:paragraph -->
