<h2 class="wp-block-heading">The lines that <em>grow</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>As celadon cools, the glaze shrinks a little more than the clay beneath it and a fine net of lines appears. On some pieces it keeps forming quietly for months, with a tiny ping you can hear on a still evening.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Tea and food slowly colour the lines, so a cup used every morning darkens into its own map. If you would rather keep it pale, rinse after use and let it dry. If you love the map, simply keep using it.</p>
