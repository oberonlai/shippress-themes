<!-- wp:heading {"className":"su-kiln__name"} -->
<h2 class="wp-block-heading su-kiln__name">Ishizuchi Kiln</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Wood-fired vases, bottles and sake sets that carry the marks of the fire.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Twice a year Kenji Arata and four friends feed a climbing kiln with red pine for four days without a break. Ash flies through the chambers and melts onto the pots, running green down their shoulders. No two pieces come out the same, and that is the point.</p>
