<!-- wp:heading {"className":"su-kiln__name"} -->
<h2 class="wp-block-heading su-kiln__name">Shirokawa Kiln</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Carved porcelain under a pale seiji glaze: teacups, jars and chopstick rests.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Haru Odagiri carves porcelain while it is leather-hard, cutting petals and ripples that the glaze then fills and softens. Where the glaze runs thin the white shows through; where it pools the carving reads as a shadow. It is slow work, and the pieces are small.</p>
