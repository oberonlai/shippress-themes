<!-- wp:heading {"className":"su-kiln__name"} -->
<h2 class="wp-block-heading su-kiln__name">Mizunoe Kiln</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Celadon so clear it looks like still water: rice bowls, plates and platters.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Sayo Mizunoe glazes thick and fires slow, so the celadon pools in every hollow and turns from pale sea-glass on the rims to deep teal in the well. She throws about forty bowls a week and keeps perhaps thirty. The rest go back into the clay bin.</p>
