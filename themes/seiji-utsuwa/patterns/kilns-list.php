<h2 class="wp-block-heading su-kiln__name">Tsukiyama Kiln</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Everyday bowls and small dishes with a dark iron rim, made to be used hard.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Emi throws, Daichi trims and glazes. Their bowls are a little heavier than most, with a rounded foot that sits well in the hand and a rim brushed in iron that fires almost black. They test every new shape at their own table for a month before it reaches ours.</p>
