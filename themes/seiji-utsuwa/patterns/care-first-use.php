<h2 class="wp-block-heading">Four <em>habits</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"su-small"} -->
<p class="su-small">Stoneware is fired hard but stays slightly open, like a stone from a river. Water closes it; oil and dark sauces, left to sit, can find their way in.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"su-care__list","style":{"layout":{"columnSpan":8}},"layout":{"type":"default"}} -->
<div class="wp-block-group su-care__list"><!-- wp:list {"ordered":true,"className":"is-style-index"} -->
<ol class="wp-block-list is-style-index"><!-- wp:list-item -->
<li><strong>Soak stoneware once.</strong> Before its first use, rest the piece in cool water (rice-rinsing water is traditional) for an hour, then let it dry for a day.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Rinse before oily food.</strong> A quick rinse in water before serving fills the pores, so oil and sauces wipe away instead of soaking in.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Dry the foot.</strong> Unglazed foot rings hold water. Let them dry upside down before stacking or putting away.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Warm slowly.</strong> No pieces straight from the fridge to a hot oven or flame. Celadon dislikes sudden heat more than heat itself.</li>
<!-- /wp:list-item --></ol>
