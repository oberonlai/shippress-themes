<p>In 2017 Ayame Fujita came home from a week of kiln visits with more bowls than her kitchen could hold. She put the extras on a shelf by the window of her flat, and friends began to ask if they could buy them. Ren Okabe, who had spent ten years packing paintings for museums, offered to help with the wrapping.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The shelf became a room, the room a website. We still choose every piece by hand and still wrap each one the way Ren learned to wrap a painting: as if it were the only one. We have grown slowly on purpose, and we intend to keep it that way.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The name means water-blue, the colour of the first celadon bowl Ayame bought, from Sayo Mizunoe, at a village market twenty years ago. She still eats from it every day.</p>
