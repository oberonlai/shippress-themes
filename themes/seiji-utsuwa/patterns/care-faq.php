<details class="wp-block-details"><summary>Can I put celadon in the dishwasher?</summary><!-- wp:paragraph -->
<p>Yes, every celadon piece we sell is fired hard enough for it. Hand washing keeps the glaze glossy for longer, but you do not have to.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is a crackle a crack?</summary><!-- wp:paragraph -->
<p>No. Crackle lives only in the glass of the glaze and does not go through the clay. A crack you can feel with a fingernail, or that rings dull when tapped, is different: write to us.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Why does my new bowl smell of earth when wet?</summary><!-- wp:paragraph -->
<p>That is the bare clay of the foot. It fades after a few washes and a day in the sun.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are the glazes food-safe?</summary><!-- wp:paragraph -->
<p>Yes. All our kilns use lead-free glazes and each new glaze is tested before it reaches the shop.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Something arrived broken. What now?</summary><!-- wp:paragraph -->
<p>Photograph it in its wrapping and write within seven days. We send a replacement or refund it, and the pieces can go to our repairer if you want to keep them.</p>
