<p class="hk-role">Online Proctored Exam and Certification Details</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">The course concludes with an online proctored exam sat from any quiet room with a standard webcam and laptop. The test consists of 40 multiple-choice questions with a 60-minute time limit, and the pass mark is 75 %. Questions evaluate practical supervisory judgment based on the Codex Alimentarius HACCP principles, temperature danger zones, and corrective actions. If you do not meet the pass mark on your first attempt, you receive one free resit within 30 days. Upon passing, your official Hakari Course supervisor certificate is issued as a downloadable PDF within 2 working days, remaining valid for 3 years.</p>
