<h3 class="wp-block-heading hk-rh">Course Fees and Inclusions</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">All course fees are charged in EUR and include VAT with no hidden administrative add-ons. The full course fee is €390, which includes 24 online lessons, 6 live Q&amp;A sessions on Tuesday evenings, the practical testing kit delivered to your kitchen, the proctored exam, and one free exam resit within 30 days. For learners who already own a professional digital probe and calibration gear, the course without kit option is €340. Businesses booking team seats for 5 or more learners from one company receive a rate of €330 per seat, including full practical kits. Company invoices are available upon request.</p>
