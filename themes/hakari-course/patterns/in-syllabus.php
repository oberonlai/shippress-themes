<div class="wp-block-group hk-read"><!-- wp:heading {"level":3,"className":"hk-rh"} -->
<h3 class="wp-block-heading hk-rh">Weeks 1 and 2: Hazards, Contamination, and Temperature Control</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">Week 1 introduces how biological, chemical, physical, and allergenic hazards travel through professional kitchens, mapping common cross-contamination routes across prep tables, sinks, and storage racks. Learners complete four lessons of ten to twenty minutes each and finish by charting their kitchen's delivery flow. Week 2 transitions directly into temperature management. Supervisors study the danger zone between 5 °C and 63 °C, safe cooking practices to reach a 75 °C core temperature, hot holding at 63 °C or higher, and weekly probe calibration. The practice task requires calibrating your probe thermometer in iced water and recording your first cold-line audit.</p>
<!-- /wp:paragraph --><!-- wp:heading {"level":3,"className":"hk-rh"} -->
<h3 class="wp-block-heading hk-rh">Weeks 3 and 4: Cooling, Reheating, Cleaning, and Allergens</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">Week 3 tackles one of the highest-risk supervisory tasks: cooling, chilling, and reheating safely. Lessons detail the two-stage cooling curve, chilling foods to 5 °C or below within established windows, and reheating once to a verified 75 °C core temperature. Your practice task involves documenting a cooling cycle for a batch cooked sauce or protein. Week 4 focuses on systematic sanitation and ingredient safety. You will examine clean-as-you-go workflows, two-stage chemical cleaning, early pest warning signs, and allergen control covering the 14 major allergens. The practical exercise has supervisors audit dry-store allergen separation and prep station cleaning schedules.</p>
<!-- /wp:paragraph --><!-- wp:heading {"level":3,"className":"hk-rh"} -->
<h3 class="wp-block-heading hk-rh">Weeks 5 and 6: HACCP Principles and Shift Leadership</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">Week 5 explores HACCP implementation through the seven principles of the Codex Alimentarius General Principles of Food Hygiene. Supervisors learn to establish practical critical limits, set monitoring frequencies, record deviations accurately, and implement corrective actions that staff understand. The practice task requires drafting an action log for an out-of-spec hot hold. Week 6 prepares you to lead food-safe shifts with confidence. Instruction covers brief team briefings, efficient shift handovers, managing formal health inspections, and structured preparation for the final exam. Across all six weeks, learners invest approximately 18 total hours, including practical kitchen logs and live Q&amp;A attendance.</p>
