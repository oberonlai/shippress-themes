<h3 class="wp-block-heading hk-headl">Your practical<br>log</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"hk-body"} -->
<p class="hk-body">Rather than relying purely on theoretical multiple-choice quizzes, the course requires a verified practical temperature log. Learners use the kit shipped upon enrolment—including a calibrated digital probe thermometer, calibration cup, 50 probe wipes, and a log pad—to document five distinct probe checks in their own working kitchen. These checks cover goods inward delivery checks, core cooking temperatures, rapid cooling cycles, hot-holding service lines, and cold storage units. Each completed log sheet is reviewed directly by your tutor, ensuring your measuring techniques and corrective action documentation match professional kitchen standards.</p>
