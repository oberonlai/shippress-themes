<p class="ah-chapter__label"><span class="ah-chapter__no">03</span> The press</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className": "ah-chapter__title"} -->
<h2 class="wp-block-heading ah-chapter__title">A baren and two hundred small circles</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Each sheet is laid on the block by eye against two cut marks, then rubbed with a baren of bamboo leaf. One colour, one block, one pass: a five-colour print is five days.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We stop at thirty. The edition is signed, numbered and the block is kept for mending.</p>
