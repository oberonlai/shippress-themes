<h2 class="wp-block-heading ah-chapter__title">One plank of mountain cherry</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every print starts as a plank of mountain cherry, planed until it holds a thumbnail of water without a ripple. We paste the drawing face down, rub the paper thin, and the lines show through like veins under a leaf.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The knife follows those lines for days. What is cut away becomes white; what is left becomes ink.</p>
