<!-- wp:heading {"className": "ah-chapter__title"} -->
<h2 class="wp-block-heading ah-chapter__title">Water, pigment and a little rice paste</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We brush pigment and rice paste straight onto the wet block. Too much water and the colour floods; too little and the wood grain shows like rain. Spring green takes the longest to get right, so we mix it first.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

