<h3 class="wp-block-heading nagi-tx__h">Modality expansion: introducing MRI in 2019</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"nagi-tx__b"} -->
<p class="nagi-tx__b">As nearby medical practices and allied healthcare clinics grew to rely on our same-day reporting workflow, we expanded our imaging capacity. In 2019, we installed our high-field MRI scanner, allowing us to deliver rapid cross-sectional imaging for complex neurological, spinal, and joint pathologies. Alongside MRI and CT, we integrated digital general radiography, high-resolution diagnostic ultrasound, DEXA bone densitometry, and dedicated mammography into our facility. Each modality was selected to provide local medical practitioners with a comprehensive, reliable outpatient diagnostic service situated just minutes from their practice doors.</p>
