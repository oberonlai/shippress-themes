<h3 class="wp-block-heading nagi-tx__h">Founded at Calder Quay in 2016</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"nagi-tx__b"} -->
<p class="nagi-tx__b">Nagi Imaging opened its doors in 2016 at 14 Calder Quay, Grand Canal Dock, Dublin 2. Founders Dr. Amira Haddad and Tomás Oyelaran recognized a persistent frustration among local general practitioners: while modern imaging scans take only minutes to acquire, patients and doctors often waited up to a week for a written report. Operating from a quiet outpatient suite overlooking the water, Nagi Imaging began with a single high-specification CT scanner and an uncompromising founding rule: patients scanned in the morning would have their finalized radiological reports delivered before clinics closed that same evening.</p>
