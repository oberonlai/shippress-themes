<h3 class="wp-block-heading nagi-tx__h">What does a Nagi imaging report contain?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"nagi-tx__b"} -->
<p class="nagi-tx__b">Each report is structured into distinct, readable sections: clinical history, technique, detailed anatomical findings, and an overarching impression. Rather than offering speculative conclusions, our radiologists compare current scans against previous examinations whenever earlier images are supplied, documenting interval stability or change. Reports conclude with concise, objective recommendations that assist the clinician with treatment planning without speculative claims. If an unexpected or urgent finding is identified during review, our duty radiologist immediately telephones the referring doctor within the hour to discuss the case directly, ensuring patient safety remains paramount.</p>
