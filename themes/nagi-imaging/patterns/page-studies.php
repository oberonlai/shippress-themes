<!-- wp:paragraph {"className":"nagi-tx__b"} -->
<p class="nagi-tx__b">Ultrasound examinations are carried out by our senior sonographer or consultant radiologists, covering abdominal, pelvic, small parts, and musculoskeletal assessments with real-time dynamic evaluation. Digital radiography provides rapid, low-dose general imaging across two standard views per requested region, including chest, spine, and extremity examinations. Both modalities operate with minimal waiting times and clear clinical protocols. Completed imaging datasets are immediately transferred to our digital archive for same-day review, allowing referring general practitioners and physiotherapists to receive structured diagnostic reports by 18:00 for morning and early afternoon appointments.</p>
