<!-- wp:details -->
<details class="wp-block-details"><summary>Can I choose a time?</summary><!-- wp:paragraph -->
<p>Choose a morning or an afternoon round at checkout. For a wedding, a funeral or a surprise at a set minute, call us and we will do our best.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

