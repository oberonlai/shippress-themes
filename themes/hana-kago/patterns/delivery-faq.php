<details class="wp-block-details"><summary>What if nobody is home?</summary><!-- wp:paragraph -->
<p>We try a neighbour you name, or leave the flowers in a safe, shaded spot you describe. Otherwise they come back to the cool room and we call you to try again the next morning, free.</p>
<!-- /wp:paragraph --></details>
