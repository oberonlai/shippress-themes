<h2 class="wp-block-heading kk-statement">What specialized training facilities are on site?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Northmere campus comprises two modern classrooms equipped for medical lectures, an anatomy study library, and a large drill hall for extrication scenarios. At the heart of the facility is our advanced skills lab, housing two full-scale ambulance-body simulators where students practice clinical interventions in tight spaces. The lab includes cardiac monitors, airway manikins, and emergency medication kits matching frontline ambulance inventories. Students have access to the skills lab from Monday to Saturday between 07:30 and 21:00 for supervised practice, allowing cohorts to refine procedural techniques outside regular class hours.</p>
