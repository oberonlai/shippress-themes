<h2 class="wp-block-heading kk-statement">When can prospective students visit the college?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We host an open evening on the first Thursday of every month from 18:00 to 20:00, offering prospective students an opportunity to tour our simulation suites, meet instructors, and view live equipment demonstrations. Administrative offices are open Monday to Friday from 08:30 to 17:00 for general inquiries and prospectus collection. Questions regarding course schedules or visits can be directed to admissions@kyukyu-college.example or by calling +1 555 0142. Staff members are available during open evenings to discuss application prerequisites, physical assessments, and placement expectations with prospective applicants.</p>
