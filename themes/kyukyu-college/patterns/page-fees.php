<h2 class="wp-block-heading kk-statement">When are tuition instalments due?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Tuition for the Paramedic Diploma is split into three equal instalments across each academic year to assist with budgeting. The first instalment is due in September upon term registration, the second instalment is due in January before the skills lab term begins, and the third instalment is due in April prior to clinical placements. Every formal application requires a non-refundable $60 application fee, submitted alongside the initial paperwork. Tuition payments must be settled according to this schedule to ensure continued enrolment in simulation classes and scheduled frontline ambulance placement shifts.</p>
