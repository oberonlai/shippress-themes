<h2 class="wp-block-heading kk-statement">What bursaries and refund terms are available?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>To assist dedicated students requiring financial support, Kyukyu College provides two competitive bursaries valued at $3,000 per year. Bursary applications are reviewed annually by the administration based on financial need and academic promise. Regarding refunds, the college offers a full refund of tuition fees if an admitted student formally withdraws before the first day of the academic term. Once teaching begins, tuition payments become non-refundable for that term. The initial $60 application fee remains strictly non-refundable under all circumstances once processing has commenced.</p>
