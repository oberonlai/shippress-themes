<h3 class="wp-block-heading kk-h3">What facilities are housed at 41 Wexford Lane?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our campus at 41 Wexford Lane in Northmere is designed entirely around emergency simulation. The facility houses two lecture classrooms for theoretical coursework, a medical library with anatomy models, and an expansive drill hall for large-scale vehicle extrication scenarios. At the centre of the building is our specialized skills lab, equipped with two full-scale ambulance-body simulators where students practice patient transfers, airway management, and cardiac monitoring. Training occurs in small groups with an instructor-to-student ratio of one to eight, ensuring constant supervision. The skills lab remains open to students from Monday to Saturday, 07:30 to 21:00.</p>
