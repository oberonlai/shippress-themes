<h3 class="wp-block-heading kk-h3">How was Kyukyu College founded?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kyukyu College was founded in 2011 by Principal Dr. Ruth Adeyemi-Holm, a former emergency physician, alongside two active station paramedics. The founders recognized that traditional academic programmes often separated emergency theory from the physical pressure of real-time clinical decisions. They established the college to teach the essential clinical and operational work that must occur before a patient reaches hospital care. Since welcoming its first class, the college has maintained cohorts of 24 students to ensure direct access to instructors and simulation bays. Every tutor continues to work active operational shifts, ensuring that classroom doctrine matches current field practice.</p>
