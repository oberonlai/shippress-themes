<h2 class="wp-block-heading kk-statement">What kit is required and what does the supplement fee cover?</h2>
<!-- /wp:heading -->

<!-- wp:html -->
<ol class="kk-req sp-stagger"><li class="sp-reveal sp-reveal--up"><span class="kk-req__n">01</span><span class="kk-req__t"><strong>Uniform.</strong> College uniform with high-visibility reflective outerwear.</span></li><li class="sp-reveal sp-reveal--up"><span class="kk-req__n">02</span><span class="kk-req__t"><strong>Boots.</strong> Heavy-duty safety boots.</span></li><li class="sp-reveal sp-reveal--up"><span class="kk-req__n">03</span><span class="kk-req__t"><strong>Shears.</strong> Personal trauma shears.</span></li><li class="sp-reveal sp-reveal--up"><span class="kk-req__n">04</span><span class="kk-req__t"><strong>Supplement.</strong> $640 per year covers insurance, uniform and vaccinations.</span></li></ol>
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>All students must deploy on shift in approved college uniform, including high-visibility reflective outerwear, heavy-duty safety boots, and personal trauma shears. Kyukyu College assesses an annual ride-along placement supplement fee of $640. This mandatory charge directly covers professional indemnity insurance, standardized uniform issuance, and all required clinical occupational vaccinations. Students receive their kit inspection clearance before entering active service, ensuring full compliance with regional station health protocols. Tutors verify all personal protective equipment during the preparatory skills lab term prior to first station deployment.</p>
