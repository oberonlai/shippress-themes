<h2 class="wp-block-heading kk-statement">How is a ride-along placement week structured?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A typical ride-along placement week follows a strict five-stop schedule designed to balance clinical intensity with structured reflection. On Monday, students work a twelve-hour day shift from 07:00 to 19:00, followed by a second twelve-hour day shift on Tuesday from 07:00 to 19:00. Wednesday is an assigned rest day dedicated to resting and drafting a mandatory reflective log. On Thursday, students complete a twelve-hour night shift running from 19:00 to 07:00. The week concludes on Friday morning with a two-hour clinical debrief from 10:00 to 12:00 alongside their dedicated college tutor.</p>
<!-- /wp:paragraph --></div>
