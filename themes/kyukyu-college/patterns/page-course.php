<h2 class="wp-block-heading kk-statement">Two years, six terms, one qualification.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Paramedic Diploma runs two years full-time with an intake in September and February. Each year holds three twelve-week terms: classroom foundations, skills lab simulation and operational placements, taught at one instructor to eight students.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Each intake is limited to twenty-four students, and every instructor still works shifts on an ambulance. You qualify in July of Year 2, after the final assessment and your last ride-along block. Tuition is $14,800 per year.</p>
