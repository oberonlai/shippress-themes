<h2 class="wp-block-heading kk-statement">How is the first year of the diploma structured?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Year One consists of three consecutive twelve-week terms running from September through June. Term 01 focuses on classroom fundamentals, covering anatomy, physiology, and emergency pharmacology. Term 02 moves directly into the skills lab, where students spend hundreds of hours mastering patient assessment, advanced airway maneuvers, and cardiac defibrillation at an instructor ratio of one to eight. Term 03 places students into their initial ride-along shifts, pairing each candidate with experienced mentors aboard active ambulance units. Across these thirty-six weeks, students transition from foundational medical science to coordinated emergency response under realistic environmental pressures.</p>
