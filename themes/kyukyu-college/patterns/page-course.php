<h2 class="wp-block-heading kk-statement">What does Year Two require for graduation?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Year Two is dedicated to clinical consolidation and advanced pre-hospital care. Students complete the remainder of their mandatory 480 frontline ride-along hours, managing acute medical emergencies, pediatric calls, and complex trauma alongside station crews. Between placement blocks, students return to campus for advanced simulation drills in the drill hall and skills lab. The academic cycle culminates in July with comprehensive clinical assessments, objective structured examinations, and case portfolio reviews. Candidates who meet every clinical requirement graduate fully prepared to step directly into emergency ambulance rosters as certified paramedics.</p>
<!-- /wp:paragraph -->

