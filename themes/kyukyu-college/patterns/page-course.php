<h2 class="wp-block-heading kk-statement">What other emergency qualifications are offered?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Alongside our flagship diploma, Kyukyu College offers focused credentials for emergency healthcare careers. The Emergency Medical Technician Certificate is a one-year programme starting every September with tuition set at $9,600. For applicants needing stronger academic preparation, our twelve-week Foundation Term provides pre-entry instruction in science and physical fitness for $2,400 with intakes in September and February. Practicing professionals can also attend our three-day Advanced Life Support refresher for $720 or our two-day emergency driving theory course for $480, both scheduled monthly throughout the calendar year.</p>
