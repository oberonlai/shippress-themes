<h3 class="wp-block-heading ss-h3">What you receive</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The deliverable is a written report, then a 45-minute review meeting. The report names the instruction, the place, the dates and the methods. A walkover records what was seen and whether any next step is justified. Phase I sets out past use and whether the soil should be opened. A sampling round lists the points, up to six, and the laboratory results that came back within 15 working days. Phase II reports the investigation that was agreed, including the laboratory work that belongs to it. You keep the report. We will say in it what was done. We will not write that a buyer, a neighbour or a public authority is obliged to accept it.</p>
<!-- /wp:paragraph --><!-- wp:heading {"level":3,"className":"ss-h3"} -->
<h3 class="wp-block-heading ss-h3">Phase I, Phase II and the sampling round</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The price rows for this work, in USD, are the same rows as on the fees page. Phase I environmental site assessment is $3,400. Phase II soil investigation is from $8,900. A water quality sampling round, up to 6 points, is $2,250. The walkover and desk study that often comes first is $1,850. All prices exclude laboratory courier beyond 60 km and tax. Half is due on instruction and half when the report is issued. A single sampling round is not a monitoring year. Four rounds at one site are the annual programme at $6,600 a year. The free scoping call, 20 minutes, within 2 working days, is where the row is chosen.</p>
