<h3 class="wp-block-heading ss-h3">Former tannery lot, Fennick Road, 2023</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">In 2023 a private landowner instructed Phase I and Phase II on the former tannery lot at Fennick Road, before resale. The site is SL-02, soil, on the ledger from that year. The challenge was an industrial past on a lot a buyer would ask about. What we did was Phase I at the published fee of $3,400, covering history and the walk of the site without opening the ground, then Phase II from the published start of $8,900 where that first phase showed the soil should be sampled. A written report and the 45-minute review closed the instruction. The outcome we state is that both phases were completed and reported before resale. We do not state that the lot was clear, or that every trace of the tannery was found.</p>
