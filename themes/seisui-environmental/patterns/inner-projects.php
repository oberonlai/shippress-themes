<h3 class="wp-block-heading ss-h3">Wend Meadow reach, 2021</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">In 2021 Alder Bridge council asked for a baseline before restoration of the floodplain meadow on the Wend Meadow reach, and for monitoring across three years. The site is WM-03, habitat, started that year. The challenge was a meadow beside the River Wend that people would be tempted to call recovered before anyone had a first record. What we did was the habitat and biodiversity survey inside April to September, then the monitoring visits the three-year instruction required. The outcome we state is that the baseline and the monitoring record were produced under the council's instruction. We do not state that the restoration succeeded, that flood behaviour changed, or that a species target was met. No such target is part of the published fee.</p>
