<h3 class="wp-block-heading ss-h3">Hollin village wells, 2024</h3>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">In 2024 the parish council at Hollin instructed a groundwater quality programme for 5 village wells. The site is GW-07, groundwater, on the ledger from 2024. The challenge was a local question about the wells without a standing set of readings the council could compare over a year. What we did was place the five wells on monitoring: 4 rounds a year, at $6,600 for the site. A water sampling round covers up to 6 points, so five wells fit one round. Results are due in 15 working days and are filed against GW-07. The outcome we state is that the programme was instructed and that the rounds are how a year of readings is built. We do not state that the water is safe to drink.</p>
