<h2 class="wp-block-heading has-text-align-center ss-h2">How four rounds a year work</h2>
<!-- /wp:heading --></div>
<!-- /wp:group --><!-- wp:group {"className":"ss-inner__text","align":"wide","layout":{"type":"constrained","contentSize":"760px","wideSize":"1200px"}} -->
<div class="wp-block-group alignwide ss-inner__text"><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Four rounds a year means a return each quarter under one instruction, not four separate sales. The fee is $6,600 for the site. Before the first round we agree the medium and the points. On a water instruction the round covers up to 6 points, which is how five Hollin wells sit inside GW-07. Field sampling is led by Lucía Ferreira. Laboratory quality assurance sits with Noah Bakker before a result is released, within the 15 working days. Henrik Aalto files the round to the code. At the end of a programme year you hold four reports that can be read together. The next round is not predicted by the last one. Comparison is the point of going back.</p>
