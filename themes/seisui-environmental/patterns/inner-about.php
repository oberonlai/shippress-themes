<h2 class="wp-block-heading has-text-align-center ss-h2">How we work</h2>
<!-- /wp:heading --></div>
<!-- /wp:group --><!-- wp:group {"className":"ss-cols3 sp-stagger","align":"wide","layout":{"type":"constrained","contentSize":"1200px","wideSize":"1200px"}} -->
<div class="wp-block-group alignwide ss-cols3 sp-stagger"><!-- wp:group {"className":"ss-cols3__item sp-reveal sp-reveal--up","layout":{"type":"default"}} -->
<div class="wp-block-group ss-cols3__item sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"ss-h3"} -->
<h3 class="wp-block-heading ss-h3">Know the water first</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The working order is the one on the front page: know the water, then shape the land. A bank, a lot or a meadow waits until someone has actually read it. The scoping call that starts an instruction is free, lasts 20 minutes, and is held within 2 working days. Desk study and walkover, when that is the next step, follow within 10 working days. Where samples are taken, laboratory results are due in 15 working days. A written report comes after that record, and we sit down for a 45-minute review. The call itself produces a scope, not a finding.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ss-cols3__item sp-reveal sp-reveal--up","layout":{"type":"default"}} -->
<div class="wp-block-group ss-cols3__item sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"ss-h3"} -->
<h3 class="wp-block-heading ss-h3">Write it down and go back</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">A site that matters is a site we return to. The figures we are willing to print are 38 sites, 16 years since 2009, and 4 rounds a year. WR-01 has been on the ledger since 2012. GW-07, the Hollin wells, entered in 2024. The annual monitoring programme that pays for those four visits is $6,600 a year per site. Each round is filed against its code and written up. The 45-minute meeting is where the report is walked through. Memory here is the file. A conversation at the water's edge is not a substitute for the row on the ledger.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ss-cols3__item sp-reveal sp-reveal--up","layout":{"type":"default"}} -->
<div class="wp-block-group ss-cols3__item sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"ss-h3"} -->
<h3 class="wp-block-heading ss-h3">The same fees for every client</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Every fee is in USD, on one list, for a landowner or a council. A site walkover and desk study is $1,850. A Phase I environmental site assessment is $3,400. A water quality sampling round, up to 6 points, is $2,250. A habitat and biodiversity survey is $4,200. Phase II soil investigation is from $8,900. An annual monitoring programme, 4 rounds per site, is $6,600 a year. Half the fee is due on instruction and half when the report is issued. Laboratory courier beyond 60 km, and tax, are excluded. We do not keep a second price list for municipal work.</p>
