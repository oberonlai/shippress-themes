<p class="ss-body">Seisui Environmental opened in 2009 at 14 Millrace Lane, Alder Bridge, a river town on the River Wend. Dr Ilse Varga, a hydrologist, started the practice so landowners and municipal clients could see what the water and the soil were doing before a bank, a field or a building plot was changed.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The first work was desk study, site walkover and sampling, written up from the same office that still keeps sample cool boxes by the door. The monitoring ledger grew with the river and the ground around it: Wend River, Mill Weir has been on the round since 2012 and Wend River, Ferry Steps since 2015.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Sixteen years on, the practice monitors 38 sites for councils and private landowners, at the standing rhythm of four rounds a year. The office is open Monday to Friday, 08:30 to 17:30, with field days by arrangement and the door shut at weekends and on public holidays.</p>
