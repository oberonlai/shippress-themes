<h3 class="wp-block-heading ss-drow__h">2012 to 2019, the first codes</h3>
<!-- /wp:heading -->

<!-- wp:group {"className":"ss-drow__body","layout":{"type":"default"}} -->
<div class="wp-block-group ss-drow__body"><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Named sites, not loose visits, are what the middle years added. In 2012 surface-water sampling began on the Wend River at Mill Weir, coded WR-01. In 2015 the Wend River at Ferry Steps, WR-04, was added to the river record. In 2018 the Alder Bridge mill pond, PD-05, joined as surface water. In 2019 the Copse Farm borehole, GW-09, entered the groundwater list. Those years are start dates on the ledger. They are not a claim that the water met any private target, because no such target is published here. The codes remain so a later round can be set beside the first.</p>
