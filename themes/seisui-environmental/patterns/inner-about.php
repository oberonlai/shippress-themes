<!-- /wp:heading -->

<!-- wp:group {"className":"ss-drow__body","layout":{"type":"default"}} -->
<div class="wp-block-group ss-drow__body"><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The recent years are also specific instructions. In 2021 Alder Bridge council commissioned a floodplain meadow baseline at Wend Meadow, WM-03, together with 3-year monitoring. In 2022 Station yard, SL-06, joined the soil list. In 2023 a private landowner instructed Phase I and Phase II on the former tannery lot at Fennick Road before resale, coded SL-02. In 2024 the parish council at Hollin instructed a groundwater quality programme for 5 village wells, GW-07. The practice that holds these files is the same one opened in 2009. Across the full list we monitor 38 sites.</p>
