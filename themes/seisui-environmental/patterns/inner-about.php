<h3 class="wp-block-heading ss-drow__h">2009, on Millrace Lane</h3>
<!-- /wp:heading -->

<!-- wp:group {"className":"ss-drow__body","layout":{"type":"default"}} -->
<div class="wp-block-group ss-drow__body"><!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">In 2009 Dr Ilse Varga founded Seisui Environmental at 14 Millrace Lane, Alder Bridge, the river town on the River Wend. The office and the sample store have stayed at that address. The work was set then and has not been restated as a slogan shop: walk the ground, sample the water, and write down what was found before anyone reshapes the land. Sixteen years later the ledger holds 38 monitored sites, visited on a programme of 4 rounds a year. The same door still opens on weekdays, and field days are still arranged rather than improvised.</p>
