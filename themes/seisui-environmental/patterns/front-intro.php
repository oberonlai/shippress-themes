<p class="ss-body">Seisui Environmental is an environmental consultancy for landowners and municipal clients, based at 14 Millrace Lane in Alder Bridge on the River Wend. From that office we plan walkovers, water and soil sampling, and habitat surveys, then write down what the visit and the laboratory actually show. The work stays specific to the site in front of us: a reach, a well, a meadow or a lot.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">A brief might be a desk study and walkover before anyone breaks ground, a Phase I when land is about to change hands, or a water-quality round at up to six points. It might be a habitat and biodiversity survey between April and September, a Phase II soil investigation, or an annual programme of four rounds on one site. Each monitored place keeps a code, a medium and the year it joined the ledger, so a later round can be read against the earlier one.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The practice was founded in 2009. Sixteen years later it monitors 38 sites, and the standing rhythm on those sites is four rounds a year. Dr Ilse Varga leads the hydrology, with soil and contamination, ecology, field sampling, GIS, permitting and laboratory QA beside her. The office is open Monday to Friday, 08:30 to 17:30. Field days are by arrangement, and the office is closed at weekends and on public holidays.</p>
