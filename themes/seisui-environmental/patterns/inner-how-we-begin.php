<h2 class="wp-block-heading has-text-align-center ss-h2">Questions people ask</h2>
<!-- /wp:heading --></div>
<!-- /wp:group --><!-- wp:group {"className":"ss-faq","align":"wide","layout":{"type":"constrained","contentSize":"760px","wideSize":"1200px"}} -->
<div class="wp-block-group alignwide ss-faq"><!-- wp:details {"className":"ss-faq__item"} -->
<details class="wp-block-details ss-faq__item"><summary>What does the scoping call cost, and when can we hold it?</summary><!-- wp:paragraph -->
<p>The scoping call costs nothing. It is the published first step, it lasts 20 minutes, and we hold it within 2 working days of a request that reaches us in office hours. Office hours are Mon–Fri 08:30–17:30 at 14 Millrace Lane, Alder Bridge. Telephone +1 555 0142 300 or email hello@seisui-environmental.example. Use the time to name the site and the decision, not to collect a finding. We will tell you which of the six USD fees applies, and whether the next action is a desk study, sampling, a habitat survey or a monitoring year. The 50% on instruction is not asked for on this call. It is asked for when you instruct the priced work.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ss-faq__item"} -->
<details class="wp-block-details ss-faq__item"><summary>Can we start with a walkover instead of Phase II?</summary><!-- wp:paragraph -->
<p>Yes. The site walkover and desk study is $1,850 and is completed within 10 working days. It is the right start when the lot, the bank or the field margin has not been read yet. Phase II, from $8,900, comes after a desk study or a Phase I assessment has shown that the soil should be opened. Phase I itself is $3,400 and does not drill. On the former tannery lot at Fennick Road, the private landowner in 2023 used Phase I and then Phase II before resale, which is the long path, not the compulsory first day. The scoping call is where we say which of those you actually need. Starting at Phase II without that reading is not how these steps are written.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ss-faq__item"} -->
<details class="wp-block-details ss-faq__item"><summary>When do laboratory results come back?</summary><!-- wp:paragraph -->
<p>Laboratory results are due in 15 working days after sampling. That timing belongs to step 03, sampling and laboratory. It covers a water quality round of up to 6 points, priced at $2,250, and Phase II soil work where sampling was part of the agreed scope, priced from $8,900. Noah Bakker checks quality assurance before the numbers are written into the report you review. The 15 working days are not a promise about the habitat survey, which is seasonal field ecology at $4,200 and is not described as a laboratory product. Courier beyond 60 km is outside the fee. If that distance applies, you hear about it before the samples travel, not after the invoice for the report.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ss-faq__item"} -->
<details class="wp-block-details ss-faq__item"><summary>How do you describe the outcome of a finished instruction?</summary><!-- wp:paragraph -->
<p>We describe the work that was done. On Wend Meadow we say that Alder Bridge council's 2021 baseline and 3-year monitoring were carried out and reported, site WM-03. On Fennick Road we say that Phase I and Phase II for the private landowner in 2023 were completed before resale, site SL-02. On the Hollin wells we say that the parish council's 2024 groundwater programme for 5 wells was instructed, site GW-07, at 4 rounds a year. We do not add that a meadow recovered, that a lot was clear of its industrial past, or that well water is safe to drink. Those sentences are not in the fees, and they are not in the reports as promises. The 45-minute meeting is for the pages we did write.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ss-faq__item"} -->
<details class="wp-block-details ss-faq__item"><summary>When is the office open, and how is the fee paid?</summary><!-- wp:paragraph -->
<p>The office and sample store are at 14 Millrace Lane, Alder Bridge, on the River Wend. Hours are Mon–Fri 08:30–17:30. Field days are by arrangement. Weekends and public holidays are closed. Reach us on +1 555 0142 300 or at hello@seisui-environmental.example. Fees are in USD. You pay 50% on instruction and 50% when the report is issued. The published prices exclude laboratory courier beyond 60 km and tax. The six amounts are $1,850, $3,400, $2,250, $4,200, from $8,900, and $6,600 a year per site. A monitoring year is four rounds, not an open-ended retainer. If a further instruction is needed after the review meeting, it is scoped and priced again from that same list.</p>
