<p class="ss-body">The third step is sampling and the laboratory. Results are due in 15 working days. A water quality round covers up to 6 points at $2,250. Phase II soil investigation, once earlier work has shown that the ground should be opened, is priced from $8,900 and agreed before sampling starts. Noah Bakker's laboratory quality assurance checks that the points and the containers match the scope before a result is released. Laboratory courier beyond 60 km is excluded, and so is tax. Habitat fieldwork, when that is the instruction instead, is the $4,200 survey in April to September and is scoped as ecology, not pushed through a laboratory step it was not given.</p>
