<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The second step is a desk study and walkover, within 10 working days. When this step is the whole instruction, the fee is $1,850. We read the records, then walk the ground: access, water, the soil surface, and past use as far as it shows. You are welcome to walk with the team. Field days are by arrangement inside the working week. The office is open Mon–Fri 08:30–17:30 and closed on weekends and public holidays. The walkover is often what justifies Phase I at $3,400, a water round, or no further work. The product is a written account of the visit. It is not a permission to build or to sell.</p>
