<div class="wp-block-group ss-cols3__item sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"ss-h3"} -->
<h3 class="wp-block-heading ss-h3">What the fee includes</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Each fee covers the work named in its row. That is the desk study and walkover, the Phase I assessment, the sampling round of up to 6 points, the habitat survey, the Phase II investigation as scoped, or the four monitoring visits at one site. It covers the written report and the 45-minute review meeting. Where the instruction includes sampling, laboratory results are due in 15 working days. The monitoring fee is for one site. A second site is a second fee of $6,600 a year. The habitat survey at $4,200 is one seasonal survey, from April to September. It is not, by itself, a year of quarterly habitat rounds. Those rounds are the annual programme if you instruct them.</p>
