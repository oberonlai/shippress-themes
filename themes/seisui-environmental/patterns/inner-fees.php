<h3 class="wp-block-heading ss-h3">Payment, courier and tax</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">Payment terms are 50% on instruction and 50% on the report. Invoices are in USD. All prices exclude laboratory courier beyond 60 km and tax. If samples must travel further than 60 km, that courier is stated before the round, as an amount outside the published fee. The office, and the week we invoice against, runs Mon–Fri 08:30–17:30. Field days are by arrangement. Weekends and public holidays are closed. Nothing on this page is a retainer for unlimited calls after the report, and the review included in the fee is the 45-minute meeting. A further instruction, if the report shows one is justified, is a new row from the same six, scoped again before it is started.</p>
