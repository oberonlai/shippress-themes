<h3 class="wp-block-heading ss-h3">Six published fees</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">The price list has six rows, in USD, identical with the fees shown elsewhere on this site. Site walkover and desk study: $1,850. Phase I environmental site assessment: $3,400. Water quality sampling round, up to 6 points: $2,250. Habitat and biodiversity survey: $4,200. Phase II soil investigation: from $8,900. Annual monitoring programme, 4 rounds, per site: $6,600 a year. Phase II is the only fee written as from, because the figure for that site is agreed before the ground is opened. The other five are the amounts published. A scoping call to see which row applies is free, lasts 20 minutes, and is offered within 2 working days. Councils and landowners use this list.</p>
