<p class="ss-body">Phase I environmental site assessment is $3,400. It covers the history of the site and the condition found on the ground, and it asks whether contamination may need a closer look. It does not open the soil. The former tannery lot at Fennick Road, instructed by a private landowner in 2023 before resale, went through Phase I and then Phase II, and is held on the ledger as SL-02. Where the history and the walk justify opening the ground, the next fee is Phase II, from $8,900. The Phase I product is a written report, reviewed with you for 45 minutes. It states what the record supports.</p>
