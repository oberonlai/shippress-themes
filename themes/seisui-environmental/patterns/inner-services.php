<p class="ss-body">A water quality sampling round costs $2,250 and covers up to 6 points. Points may lie on the River Wend, on a still water such as the Alder Bridge mill pond, or on wells. The field team takes the samples, and laboratory results are due in 15 working days. One round is a single return. A year of comparable visits is a different instruction: the annual monitoring programme, 4 rounds at one site, at $6,600 a year. The round fee excludes laboratory courier beyond 60 km, and it excludes tax. A set of points larger than six is a different scope, agreed before anyone travels, and it is not folded into the $2,250.</p>
