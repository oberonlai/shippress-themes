<h3 class="wp-block-heading ss-h3">Site walkover and desk study</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"ss-body"} -->
<p class="ss-body">A site walkover and desk study is the shortest full instruction we publish, at $1,850. We read the available records, then walk the plot: access, the edge of any water, the soil surface, and the obvious past use. It is scheduled within 10 working days, which is step 02 of the way an assessment begins. You receive a written account of what was seen and which next step, if any, is justified — a Phase I assessment, a sampling round, a habitat survey, or a stop. Many landowners come out on the walk. The note is a record of that visit. It is not a clearance to build, sell or plant.</p>
