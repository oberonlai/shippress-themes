<p class="ss-card__body">Amara Okonkwo leads the ecology. She writes the species and the habitats that were seen on the visit, in the April to September window, and she leaves the unvisited months blank. The 2021 Wend Meadow instruction was a baseline plus monitoring for three years, for Alder Bridge council. The outcome we will put in a sentence is that those surveys were instructed and reported. A planting of willows, or a season of wildflowers, is described if it was on the ground. It is not upgraded into a claim that restoration worked. Where you need four returns inside one monitoring year, that is the annual programme at $6,600 for the site, alongside the survey rather than instead of a clear scope.</p>
