<!-- wp:paragraph {"className":"ss-card__body"} -->
<p class="ss-card__body">Habitat and biodiversity fieldwork runs from April to September. Outside that season we do not treat a vegetation list as complete. Preparation and the reading of earlier notes can happen in the colder months. The survey itself is one fee of $4,200, covering the seasonal field visit and the written record. Wend Meadow, WM-03, is the habitat site on the ledger. Alder Bridge council instructed it in 2021 as a floodplain meadow restoration baseline, with 3-year monitoring. A baseline says what was growing on the visits. Later monitoring says what was there when we returned. Neither is a forecast of the meadow, and no recovery score is attached to the fee.</p>
