<p class="ss-card__name">Walk, quadrat and baseline</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"ss-card__body"} -->
<p class="ss-card__body">The survey is three pieces of work under the single fee of $4,200, which is how the three cards on this page should be read. The habitat walk records the day itself: reed-bed, meadow, hedgerow, bare ground. The measured plot uses a quadrat and a tape so cover is counted. The written baseline is the report you can put with a council file or a land file, then talk through in the 45-minute review. We do not split the survey into three invoices. If the real question is water quality, that is a sampling round at $2,250 for up to 6 points. If it is contamination history, Phase I is $3,400. We would rather say so at the scoping call than stretch this fee.</p>
