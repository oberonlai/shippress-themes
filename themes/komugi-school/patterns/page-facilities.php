<div class="wp-block-group ks-sub"><!-- wp:heading {"className":"ks-sub__h"} -->
<h2 class="wp-block-heading ks-sub__h">Hearth Baking: Deck and Rack Oven Capacity</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ks-sub__b","layout":{"type":"default"}} -->
<div class="wp-block-group ks-sub__b"><!-- wp:paragraph -->
<p>The heart of our baking floor consists of three commercial four-deck ovens and one rotating rack oven. The four-deck stone hearth ovens deliver continuous high-temperature heat distribution with independent digital steam injection across every deck, allowing students to bake crusty levain loaves under precise vapor saturation. The single rack oven provides convection airflow control for consistent baking of viennoiserie, brioche, and enriched pastries on multi-tier bakery racks. Students learn to load, steam, vent, and unload both oven types daily, mastering peel ergonomics and heat management under authentic commercial bakery pressures.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ks-sub","layout":{"type":"default"}} -->
<div class="wp-block-group ks-sub"><!-- wp:heading {"className":"ks-sub__h"} -->
<h2 class="wp-block-heading ks-sub__h">Mixing, Sheeting, and Climate-Controlled Proofing</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ks-sub__b","layout":{"type":"default"}} -->
<div class="wp-block-group ks-sub__b"><!-- wp:paragraph -->
<p>Dough development relies on four commercial spiral mixers of varying capacities, allowing students to mix small test batches as well as large bulk production doughs without shear stress. A heavy-duty reversible dough sheeter ensures precise, uniform butter lamination down to millimeter tolerances for laminated pastry doughs. The bakery houses a walk-in retarder-prover room maintaining exact humidity and temperature calibration between two and twenty-six degrees Celsius. This climate-controlled facility allows students to study delayed fermentation kinetics and run reliable overnight cold proofs on sourdough bâtards and shaped croissants.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ks-sub","layout":{"type":"default"}} -->
<div class="wp-block-group ks-sub"><!-- wp:heading {"className":"ks-sub__h"} -->
<h2 class="wp-block-heading ks-sub__h">Student Workstations, Stone Benches, and Hand Tools</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ks-sub__b","layout":{"type":"default"}} -->
<div class="wp-block-group ks-sub__b"><!-- wp:paragraph -->
<p>Our spacious training floor provides twelve dedicated student bench stations surfaced in solid marble and thick beech wood. Each station is equipped with an individual digital scale, professional dough scrapers, rolling pins, linen proofing couches, and German spruce pulp bannetons. The storeroom maintains organized grain bins and unprinted sacks of regional stone-ground flours, rye, and ancient grains. By limiting cohorts to twelve bakers, every student retains uninterrupted access to their own station, sink, and mixer throughout the daily 06:00 to 14:00 teaching shift.</p>
