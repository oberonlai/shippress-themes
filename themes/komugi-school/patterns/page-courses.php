<div class="wp-block-group ks-sub__b"><!-- wp:paragraph -->
<p>We offer two distinct five-day intensive courses for specialized craft mastery. Viennoiserie Week, priced at €980, explores laminated dough production, covering butter plasticity, lamination turns, mechanical sheeting, and proofing control for croissants, pain au chocolat, and brioche. Sourdough Week, priced at €920, focuses entirely on natural levain systems, wild yeast propagation, lactic versus acetic fermentation balances, and stone-ground flour hydration. Both five-day modules run full-time from 06:00 to 14:00, giving students immersive hands-on repetition on commercial bakery equipment.</p>
