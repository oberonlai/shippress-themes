<!-- wp:group {"className":"ks-sec ks-faq","layout":{"type":"default"},"tagName":"section"} -->
<section class="wp-block-group ks-sec ks-faq"><!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>What prior baking experience is required to apply?</summary>

<!-- wp:paragraph -->
<p>We do not require prior commercial bakery experience to apply for the Professional Bread &amp; Pastry programme or our short courses. Our syllabus begins with fundamental grain chemistry, manual dough handling, and baker's percentages, making the instruction accessible to career switchers, cooks, and dedicated home bakers. What we look for in applicants is physical stamina, a calm temperament, attentiveness to detail, and a genuine readiness to work disciplined early morning hours from 06:00 to 14:00 at the bench.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>How many students are accepted into each training cohort?</summary>

<!-- wp:paragraph -->
<p>Each six-week cohort is strictly capped at twelve students. Limiting class size ensures that every student has their own dedicated marble or wood bench station, personal hand tools, and unrestricted daily access to our deck ovens and spiral mixers. Senior instructors work side by side with students throughout the morning, providing direct feedback on dough development, shaping tension, and bake profiles that would be impossible in larger class environments.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>What is included in the course tuition fee?</summary>

<!-- wp:paragraph -->
<p>The tuition fee covers all organic flours, butter, dairy, and bakery ingredients consumed throughout the course. Each student also receives a durable linen apron, a professional knife roll outfitted with a curved lame, bench scrapers, and a digital thermometer, alongside the bound Komugi bench book. Tuition also covers the full supervision of the two-week partner kitchen placement following graduation. All listed course fees are stated in euros and include value added tax.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>Are the two-week kitchen placements paid or linked to permanent positions?</summary>

<!-- wp:paragraph -->
<p>The two-week placements in weeks seven and eight are unpaid educational assignments structured to provide real commercial kitchen experience. Students work alongside professional teams at partner bakeries including Maasbrood, Atelier Korenbloem, North Pier Bakehouse, and Kade Patisserie. While Komugi School does not promise employment or extend hiring commitments, placements offer students invaluable professional references, commercial speed calibration, and direct industry contacts that frequently lead to career opportunities.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>What are the start dates for upcoming cohorts?</summary>

<!-- wp:paragraph -->
<p>We operate five six-week cohorts annually. For the 2027 calendar year, cohorts begin on 12 January, 9 March, 4 May, 7 September, and 2 November. Our next upcoming cohort commences on 12 January 2027. Because cohort capacity is strictly limited to twelve seats, we encourage prospective students to submit their applications at least two to three months prior to their desired term.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>How does the four-stage admissions process work?</summary>

<!-- wp:paragraph -->
<p>The admissions process comprises four distinct steps. First, prospective students submit an online application outlining their background and career goals. Second, candidates attend a Saturday open bench morning to meet our faculty and tour the bakery. Third, successful applicants receive a formal written offer within ten days of their visit. Fourth, the student confirms enrollment by paying a fifty percent deposit, with the remaining balance due prior to the start of instruction.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>Are bursary places available for students in need of financial assistance?</summary>

<!-- wp:paragraph -->
<p>Yes. We offer two part-fee bursary places for every six-week Professional Bread &amp; Pastry cohort. These bursaries are intended to assist dedicated candidates who demonstrate high craft commitment but face documented financial constraints. Applicants interested in being considered for a bursary place should indicate this on their initial application form. Bursary decisions are reviewed by our admissions panel and communicated alongside standard admission offers.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>What commercial equipment will students learn to operate?</summary>

<!-- wp:paragraph -->
<p>Students train on authentic professional production equipment at our Hallstraat 14 bakery. Our facilities include three four-deck stone hearth ovens with independent digital steam controls, one rotating rack oven, four spiral mixers of varying capacity, a commercial reversible dough sheeter, and a walk-in retarder-prover room. Every student learns manual peel loading, steam timing, and routine oven maintenance during their daily production shifts.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>How can prospective students visit the school before applying?</summary>

<!-- wp:paragraph -->
<p>Prospective applicants can attend our open bench mornings held every Saturday from 09:00 to 12:00. These three-hour visits cost €45 and are limited to eight participants to ensure meaningful conversation with faculty. Visitors tour the bakery, observe our baking equipment, inspect dough fermentation stages, and ask detailed questions about the curriculum. Attending an open bench morning satisfies the second stage of our admissions evaluation.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq__item"} -->
<details class="wp-block-details ks-faq__item"><summary>What is the deposit policy upon receiving an offer?</summary>

<!-- wp:paragraph -->
<p>Upon receiving a written offer of admission, applicants must submit a fifty percent deposit within ten days to secure their place in the cohort. The remaining balance must be paid in full prior to the first day of class. Because each cohort is limited to twelve students, deposits ensure committed enrollment and allow us to allocate bench stations, personal tool rolls, and raw materials accurately.</p>
<!-- /wp:paragraph -->
</details>
