<!-- wp:heading {"level":3,"className":"nw-h3"} -->
<h3 class="wp-block-heading nw-h3">Why do we avoid synthetic coatings on heavy canvas trousers?</h3>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-qa__a","layout":{"type":"default"}} -->
<div class="wp-block-group nw-qa__a"><!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Synthetic waterproof coatings trap sweat against the skin and peel away when scraped against rough brick, metal, or wood. Our cotton duck canvas relies on a dense, heavy 12 oz weave that stops wind naturally while allowing moisture to escape during intense physical labor. When canvas does tear from a sharp nail or sharp tool edge, it can be patched flat with matching cotton cloth on our repair machines. Coated synthetic fabrics melt under friction and cannot be mended as cleanly or securely, which shortens the working lifespan of the trousers.</p>
