<h3 class="wp-block-heading nw-h3">How we choose a cloth</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Selecting work cloth requires understanding how fibers behave when dragged across rough decking, soaked with engine oil, or rubbed against heavy timber. Hana Kowalczyk manages our fabrics and sourcing, finding mills that produce tight, dense weaves with consistent tensile strength. We avoid synthetic blends where pure cotton duck performs better, because natural canvas holds its structural integrity under repeated laundering and friction. When synthetic fibers are necessary for stretch or stain resistance, as in our poly-cotton coveralls and 3-layer soft-shell jackets, we choose weaves that can still be patched on our workshop sewing machines without puckering.</p>
