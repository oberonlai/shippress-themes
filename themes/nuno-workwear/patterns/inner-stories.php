<p class="nw-body">The Westpark Grounds Team consists of 9 groundskeepers responsible for maintaining public parks, clipping perimeter hedges, and tending wet turf through winter rain. They required weather-resistant jackets that would shed heavy rain without the clammy heat buildup typical of synthetic rainwear. We fitted the entire crew of 9 workers in our waxed field jackets, made from 8 oz waxed cotton with paraffin finish. To maintain water resistance against brambles and thorns, the team brings all 9 jackets back to our Rotterdam workshop every autumn for re-proofing at €32 per jacket. Tomasz Wilk and his team complete the wax application in 5 working days, returning the garments clean and weatherproofed.</p>
