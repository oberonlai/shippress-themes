<p class="nw-crew__meta">twelve sets of canvas and wax</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Vos Joinery is a timber workshop employing 12 joiners who spend their shifts framing, sawing, and hauling heavy beams. Their team needed trousers that could survive continuous friction against rough sawn oak and jagged sawhorse edges without splitting at the knees. We conducted 2 fittings at their workshop to establish individual waist sizes and leg lengths between 30 and 36 inches. We outfitted all 12 craftsmen in our double-knee canvas trousers in 12 oz cotton duck, paired with waxed field jackets for outdoor transport. Their complete crew order was delivered in 10 working days. After eighteen months of daily sawing and joinery work, three pairs returned to Kadeweg 18 with pocket seam wear, which Tomasz Wilk reinforced within 3 working days.</p>
