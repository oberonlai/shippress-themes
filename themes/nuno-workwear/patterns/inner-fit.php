<h2 class="wp-block-heading nw-h2">HOW TO MEASURE</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-hs__r","layout":{"type":"default"}} -->
<div class="wp-block-group nw-hs__r"><!-- wp:paragraph {"className":"nw-lead"} -->
<p class="nw-lead">How to measure chest, waist, and inseam</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-meas__list","layout":{"type":"default"}} -->
<div class="wp-block-group nw-meas__list"><!-- wp:group {"className":"nw-meas","layout":{"type":"default"}} -->
<div class="wp-block-group nw-meas"><!-- wp:paragraph {"className":"nw-step__no"} -->
<p class="nw-step__no">01</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">To measure chest circumference, wrap a tape measure under the armpits around the fullest part of your chest while standing upright and breathing normally.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-meas","layout":{"type":"default"}} -->
<div class="wp-block-group nw-meas"><!-- wp:paragraph {"className":"nw-step__no"} -->
<p class="nw-step__no">02</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">For waist measurements, measure around your natural waistline where your work trousers sit, keeping one finger between your body and the tape to allow ease of movement.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-meas","layout":{"type":"default"}} -->
<div class="wp-block-group nw-meas"><!-- wp:paragraph {"className":"nw-step__no"} -->
<p class="nw-step__no">03</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">For inseam length, measure along the inside leg from the crotch down to the ankle bone, taking into account the heel height of your work boots.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"nw-meas","layout":{"type":"default"}} -->
<div class="wp-block-group nw-meas"><!-- wp:paragraph {"className":"nw-step__no"} -->
<p class="nw-step__no">04</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Remember that heavy canvas trousers do not stretch like leisure denim, so always choose the larger size if your measurements fall between standard sizes.</p>
