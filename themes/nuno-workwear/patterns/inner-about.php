<!-- wp:heading {"level":2,"className":"nw-h2"} -->
<h2 class="wp-block-heading nw-h2">THE WORKSHOP</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Our workshop at Kadeweg 18 is an active, open production space where sewing machines run alongside customer fitting areas. Rather than hiding our repair operations behind closed doors, our benches sit directly in view of the shop floor. When a carpenter visits to replace worn trousers, they can see jackets being waxed by hand and boots being re-soled on the last. Keeping repairs and sales together ensures our designs remain grounded in practical utility, because every seam failure and fabric tear is inspected by the people who craft our patterns.</p>
