<!-- wp:heading {"level":3,"className":"nw-h3"} -->
<h3 class="wp-block-heading nw-h3">Why do we keep our sales counter and repair workshop in the same space?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"nw-body"} -->
<p class="nw-body">Keeping sales and repair in a shared space maintains direct accountability between the clothing we supply and the punishment it receives on real job sites. When a fitter pins trousers for a new apprentice, our repair lead Tomasz Wilk is working only paces away. This immediate connection allows us to spot common wear patterns, test stronger thread tensions, and adjust garment specifications based on actual trade feedback. It also means customers can drop off torn jackets for repair while picking up new trousers before their morning shift starts.</p>
