<p class="nw-body">Ines Navarro established Nuno Workwear in 2009, initially opening as a modest repair counter at Rijnhaven Works, Unit 4, Kadeweg 18 in Rotterdam. Seeing tradespeople struggle with poorly sewn workwear that tore after a few weeks, Ines focused on repairing canvas trousers, reinforcing seams, and fixing broken hardware. In 2014, we expanded beyond repairs by introducing our own catalogue of six core trade garments, built according to patterns refined on the repair bench. In 2021, we added our dedicated embroidery room to provide in-house company branding and name stitching, allowing us to manage every stage of crew outfitting under our own roof.</p>
