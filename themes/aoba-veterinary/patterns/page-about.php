<section class="wp-block-group alignfull av-section av-page"><!-- wp:paragraph {"className":"av-lead"} -->
<p class="av-lead">Aoba Veterinary Clinic was founded in 2014 by Dr. Elena Varga at 214 Alder Street, Fairhaven, after twelve years in a city referral hospital.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small av-long--first"} -->
<h2 class="wp-block-heading av-long av-long--small av-long--first">Opened in 2014</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dr. Elena Varga opened Aoba Veterinary Clinic in 2014 after twelve years in a city referral hospital. She chose a street-level practice in Fairhaven, and the address has stayed 214 Alder Street. The work is general practice for dogs and cats, with surgery and dentistry in the same building, led by a director whose own field is internal medicine.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A smaller clinic was the point. The first conversation with an owner can last long enough to hear the real history, and the people who do the surgery, the dentistry and the nursing are colleagues on the same corridor, not a distant department. Fairhaven has been the setting since that opening year. The phone is +1 555 0142 300 and the desk email is hello@aobavet.example.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Dogs and cats</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Aoba Veterinary Clinic sees dogs and cats only. The waiting rooms, the handling and the way the day is timed are built for those two, because that is the medicine the team practises every day. Cats have a room of their own, so a carrier is not set down in the middle of dogs. Dogs are examined, admitted and discharged on a path that leaves the cat room quiet.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Stock, equipment and appointment length follow the same choice. Dr. Varga brought that focus from twelve years of referral work into a general practice she could keep personal. If you share your home with a dog or a cat in Fairhaven, this is the clinic that was arranged for that animal.</p>
<!-- /wp:paragraph -->

