<!-- wp:heading {"className":"av-long av-long--small av-long--first"} -->
<h2 class="wp-block-heading av-long av-long--small av-long--first">Thirty-minute first consultations</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A first consultation is 30 minutes and the fee is $65. The length is deliberate. It covers a full examination, time to hear how the problem started, and time to explain what we find in ordinary language. Treatment is not started in the same breath as the diagnosis. You receive a written estimate first, and prices on the published list include tax.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A follow-up consultation is 15 minutes at $45, which is enough to judge whether a plan is working. The longer first visit is how a small clinic takes the time to listen. It is also why we ask you to book, rather than hoping to be seen between other animals. Urgent same-day slots still exist on weekdays, and they are arranged by phone.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Time, clarity and calm</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Time is the first value. The 30-minute first consultation, and the 15-minute follow-up, exist so the history and the examination are done properly and the plan is explained before anyone is asked to agree. Clarity is the second. We show you what we find, and we write the estimate before treatment. The fee list is public, from the $65 first consultation to a dental scale and polish under anaesthesia from $320. You should be able to read what a visit may cost before you are at the desk.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Calm is the third. Dogs and cats wait apart. Handling stays as gentle as a proper examination allows. Within 48 hours of a visit, a nurse calls. If you were unsure whether to come, a nurse will tell you on the phone whether it can wait.</p>
<!-- /wp:paragraph -->

