<p class="av-lead">Surgery and dental care are planned with a written estimate, monitored anaesthesia, pain relief, and a discharge call after you get home.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small av-long--first"} -->
<h2 class="wp-block-heading av-long av-long--small av-long--first">Before the day</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Planned surgery and dental work start with an examination and a written estimate, before a date is kept. The estimate names the procedure, the anaesthetic and monitoring, pain relief, and the fee. You have it before treatment is booked. Fasting rules are given for that animal at that booking. We tell you when food should stop and whether a drink of water is still right. There is no single fasting time printed for every dog and cat, because the instruction depends on the patient and the procedure.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Cat spay or neuter starts from $240. Dog spay or neuter starts from $380. A dental scale and polish under anaesthesia starts from $320. Orthopaedic work, such as a cruciate ligament repair, is estimated individually because it is not one of the eight published lines. Prices include tax.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Surgery day</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>On the day, you arrive at the time Clara Moreau or a nurse has given you, with the fasting instructions already followed. A nurse settles your dog or cat. In surgery, Dr. Samuel Osei leads orthopaedic and soft-tissue work. Dental procedures and imaging sit with Dr. Tomás Ribeiro.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A nurse stays with the anaesthetic throughout, watching heart rate, breathing and temperature. We tell you afterwards how that anaesthetic went. Your animal then rests on a soft blanket in a recovery kennel until it is sensible to travel. You are welcome to call the clinic on +1 555 0142 300 if the morning raises a question. The team would rather hear it then than have you guess. Discharge happens only when your animal is ready to leave the building safely.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Dental care</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dental scale and polish is done under anaesthesia, not in a quick conscious scrape. The published fee starts from $320, and the written estimate for your animal replaces that starting figure once Dr. Tomás Ribeiro has examined the mouth. He will show you what he finds. Decisions about teeth are made with you on the estimate, before the anaesthetic is booked.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Digital imaging is part of how dentistry is planned here, since dentistry and imaging are his field. Pain relief is on the estimate as well, and it continues as your animal goes home. If the mouth you can see at home looks worse than at the last vaccination, book a consultation first. The $65 first visit, or a $45 follow-up if we have seen your animal recently, is how a dental day is decided.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Home recovery</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Before you leave, a nurse goes through written notes: rest, the medicines prescribed for your animal, food and water, and what should prompt a call. Pain relief is the plan you already agreed, sent home with instructions for that patient. A discharge call checks the first hours after you are back. The clinic’s follow-up call still comes within 48 hours of a visit. Hannah Lindqvist, head veterinary nurse, leads the nursing team that makes those calls. If recovery needs rehabilitation, Malik Haddad writes the plan.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>He did that for Biscuit, a beagle aged 7, after Dr. Osei repaired a cruciate ligament, and Biscuit was on full walks in 10 weeks. That interval belonged to Biscuit. Every animal is different. Call if the wound, the appetite or the comfort is not what the notes led you to expect.</p>
<!-- /wp:paragraph -->

