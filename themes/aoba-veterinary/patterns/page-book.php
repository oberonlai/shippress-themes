<!-- wp:heading {"className":"av-long av-long--small av-long--first"} -->
<h2 class="wp-block-heading av-long av-long--small av-long--first">Email, phone, or call before you come</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There are three ways to arrange a visit. Email hello@aobavet.example with your name, a phone number, the animal’s name, whether they are a dog or a cat, and the reason you want to come. That message is the online request. Or call +1 555 0142 300 during opening hours and book with Clara Moreau or a nurse. The third way is for urgent cases only: call first, then come.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Weekdays keep same-day slots for problems that should not wait. We will tell you to come to 214 Alder Street when a slot is the right step, and we will point you to the regional emergency hospital when it is not. A first consultation is 30 minutes at $65. A follow-up is 15 minutes at $45. We see dogs and cats only.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">What happens after you book</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>After you email or call, the clinic confirms the day, the time, and whether you are booked for 30 minutes or 15. We say what to bring: the vaccination record, a list of food and medicines, and a photo or video of the symptom if you have one. If a procedure is being planned, we give fasting instructions for that animal. You get a written estimate before treatment, so confirmation of an appointment is not by itself permission to start a procedure.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>On the day, cats go to the separate waiting room and dogs are settled away from it. A nurse calls within 48 hours after the visit. If you need to change the time, call the same number, +1 555 0142 300, or write again to hello@aobavet.example. Clara Moreau keeps the book.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Hours</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Monday to Friday: 9:00–12:30 and 15:30–19:00. Saturday: 9:00–12:30 and 15:30–17:00. Saturday afternoon is the shorter session. Sunday and public holidays: closed. Book into an open block. The desk cannot make an appointment in the middle of the day, between 12:30 and 15:30, or on a Sunday.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Out of hours, call the regional emergency hospital for a true emergency. When we are open, the filled booking route is this one: phone +1 555 0142 300 or email hello@aobavet.example. The clinic is at 214 Alder Street, Fairhaven, with 6 parking spaces. Aoba Veterinary Clinic has used these hours, this address and this fee list since the practice was founded in 2014. Prices include tax, and the estimate still comes before treatment.</p>
<!-- /wp:paragraph -->

<!-- wp:pattern {"slug":"aoba-veterinary/timetable"} /-->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Signs that are worth a visit</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Come in, or at least call, if you are seeing any of these. Not eating for more than a day. Limping that lasts beyond 24 hours. Drinking much more than usual. Repeated vomiting or diarrhoea. Scratching ears or shaking the head. Breathing faster at rest. A cat hiding more than usual.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Lumps that change size. If you are unsure, call us — a nurse will tell you whether it can wait. Urgent same-day slots are there for weekdays. None of these signs diagnoses the cause by itself. They are reasons to let Dr. Elena Varga and her colleagues examine the animal. A quiet change in a cat, such as the weight loss Juniper showed, is as worth a call as a dramatic limp. Bring the video if the sign comes and goes.</p>
<!-- /wp:paragraph -->

