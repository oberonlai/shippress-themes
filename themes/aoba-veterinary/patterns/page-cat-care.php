<!-- wp:heading {"className":"av-long av-long--small av-long--first"} -->
<h2 class="wp-block-heading av-long av-long--small av-long--first">Quiet arrival</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Bring your cat in a secure carrier, with a familiar towel in the base if you have one. Keep the carrier closed on the journey and speak softly. When you reach 214 Alder Street, the reception desk will point you to the cat waiting room rather than leaving you in a mixed hallway. Clara Moreau, reception and care coordinator, or a nurse, meets you there. We book cat visits so the time in the carrier stays close to the appointment you were given.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A first consultation is 30 minutes. A follow-up is 15 minutes. Arriving a few minutes early is enough. If your cat is already worried at home, say so when you book on +1 555 0142 300 and we will keep the arrival as simple as the day allows.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">A separate waiting room</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dogs and cats wait in different rooms. The cat waiting room is arranged for carriers: a place to set them down, a towel if the carrier floor needs one, and pheromone diffusers in the room itself. It is a quiet part of the clinic, away from dogs arriving for their own appointments. That separation is one reason Aoba Veterinary Clinic sees dogs and cats only.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The room can be run for cats because the day is not also trying to serve every other species. You stay with your cat. If the consult room is free, we move you through rather than parking the carrier for a long stretch. The same room is used for a routine vaccination and for a cat who comes back every few months for a long-term condition.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Low-stress handling</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dr. Priya Nair leads feline medicine, and the handling standard is the same whoever is in the room. We use the least restraint that still lets us examine properly. A towel, a quiet voice and an owner who can stay and hold a settled cat are part of the method. If a cat needs a moment before the stethoscope or the ear exam, we take the moment inside the booked time.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Appointments are kept to that booked length so the visit itself stays short. Ears, teeth, weight and heart are still examined. Low-stress handling is not a skipped examination. It is a full examination done in an order the cat can tolerate. Tell us what has helped at other visits, and what has not, when you sit down.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"av-long av-long--small"} -->
<h2 class="wp-block-heading av-long av-long--small">Juniper’s visits</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Juniper is a cat of 12. She came because of weight loss, and Dr. Priya Nair found a thyroid condition. It is managed with daily medication and with checks every 3 months. Those return visits are ordinary days in the cat waiting room: a carrier, a short wait, an examination, and a clear note of what to do until the next check.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Her story is not a promise about another cat with weight loss. Every animal is different. It does show how a long-term feline case is held here, by the same doctor, on a schedule you can put in a diary. If your cat is losing weight, drinking more, or hiding more than usual, book a 30-minute consultation. The fee is $65, and any medicine is written on an estimate first.</p>
<!-- /wp:paragraph -->

