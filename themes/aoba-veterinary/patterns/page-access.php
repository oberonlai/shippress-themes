<h2 class="wp-block-heading av-long av-long--small">Opening hours</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Monday to Friday the clinic is open 9:00–12:30 and 15:30–19:00. Saturday it is open 9:00–12:30 and 15:30–17:00. Saturday afternoon is the shorter session. Sunday and public holidays are closed. We work those two blocks, morning and afternoon, with the middle of the day between them. Appointments are placed inside the open hours.</p>
