<p>Founded in 2012 in Ghent, Kaname Watches operates from a single room with a single glass counter on Klokstraat. We deliberately keep a short list of mechanical watches and will never present more than twelve at any time. Currently, there are five pieces in the shop. Each watch is chosen one by one for its balance, case architecture, and everyday endurance.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every mechanical piece is opened, checked, and timing-tested on Tomasz Wrona's service bench before it is added to the counter tray. We believe a watch should live comfortably on a real wrist rather than sit untouched in a display case. Restricting our collection ensures that every case, dial, and caliber receives our complete, unhurried attention.</p>
