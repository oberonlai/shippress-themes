<!-- wp:heading {"level":2,"className":"kw-h kw-h--q kw-h--left"} -->
<h2 class="wp-block-heading kw-h kw-h--q kw-h--left">DOES IT KEEP GOOD TIME AFTER A WEEK ON TOMASZ'S BENCH?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ilse Verhoeven never adds a watch to our short list based on manufacturer claims alone. Before any piece joins the counter, watchmaker Tomasz Wrona opens the caseback and monitors its movement across multiple positions over seven full days.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The calibre must maintain consistent amplitude, clean beat error, and steady daily rates before we approve it. If an escapement exhibits erratic variance or unstable regulation under observation on the bench, that watch does not join the collection at Klokstraat 12.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
