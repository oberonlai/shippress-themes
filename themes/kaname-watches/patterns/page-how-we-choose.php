<!-- wp:heading {"level":2,"className":"kw-h kw-h--q kw-h--left"} -->
<h2 class="wp-block-heading kw-h kw-h--q kw-h--left">CAN IT BE SERVICED IN TEN YEARS?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We deliberately select mechanical watches designed for enduring ownership and straightforward long-term maintenance. Tomasz inspects whether balance assemblies, mainsprings, reversing wheels, and case gaskets will remain accessible ten years down the road.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Proprietary modules, glued components, or movements lacking accessible spare parts are rejected immediately. A watch that cannot be fully disassembled, cleaned, oiled, and regulated by an independent watchmaker has no place on the counter tray in our Ghent shop.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></section>
<!-- /wp:group -->

