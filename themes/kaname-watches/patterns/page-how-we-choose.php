<!-- wp:heading {"level":2,"className":"kw-h kw-h--q kw-h--left"} -->
<h2 class="wp-block-heading kw-h kw-h--q kw-h--left">DOES IT SIT FLAT ON A 15 CM WRIST?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ergonomic balance matters far more than case diameter figures on paper. Ilse assesses how caseback depth, lug curvature, and strap attachment points settle on smaller wrists, adopting a 15 cm wrist circumference as our reference standard.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Watches such as the Aldren Square 28 and Corvo Dress 34 lie comfortably flush without rocking or sliding off centre. If a watch feels top-heavy, snags against a shirt cuff, or resists resting naturally on the tray, we pass on it.</p>
