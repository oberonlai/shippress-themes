<h2 class="wp-block-heading kw-h kw-h--q kw-h--left">WOULD WE WEAR IT OURSELVES AND WHEN DOES A WATCH LEAVE THE LIST?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our final question is simple: would Ilse, Tomasz, Amara, or Jonas wear this watch every day? We cap the collection at twelve pieces so we can genuinely advocate for each one.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When a maker modifies case proportions, switches to inferior movement suppliers, or discontinues replacement parts, Ilse removes that model from the list. Watches leave our counter quietly, ensuring our current selection of five pieces represents mechanical integrity we support without hesitation.</p>
