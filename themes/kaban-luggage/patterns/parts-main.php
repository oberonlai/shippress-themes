<h4 class="wp-block-heading kl-chapter__h">Shell Materials: Aluminium, Polycarbonate, and Waxed Canvas</h4>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kl-chapter__p"} -->
<p class="kl-chapter__p">The case shell protects contents against weather, cargo shifting, and baggage conveyors. Brushed aluminium weighs between 4.6 kg and 6.9 kg; it scuffs and takes shallow dents under impact but will not puncture, and dents can be treated at our bench. Matte polycarbonate weighs between 2.4 kg and 3.6 kg; it flexes to disperse kinetic shocks and resists surface scratching, though cracked shells require panel replacement. Waxed canvas weighs approximately 1.9 kg; it never dents, develops a rich surface patina over years of use, and can be re-stitched or patched indefinitely.</p>
