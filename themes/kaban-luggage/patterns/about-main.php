<!-- wp:paragraph {"className":"kl-chapter__p"} -->
<p class="kl-chapter__p">Ines Vandamme founded Kaban Luggage in 2009 after witnessing travellers struggle with oversized, poorly balanced suitcases that broke on their second journey. She established our independent shop and back-room workshop at Veerkaai 14 along the Antwerp quays. Instead of treating travel cases as disposable seasonal fashion, our philosophy pairs careful physical fitting at the retail counter with mechanical repair bench services. By stocking replaceable wheels, handles, and locks, we ensure every case we sell or service can travel reliably for years.</p>
