<!-- wp:paragraph -->
<p>Lacquer does not dry; it cures, drawing oxygen from humid air at around 25 °C and 75 % humidity. We keep a cedar cabinet, the furo, wetted every morning. A thin coat takes a day. Rushing it leaves wrinkles that only the whetstone can take away.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That is why a bowl spends eighteen months with us, and why the count of coats on each piece in the shop matters.</p>
