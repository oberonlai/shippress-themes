<!-- wp:heading {"className": "kk-chap__title"} -->
<h2 class="wp-block-heading kk-chap__title">The wood waits</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Mizuki and cherry are cut in late autumn, when the sap is low, and stacked under the eaves with the bark still on. Two winters later the logs ring when you knock them, and they are ready.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We split each log into billets the length of a doll and rough them round with a hatchet before they ever touch the lathe.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className": "kk-chap", "layout": {"type": "default"}} -->
<div class="wp-block-group kk-chap"><!-- wp:paragraph {"className": "kk-chap__num"} -->
<p class="kk-chap__num"><span class="kk-chap__no">02</span></p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className": "kk-chap__title"} -->
<h2 class="wp-block-heading kk-chap__title">The lathe</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The head and the body are turned separately on a foot-powered lathe. The body is a plain cylinder, or a gentle waist for the togatta style; the head is a sphere with a peg underneath.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For a naruko doll the peg is cut a hair too tight and pressed in with a twist, so the head turns with a small squeak, the sound the style is known for.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className": "kk-quote", "layout": {"type": "default"}} -->
<div class="wp-block-group kk-quote"><!-- wp:paragraph {"className": "kk-quote__text"} -->
<p class="kk-quote__text">&#8220;A kokeshi should look as if it was always round. You only take away what was hiding it.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className": "kk-quote__cite"} -->
<p class="kk-quote__cite">Sumi Ogata, third turner at the lathe</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className": "kk-chap", "layout": {"type": "default"}} -->
<div class="wp-block-group kk-chap"><!-- wp:paragraph {"className": "kk-chap__num"} -->
<p class="kk-chap__num"><span class="kk-chap__no">03</span></p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className": "kk-chap__title"} -->
<h2 class="wp-block-heading kk-chap__title">One brush, one breath</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The face goes on first: two strokes for the eyes, one for the nose, a dot of red for the mouth. Then the hair, then the flowers on the body. Each line is painted once and never corrected.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A doll whose face is not right goes back on the lathe and becomes a smaller doll.</p>
<!-- /wp:paragraph --></div>
