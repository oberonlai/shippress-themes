<!-- wp:paragraph {"className": "is-style-lead kk-long__lead"} -->
<p class="is-style-lead kk-long__lead">A kokeshi takes three days at the lathe and a winter or two before that on the drying rack. This is the whole story, in the order it happens.</p>
<!-- /wp:paragraph -->

<!-- wp:group {"className": "kk-chap", "layout": {"type": "default"}} -->
