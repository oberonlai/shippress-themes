<h2 class="wp-block-heading">One sheet, <em>one breath</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Every sheet on our shelves was lifted from the vat by hand: a scoop of milky water, a rocking motion, and the fibres knit into paper on the screen. Then it is pressed overnight and brushed onto a board to dry in the sun.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"ordered":true,"className":"is-style-steps"} -->
<ol class="wp-block-list is-style-steps"><!-- wp:list-item -->
<li>Cook and clean the mulberry bark, picking out every dark fleck by hand.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Beat the fibres on a stone until they float apart in water.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Lift each sheet from the vat on a bamboo screen, rocking it to knit the fibres.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Press overnight, then brush each sheet onto a wooden board to dry.</li>
