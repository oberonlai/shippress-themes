<h2 class="wp-block-heading">It started with a borrowed slot and a broken heater.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In the winter of 2019 a community station lent us its late slot for six weeks. The heater in Studio B did not work, so the first episodes were recorded in coats, and the first place we visited was the station’s own car park at night.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Six weeks became six years. In 2023 the show went independent: no advertising, paid for by the listeners who join as members, and still recorded in the same studio with a heater that now works.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The rules have not changed. One place per episode. No music bed under the recording. The guest picks the last song.</p>
