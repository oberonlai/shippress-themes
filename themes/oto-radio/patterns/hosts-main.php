<h2 class="wp-block-heading oto-host__name">Nao Hoshino</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Nao started recording at eleven with a borrowed cassette deck, taping the trains that ran behind her school. She studied acoustics, worked nights at a sound-hire company and joined the show in its first month to “hold the microphone for one episode”.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She plans every place, asks every permission and spends Wednesday recording four hours to keep twenty minutes. She narrates very little: the place does the talking.</p>
<!-- /wp:paragraph -->

