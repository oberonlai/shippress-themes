<!-- wp:heading {"className":"oto-host__name"} -->
<h2 class="wp-block-heading oto-host__name">Emi Tachibana</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Emi ran the late slot at a community station for six years before she and Nao went independent. She chooses the guests, cuts every episode on Thursday and reads the letters on air, all of them first, out loud, to the empty studio.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Listeners know her laugh before her name. She keeps a notebook of every closing record ever played and has never repeated one.</p>
<!-- /wp:paragraph -->

