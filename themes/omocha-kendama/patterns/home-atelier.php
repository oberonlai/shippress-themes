<h2 class="wp-block-heading ok-feature__title">The balance <em>of a kendama.</em></h2>
<!-- /wp:heading -->

<!-- wp:group {"className": "ok-columns", "layout": {"type": "default"}} -->
<div class="wp-block-group ok-columns"><!-- wp:paragraph {"className": "ok-dropcap"} -->
<p class="ok-dropcap">A kendama is three pieces of wood and a string, and it only plays well when all four agree. We turn the handle and the cup from one plank of beech so the grain runs the same way, then drill the ball until it sits on the spike without wobbling.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The string is the last thing we fit and the first thing to wear out. It is cotton, 40 centimetres, tied twice: long enough for a big swing, short enough for a child&#8217;s arm.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Before a kendama goes on the shelf, someone in the shop catches the ball on every cup a hundred times. If it rattles, it goes back to the lathe.</p>
<!-- /wp:paragraph --></div>
