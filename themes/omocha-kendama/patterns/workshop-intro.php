<h2 class="wp-block-heading ok-chapter__title">Beech for cups, cherry for tops</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Beech is hard and even, so it takes a sharp edge on a kendama cup. Cherry is softer and warmer, and it spins smooth. Maple goes to the youngest toys, because it is pale, light and never splinters.</p>
