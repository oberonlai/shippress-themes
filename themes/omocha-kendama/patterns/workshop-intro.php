<h2 class="wp-block-heading ok-chapter__title">Two turners and a timber yard next door</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sora Ishimori turns the kendama and the tops; Nao Fujikura paints the rings, threads the strings and runs the shop. The wood comes over the fence from the timber yard, a plank at a time.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Most mornings the lathe starts at eight and stops when the shop opens. In the afternoon the shavings are swept into bags for the bakery stove across the road.</p>
