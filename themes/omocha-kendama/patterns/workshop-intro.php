<!-- wp:heading {"className": "ok-chapter__title"} -->
<h2 class="wp-block-heading ok-chapter__title">Oil, beeswax and nothing else</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every toy is sanded to 400 grit, wiped with plant oil and polished with beeswax. Paint is used only for the rings on tops and the discs of the daruma otoshi, and it is the same water-based paint used for school crayons.</p>
