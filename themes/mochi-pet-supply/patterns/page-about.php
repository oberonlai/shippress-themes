<div class="wp-block-group mo-col8"><!-- wp:heading {"className":"mo-h3"} -->
<h2 class="wp-block-heading mo-h3">2017 in Leith</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"mo-body"} -->
<p class="mo-body">Isla had been a veterinary nurse and wanted the shop floor to be a place for plain answers. Tomasz took on buying. They opened with a handful of foods, a few shelves and a counter, and the two of them behind it.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"mo-h3"} -->
<h2 class="wp-block-heading mo-h3">How we choose</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"mo-body"} -->
<p class="mo-body">Short ingredient lists come first. Tomasz keeps the suppliers few enough that the packing room can name what is in each sack, and nothing goes on the shelf that the shop has not fed to its own animals first.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"mo-h3"} -->
<h2 class="wp-block-heading mo-h3">The van round</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"mo-body"} -->
<p class="mo-body">Kofi Mensah drives the Tuesday and Friday van through Leith, Portobello and Stockbridge, free. Everywhere else in the UK, parcels leave the packing room by 14:00 and arrive in one or two working days.</p>
