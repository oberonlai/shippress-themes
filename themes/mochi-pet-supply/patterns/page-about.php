<!-- wp:paragraph {"className":"mo-para"} -->
<p class="mo-para">Mochi Pet Supply opened in 2017 on Brunton Lane in Leith. Isla Morrow and Tomasz Kowal wanted a shop where someone could ask a plain question and leave with a bag that matched the animal at home.</p>
