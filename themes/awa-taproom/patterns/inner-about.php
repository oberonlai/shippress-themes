<p class="awa-body">Ines Halvorsen and Tomas Achebe established Awa Taproom in 2019 at 214 Water Street in Bellingham. Rather than building a remote warehouse production plant, they designed a space where brewing and hospitality occur in the same room. Our five-barrel brewhouse and six stainless steel fermenters stand right behind the bar rail, separated from customers only by a wooden counter. Tomas handled the initial renovation of the brick room, while Ines established our brewing schedule of Tuesday and Thursday brew mornings. Every batch is brewed, fermented, conditioned, and kegged within metres of where our thirty-eight seats sit.</p>
