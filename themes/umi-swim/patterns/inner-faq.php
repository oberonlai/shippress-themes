<details class="wp-block-details us-qa"><summary>How do trial lessons, cancellations, and make-ups work?</summary>
<!-- wp:paragraph -->
<p>Trial lessons cost €15 for 30 minutes and can be arranged across all ages before committing to a term. We schedule 4 terms per year, each lasting 10 weeks. If you need to cancel an upcoming term, we require 14 days notice before the term start date for a full refund. For missed sessions due to illness, we offer up to 2 make-up classes per term, subject to coach availability.</p>
