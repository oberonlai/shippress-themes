<details class="wp-block-details us-qa"><summary>What should adult beginners expect during their first class?</summary>
<!-- wp:paragraph -->
<p>Our adult beginner course is capped at 5 swimmers per coach to maintain a calm, relaxed environment. You will never be pushed into deep water or forced to swim lengths immediately. Lessons take place in our 0.9 m teaching pool where you can always touch the bottom securely. Coach Priya Nair guides the group through gentle breathing exercises, letting go of shoulder tension, and discovering natural buoyancy at your own unhurried pace.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details us-qa"><summary>Do I need to swim already?</summary>
<!-- wp:paragraph -->
<p>No. Adult beginner classes start in the shallow teaching pool, where you can always touch the bottom.</p>
