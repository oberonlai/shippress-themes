<h2 class="wp-block-heading us-h sp-reveal sp-reveal--mask">How We Teach: Four Principles</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:paragraph {"className":"us-lead2"} -->
<p class="us-lead2">Our teaching method follows four simple principles across all four ten-week terms. First, calm comes first: no swimmer is hurried away from the rail before they feel grounded. Second, we keep groups small, maintaining a strict ratio of one coach for every four children. Third, our warm teaching pool is kept at 32 °C and a depth of 0.9 m, providing an inviting space where shoulders stay relaxed. Fourth, every swimmer receives a clear progress card at the end of each term, celebrating personal milestones without pressure or arbitrary expectations.</p>
