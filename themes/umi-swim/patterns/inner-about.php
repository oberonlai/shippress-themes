<!-- wp:paragraph -->
<p>Our facility at Larkfield houses two purpose-built indoor pools designed for specific stages of learning. Our 12 by 6 metre teaching pool is heated to 32 °C with a uniform depth of 0.9 metres, creating a secure environment for infants, children, and adult beginners learning to submerge and float. For endurance, technique, and continuous swimming, our 25 metre main pool features 6 dedicated lanes maintained at 29 °C. Both pools are monitored continuously by certified deck staff to ensure clean water, stable temperatures, and total peace of mind during every session.</p>
