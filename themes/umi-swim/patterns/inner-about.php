<p>Lena Moreau founded Umi Swim School in 2014 after spending twelve years coaching nervous adults and hesitant beginners. She saw that commercial leisure centres were often too loud, cold, and crowded for learners to feel secure. Lena envisioned a dedicated school focused entirely on quiet confidence, water comfort, and steady skill progression. Beginning as a focused four-lane school, Umi has remained committed to unhurried instruction at 12 Quay Road in Larkfield. Every lesson prioritises calmness before distance, ensuring swimmers feel supported from their very first breath at the pool edge.</p>
