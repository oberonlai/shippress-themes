<h3 class="wp-block-heading us-card__t">Inès and Leo: From Baby Water to Stage 1</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"us-card__tx"} -->
<p class="us-card__tx">Inès enrolled her son Leo in Parent &amp; baby water when he was eight months old. Under the guidance of coach Amara Osei, their weekly 30-minute sessions in the 32 °C pool became a peaceful shared routine of splashing, floating, and building mutual trust. Leo developed an easy comfort with water over multiple terms. Now turning four, Leo has transitioned seamlessly into Kids Stage 1 with coach Tomás, happily kicking with a board and gliding toward the coach with natural ease.</p>
