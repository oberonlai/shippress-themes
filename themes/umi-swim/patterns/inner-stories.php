<h3 class="wp-block-heading us-card__t">Maya: Finding Confidence at Seven</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"us-card__tx"} -->
<p class="us-card__tx">Maya joined Umi Swim School at age seven feeling very hesitant around deep water. During her initial sessions in the 32 °C teaching pool, coach Tomás stayed right beside her as she held the poolside rail and practiced blowing surface bubbles. Over time, gentle encouragement helped her relax her shoulders and attempt supported back floats. By her second 10-week term in Kids Stage 2, Maya swam her first full width of the teaching pool completely unassisted, proudly collecting her term progress card.</p>
