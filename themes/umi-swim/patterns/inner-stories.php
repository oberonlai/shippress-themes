<h3 class="wp-block-heading us-card__t">Robert: Overcoming Lifelong Hesitation</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"us-card__tx"} -->
<p class="us-card__tx">At 54 years old, Robert had avoided swimming pools since a frightening childhood experience. Deciding to finally confront his fear, he booked a trial lesson with Priya Nair in our quiet shallow pool. Working in a small group capped at five adults, Robert learned to submerge his face, breathe rhythmically, and trust the buoyancy of water. Progressing into Adult Beginner 2, he successfully swam his first full 25-metre length in lane 1 of the main pool without stopping or feeling anxious.</p>
