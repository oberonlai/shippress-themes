<div class="wp-block-group"><!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What happens if it rains?</summary><!-- wp:paragraph -->
<p>Light rain does not stop the fireworks, and the stages are covered. In a storm or high wind we postpone that night to Monday 2 August and post the decision here and on the newsletter by 14:00 on the day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Can I bring food and drinks?</summary><!-- wp:paragraph -->
<p>Yes. Picnics are welcome on the banks. Please bring no glass, no barbecues and no camping stoves, and take your rubbish home or to the sorting stations by the bridges.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Is there parking?</summary><!-- wp:paragraph -->
<p>No. The river roads close at 15:00 and the town has no festival car parks. Use the park-and-ride at Kitano Sports Ground, the train or a bicycle.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Can I fly a drone?</summary><!-- wp:paragraph -->
<p>No. The air above the river is closed to drones from 12:00 to midnight on all three days, for the safety of the firing crews and the crowd.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Is it good for children?</summary><!-- wp:paragraph -->
<p>Very. Bring ear defenders for small children: the thunder shells are loud. Lost children are looked after at the festival office (point 5 on the map), and every child can get a free name band at the gates.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Where can I rent a yukata?</summary><!-- wp:paragraph -->
<p>Several shops on the Minase shopping street rent and dress yukata on festival days. Book a time slot with them directly; they get busy after 14:00.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Is there step-free access?</summary><!-- wp:paragraph -->
<p>Yes. The accessible deck by the North Gate has a ramp, seating and its own toilets. It is free for a guest and one companion; book it when you pre-register for passes or by email.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>When should I leave?</summary><!-- wp:paragraph -->
<p>There is no need to rush. The stages keep playing after the last shell, the Asagi Line runs extra trains until 23:30 and the last shuttle bus leaves at 23:15.</p>
