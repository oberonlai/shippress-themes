<h3 class="wp-block-heading ky-scene__title">The garden and the tea bench</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Below the studio is a small moss garden that came with the building. We added a long cedar bench and a kettle. After every class there is roasted green tea, and no one is in a hurry to leave.</p>
<!-- /wp:paragraph -->

