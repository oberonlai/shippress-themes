<div class="wp-block-group ky-faq"><!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>I am not flexible at all. Is that a problem?</summary><!-- wp:paragraph -->
<p>Not at all. Flexibility is something yoga gives you slowly, not something you need to bring. Every pose has an easier version.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What should I wear and bring?</summary><!-- wp:paragraph -->
<p>Clothes you can move in, and bare feet. We have mats, blocks, bolsters, blankets and a small changing room. Bring water if you like; the tea is ours.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>I have an injury or I am pregnant. Can I come?</summary><!-- wp:paragraph -->
<p>Usually, yes. Tell us in the form and your teacher will suggest the right class and adjustments. If in doubt, ask your doctor first.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>How early should I arrive?</summary><!-- wp:paragraph -->
<p>About ten minutes before the class starts, so there is time to fill in a short card and find a mat. The door closes at the start time.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What happens after the trial?</summary><!-- wp:paragraph -->
<p>Nothing, unless you want it to. If you would like to come back, a drop-in class or an eight-class card are easy ways to continue.</p>
<!-- /wp:paragraph --></details>
