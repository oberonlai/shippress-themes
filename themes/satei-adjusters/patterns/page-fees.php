<details class="wp-block-details sa-faq__d"><summary>Is travel included within your coverage area?</summary>
<!-- wp:paragraph -->
<p>Yes. Travel costs are fully included for all instructions located within our defined operating boundary of 90 minutes' drive from our Bristol desk. We do not bill mileage surcharges, congestion fees, or travel hours for visits undertaken across South West England and South Wales. The fixed fee confirmed at appointment represents the total professional charge for our site attendance. Insurers receive clear cost certainty before our team departs.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>How are re-inspections after drying handled?</summary>
<!-- wp:paragraph -->
<p>Re-inspections following structural drying are billed at the separate fixed rate of £260 per visit. When drying equipment has concluded its cycle, building surveyor Samir Haddad or an attending adjuster returns to site to take secondary moisture readings and photographic verification. This ensures the structure has returned to baseline equilibrium before repair contractors re-board or redecorate affected spaces. A concise re-inspection report is submitted to the insurer.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>Are fees subject to VAT?</summary>
<!-- wp:paragraph -->
<p>All fees quoted on our schedule and invoices are in GBP and exclusive of value-added tax. Applicable VAT is added at the prevailing statutory rate on the final monthly invoice. The appointing insurer is responsible for settlement, and no VAT liabilities or fee payment requests are ever directed to the policyholder whose home or premises sustained the physical damage. Our invoices clearly itemize VAT breakdowns for accounting clarity.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>How and when are invoices issued?</summary>
<!-- wp:paragraph -->
<p>We issue invoices monthly directly to the instructing insurer's claims department. Each monthly statement provides a consolidated summary referencing individual claim file numbers, visit dates, adjuster names, and specific service categories. Because each fee is agreed before we go, claims handlers experience straightforward invoice reconciliation without unexpected disbursements, time-sheet disputes, or retrospective fee adjustments. Payment terms follow standard commercial agreements established upon panel acceptance.</p>
