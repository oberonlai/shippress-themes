<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>Who pays for the loss adjuster's fees?</summary>
<!-- wp:paragraph -->
<p>The appointing insurer pays our professional fees in full. Satei Adjusters works exclusively under direct instruction from insurance companies, and our invoice is sent directly to their claims department. The policyholder whose home or business has sustained water or fire damage never pays us anything, nor do we request any deposit, contribution, or administrative fee from the insured. All financial arrangements remain strictly between our desk and the commissioning insurer.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>Do you carry out building repairs or strip-out work?</summary>
<!-- wp:paragraph -->
<p>No. Satei Adjusters is an independent loss-adjusting desk, not a repair firm, builder, or restoration contractor. We do not provide building works, strip-out labour, or drying equipment hire, nor are we owned by any repair franchise. Our sole objective is to inspect the damage, record impartial technical facts, and compile clear evidence so that insurers and their chosen contractors can proceed.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>How far do you travel for site visits?</summary>
<!-- wp:paragraph -->
<p>Our field coverage covers locations within 90 minutes' drive of our desk at Canal Wharf in Bristol. This operating area encompasses South West England and South Wales, including cities such as Bristol, Bath, Cardiff, Newport, Gloucester, and Cheltenham. Limiting our attendance to this realistic radius ensures our adjusters reach sites within 48 working hours without travel delays or fatigue. All travel within this zone is covered by our standard fixed fees.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>What does a panel place mean?</summary>
<!-- wp:paragraph -->
<p>A panel place represents a dedicated working partnership between an insurer and our Bristol desk. To ensure our team is never overextended and can meet our strict 48-hour site attendance and 5-day reporting commitments, we deliberately cap our client roster at at most 12 insurers at a time. Holding a panel place secures regular instruction capacity and direct access to our specialist adjusting personnel throughout the year.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>When do panel places open?</summary>
<!-- wp:paragraph -->
<p>Four panel places will open in April 2027. When places become available, we review requests strictly in the chronological order that they joined our waitlist. Insurers wishing to secure an allocated slot for their claims teams are encouraged to submit a waitlist request through our online form, providing estimated monthly claims volume and operational details. Our desk contacts prospective panel members in advance of the opening date.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>How quickly can an adjuster attend a site?</summary>
<!-- wp:paragraph -->
<p>An adjuster attends site within 48 working hours of the instruction being confirmed by our desk. Ruth Abernethy confirms all incoming appointments the same working day, liaising with the policyholder to establish access. Site visits take place Monday to Saturday between 08:00 and 17:00, allowing us to attend promptly before stripping out or temporary modifications alter the physical loss evidence. This fast response keeps claim investigations on track.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>How is a claim appointment scheduled?</summary>
<!-- wp:paragraph -->
<p>Scheduling begins when the insurer transmits claim documentation and policy details to desk@satei-adjusters.example or calls our phone lines between 08:00 and 18:00, Monday to Friday. Ruth Abernethy confirms receipt on the same working day, contacts the property owner, and allocates the appropriate specialist adjuster based on whether the loss involves water, fire, or contents damage. Appointment details are shared with the insurer immediately after confirmation.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>When will the insurer receive the final report?</summary>
<!-- wp:paragraph -->
<p>Our complete written report is delivered to the appointing insurer within 5 working days of the physical site inspection. Lin Qiao edits each report to verify factual accuracy and clarity. The document includes high-resolution photographs, calibrated moisture diagrams, a room-by-room damage breakdown, and causation notes, providing claims handlers with everything required to progress settlement without administrative back-and-forth. Reports are sent securely via email directly to the handler.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>Are your fees billed per hour or as fixed amounts?</summary>
<!-- wp:paragraph -->
<p>We operate entirely on a transparent fixed-fee schedule rather than billing open-ended hourly rates. Every service category carries a defined price: desk reviews are £180, standard water visits are £420, extended visits are £690, fire assessments are £860, half-day contents inventories are £340, and drying re-inspections are £260. All figures exclude VAT and are billed monthly to the insurer. Fixed fees give claims departments total predictability over adjusting expenses.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"sa-faq__d"} -->
<details class="wp-block-details sa-faq__d"><summary>Are you owned by or affiliated with any insurance company?</summary>
<!-- wp:paragraph -->
<p>No. Satei Adjusters was founded in 2014 as a completely independent loss-adjusting desk. We are not owned by, subsidiary to, or affiliated with any insurance company, insurance broker, or contractor repair network. This complete structural independence ensures our loss documentation, moisture readings, and scope observations remain entirely factual, neutral, and uncompromised by secondary commercial interests. Our role is simply to record the truth of the physical damage.</p>
