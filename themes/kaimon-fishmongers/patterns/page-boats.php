<h2 class="wp-block-heading kf-h2">The Five Boats and Their Landings</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We partner with five dedicated day boats, each landing on a specific weekday. On Tuesday, Morwen lands with skipper Ewan Price, bringing line-caught mackerel and sea bass. On Wednesday, Ellie Rose uses small trawl gear to land plaice, sole, and red gurnard. On Thursday, Saoirse arrives with pots full of brown crab and native lobster. On Friday, Two Sisters works nets to supply gilt-head bream, fresh squid, and cuttlefish. On Saturday, Kestrel finishes the week with hand-dived scallops and rope mussels. Every skipper fishes responsibly, bringing in seasonal hauls matched to local waters.</p>
