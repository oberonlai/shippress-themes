<h2 class="wp-block-heading kf-h2">How Buying on Quay 2 Works</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every morning begins at 04:40 on Quay 2, before the town stirs. Maren Holt meets the skippers as their deck lamps cut through the harbour mist, inspecting crates right on the stone quay. We buy only what was caught on the overnight trip, assessing clarity in the eyes, firm belly walls, and sea-bright sheen. By 05:15, buying is complete and the fish is transported immediately to 4 Quay Row. Because we purchase directly from the boats without middle wholesalers, the fish moves from saltwater to our iced display in less than two hours, preserving absolute sea freshness.</p>
