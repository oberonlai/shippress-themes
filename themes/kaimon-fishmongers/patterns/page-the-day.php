<h2 class="wp-block-heading kf-h2">Saturday Hours and Quiet Days</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Saturdays follow a dedicated weekend routine. Doors open half an hour earlier at 07:00 to welcome the landing of Kestrel's hand-dived scallops and mussels, and the shop closes promptly at 14:00, with last cuts taken at 13:30. On Sundays and Mondays, our doors remain closed. Because day boats do not go out on Sunday nights or Monday mornings, there are no fresh landings at Quay 2. Rather than stocking weekend carryover on ice, we stay closed until Tuesday dawn brings new boats to harbour.</p>
