<h2 class="wp-block-heading kf-h2">Morning on the Quay to Counter Opening</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our schedule begins at 04:40 when the first day boat ties up at Quay 2 under harbour lights. At 05:15, Maren Holt buys directly on the quay, selecting the finest crates of sea bass, mackerel, or flatfish. By 06:30, crates arrive at 4 Quay Row, where the team shovels fresh crushed ice onto the counter display and writes the day's board with landing weights and prices. At 07:30, our doors open to early customers, home cooks, and neighbourhood chefs seeking the first choice of the morning catch.</p>
