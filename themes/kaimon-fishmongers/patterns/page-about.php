<!-- wp:heading {"className":"kf-h2"} -->
<h2 class="wp-block-heading kf-h2">Nothing From the Boat Is Wasted</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our founding principle is simple: nothing from the boat is wasted. When a fish is cut on our wooden block, prime fillets go into customer bags, while the pristine bones, heads, and collars are gathered for cooking. Since 2014, our daily trim run transports these portions directly to local kitchens across Harrowmouth, turning would-be scrap into rich stocks and hearty family broths. Any customer can also request free heads and frames with their counter order. Our daily schedule begins on Quay 2 at 04:40 and finishes at 18:00 when the ice is hosed down, an honest progression described in full on The Day.</p>
