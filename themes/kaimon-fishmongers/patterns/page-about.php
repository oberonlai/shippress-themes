<!-- wp:heading {"className":"kf-h2"} -->
<h2 class="wp-block-heading kf-h2">Three Milestones in Our History</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our work has grown steadily around the rhythm of Harrowmouth harbour through three central milestones. In 2009, Maren Holt opened the doors at 4 Quay Row with an empty ice board and a morning handshake with two local skippers. In 2014, we ran our first kitchen trim run, creating a practical route to deliver clean heads and frames to neighbourhood pots instead of discarding them. In 2021, the Saturday scallop boat joined our landing schedule, completing our five-day boat roster with hand-dived shellfish. Each step strengthened our relationship with the harbour without altering our original commitment to small boats and daily trade.</p>
