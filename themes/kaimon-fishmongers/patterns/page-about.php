<!-- wp:heading {"className":"kf-h2"} -->
<h2 class="wp-block-heading kf-h2">The Net Store on Quay Row</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kaimon Fishmongers was founded in 2009 by Maren Holt inside a former net store at 4 Quay Row. The shop takes its name from the old sea gate standing at the end of the row, where harbour boats have tied up for generations. From the first morning, Maren set a single standard: buy directly from the day boats landing on Harrowmouth quay and sell every catch before evening. We do not keep stock overnight or buy from industrial freezer trawlers. Working exclusively with day boats means our counter mirrors the tides, the season, and the weather out past the headland. Every fish on our counter was swimming hours before our doors opened.</p>
