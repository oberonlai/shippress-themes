<h2 class="wp-block-heading kf-h2">Why do we report on harbour weather?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Small day boats are completely reliant on sea state, tidal flow, and wind direction. If a low-pressure system brings heavy Atlantic swells to Harrowmouth, small boats cannot safely shoot nets or lift crab pots. In each Monday newsletter, we explain forecast weather patterns honestly. If storms mean a boat must stay in harbour, we tell you early so you know why the shop board might be smaller on Wednesday or Thursday. Subscribing is free by entering your email on our site.</p>
