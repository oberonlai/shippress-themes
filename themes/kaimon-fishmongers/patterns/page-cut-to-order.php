<!-- wp:heading {"className":"kf-h2"} -->
<h2 class="wp-block-heading kf-h2">Why should you take the heads and frames?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When we fillet a fish, more than a third of its weight remains in the head, spine, and collar. These bones hold natural gelatin and deep sea flavour that commercially prepared cubes cannot replicate. If you ask at the block, we pack your fish frames and heads into a clean bag at no extra charge. Simmered for twenty minutes with onion, bay leaf, and peppercorns, they produce an aromatic, golden stock ideal for risottos, chowders, and poaching broths. Taking the frames honours the fish and ensures nothing from the boat is wasted.</p>
