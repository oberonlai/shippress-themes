<h2 class="wp-block-heading kf-h2">The Four Steps at the Block</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our preparation follows four clear steps at the wooden cutting block. Step 01: Choose a whole fish resting on the crushed ice. Step 02: Tell us how you will cook it, whether in a pan, roasted whole in the oven, or poached gently. Step 03: We cut while you wait, taking about 6 minutes a fish with sharp knives and clean strokes. Step 04: Your fish is wrapped in waxed paper; heads and frames are bagged for stock if you want them, completely free of charge. Nothing is hurried, and every cut is cleanly finished.</p>
