<!-- wp:heading {"className":"kf-h2"} -->
<h2 class="wp-block-heading kf-h2">How do you choose a whole fish on the ice?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Selecting whole fish is straightforward when you know the four indicators of day-boat freshness. First, examine the eyes: they must be clear, plump, and bright, never sunken, clouded, or dull. Second, check the gills by lifting the gill cover; they should show a vibrant, clean blood-red colour without brown mucus. Third, smell the fish closely: it should carry only the clean, cool scent of ocean water and kelp, with no sour or stale odour. Fourth, touch the flesh; it must feel firm, resilient, and elastic to the touch, bouncing back immediately under gentle pressure.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
<ol class="kf-pairs sp-stagger">
<li class="kf-pair kf-rule"><h3>Eyes</h3><p>Clear, plump and bright. Sunken, cloudy or dull eyes mean the fish has been on ice for days.</p></li>
<li class="kf-pair kf-rule"><h3>Gills</h3><p>Lift the cover: a clean blood-red, without brown mucus.</p></li>
<li class="kf-pair kf-rule"><h3>Smell</h3><p>Cold salt water and clean tide only. Nothing sour, nothing stale.</p></li>
<li class="kf-pair kf-rule"><h3>Flesh</h3><p>Firm and elastic; it springs back when you press it gently.</p></li>
</ol>
