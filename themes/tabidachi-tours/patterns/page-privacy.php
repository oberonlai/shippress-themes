<h1 class="wp-block-heading tt-page-h">Privacy.</h1>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"tt-standfirst"} -->
<p class="tt-standfirst">This privacy policy explains how Tabidachi Study Tours collects, stores, and protects personal information belonging to teachers, parents, and students. We handle all data in strict compliance with applicable data protection legislation.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"className":"tt-legal__h"} -->
<h2 class="wp-block-heading tt-legal__h">Information we collect</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>To plan and execute educational journeys safely, we collect contact information for school coordinators, including names, official email addresses, and phone numbers. For participating students, we record full names, year groups, room allocations, and coach seat assignments. Where necessary for pupil safety and wellbeing, we collect parent emergency phone numbers, dietary requirements, and essential medical disclosures submitted on signed school consent forms.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"className":"tt-legal__h"} -->
<h2 class="wp-block-heading tt-legal__h">How personal data is used</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>All collected data is utilised strictly to operate booked study tours, satisfy statutory health and safety obligations, and coordinate emergency responses. Student dietary and medical sheets are shared only with relevant tour leaders, coach drivers, and vetted accommodation managers. We use parent mobile numbers solely to deliver the twenty-one hundred hours evening update message and for urgent communication during travel. We never sell, rent, or share personal data with external marketing agencies.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"className":"tt-legal__h"} -->
<h2 class="wp-block-heading tt-legal__h">Data retention and contact rights</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Operational records, student manifests, and medical sheets are retained through the post-trip debriefing period, which concludes within ten days of returning to the school. Following debrief completion, temporary medical documents and daily manifests are securely destroyed, while financial transaction records are retained in accordance with statutory accounting requirements. If you have questions about your personal data, contact our data coordinator at eighteen Platform Lane, Ashby Vale, or email hello@tabidachi-tours.example.</p>
