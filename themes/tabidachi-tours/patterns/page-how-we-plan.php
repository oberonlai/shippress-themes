<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>During this term, our safety director finalises the signed, venue-specific risk assessment, incorporating transport routes and hostel fire safety plans. By the end of spring term, the second instalment of forty percent is collected.</p>
