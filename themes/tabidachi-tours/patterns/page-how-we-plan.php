<div class="wp-block-group tt-brow__b"><!-- wp:paragraph -->
<p>In November and December, we organise a complimentary planning visit for confirmed itineraries, allowing school leaders to inspect accommodations, walking routes, and coach access points firsthand. We then assemble your comprehensive governors approvals pack, which includes detailed draft itineraries, risk assessments, insurance certificates, and tour leader qualifications. During this phase, the school confirms booking arrangements and prepares communication packs for families ahead of spring launches.</p>
