<h2 class="wp-block-heading ys-sec__title">Ninety-eight cushions, one stage, no microphone.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Kanda family built the hall above their sweet shop when the old yose on the corner burned down. The cushions are restuffed every spring; the lantern by the stage is the original.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Apprentices start as zenza, folding kimono and beating the drum, and open the bill each night. After four years they become futatsume; after ten or so, shin&#8217;uchi, and may close the night.</p>
