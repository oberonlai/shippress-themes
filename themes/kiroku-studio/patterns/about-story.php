<h2 class="wp-block-heading">Started with one camera and one night.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In the spring of 2015 Ren Kuroda, an animator, and Aya Morikawa, a type designer, borrowed a camera, set it on a tripod in an empty warehouse and drew the word “kiroku” in the air with a torch. That 30-second exposure became the studio's first reel and, in a way, its whole method.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We still sketch in motion before we sketch on paper. Every identity we make is tested as a moving thing first: how it enters, how it waits, how it leaves. If it cannot move well, it is not finished.</p>
<!-- /wp:paragraph -->

