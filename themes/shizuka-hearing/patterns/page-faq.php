<details class="wp-block-details sh-faq__item"><summary>How do I know if I need a hearing check?</summary>
<!-- wp:paragraph -->
<p>Many adults notice gradual changes in their hearing long before they experience difficulty in quiet rooms. If you frequently find yourself asking family members to repeat sentences, struggling to follow group conversations in restaurants, or raising the television volume above what others find comfortable, a hearing check is recommended. Missing consonants or feeling mentally fatigued after social gatherings are also classic indicators. Our 60-minute hearing check for €95 provides objective measurements of your hearing sensitivity and clarifies whether your difficulties stem from earwax, auditory fatigue, or high-frequency hearing loss.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"sh-faq__item"} -->
<details class="wp-block-details sh-faq__item"><summary>What happens during a 60-minute hearing check?</summary>
<!-- wp:paragraph -->
<p>Your appointment begins with an in-depth conversation about your medical history, listening environments, and daily communication challenges. Next, your audiologist performs video otoscopy to inspect your outer ear canals and eardrums for wax or physical irritation. You then step into our calibrated sound booth for pure-tone audiometry, where you listen to gentle tones across various pitches. We explain your results immediately using clear visual charts. You receive a plain-language summary to take home, with no obligation to purchase devices or proceed with further treatment unless you choose to do so.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"sh-faq__item"} -->
<details class="wp-block-details sh-faq__item"><summary>What is real-ear measurement and why is it essential?</summary>
<!-- wp:paragraph -->
<p>Real-ear measurement is an objective verification standard that measures the exact sound pressure delivered by a hearing aid directly inside your ear canal. Because ear canals differ significantly in volume, shape, and acoustic resonance, generic manufacturer software settings can miss prescription targets by substantial margins. By placing a tiny silicone probe tube adjacent to your eardrum during fitting, we measure calibrated speech in real time. We adjust your hearing aid&#x27;s frequency response until amplified speech matches your auditory prescription precisely, ensuring that conversation sounds natural, intelligible, and comfortable in daily wear.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"sh-faq__item"} -->
<details class="wp-block-details sh-faq__item"><summary>How does the 14-day home trial work?</summary>
<!-- wp:paragraph -->
<p>Hearing aids sound very different in real-world environments than they do in a quiet consulting room. Our fitting package includes a 14-day home trial using loaner devices programmed to your prescription. Over two weeks, you test the instruments in familiar settings: watching television at home, talking over dinner in noisy restaurants, and walking outside. You maintain a simple listening log noting any environments where speech felt muffled or sharp. At your second fitting visit, we analyze your experiences and refine the acoustic programming to ensure long-term comfort and optimal clarity.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"sh-faq__item"} -->
<details class="wp-block-details sh-faq__item"><summary>Can tinnitus be cured completely?</summary>
<!-- wp:paragraph -->
<p>In ethical audiology, we must be honest: there is currently no medically proven cure that eliminates tinnitus permanently. However, effective clinical strategies can significantly lessen how intrusive the sound feels. Through our 75-minute tinnitus consultation with Mei Lin Hartmann, priced at €140, we combine acoustic sound therapy, environmental sound enrichment, and habituation counselling. By addressing underlying hearing changes and calming the brain&#x27;s heightened auditory gain, many patients find their tinnitus recedes into the background of awareness, allowing them to relax, work, and sleep peacefully again.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

