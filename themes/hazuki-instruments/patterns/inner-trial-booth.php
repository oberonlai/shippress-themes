<div class="wp-block-group hz-qa"><!-- wp:heading {"level":3,"className":"hz-qa__q"} -->
<h3 class="wp-block-heading hz-qa__q">Is there any fee or purchase obligation for using a sound booth?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>No. Every 45-minute trial booth session is free of charge, and there is never any obligation to buy an instrument. We created our booths because musical instruments cannot be judged in a noisy aisle with staff hovering over your shoulder. Whether you are comparing two upright pianos, testing a student trumpet, or simply checking how a guitar neck feels in your hands, you receive the same private room and patient support from our team.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hz-qa","layout":{"type":"default"}} -->
<div class="wp-block-group hz-qa"><!-- wp:heading {"level":3,"className":"hz-qa__q"} -->
<h3 class="wp-block-heading hz-qa__q">How many instruments can I bring into the booth?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We recommend bringing two or three instruments into the booth at one time. This gives you ample opportunity for direct, back-to-back comparison without cluttering the room or rushing through your forty-five minutes. If you wish to try additional models, our staff can swap instruments out midway through your session. You are also welcome to bring your existing personal instrument into the room to compare its sound and feel against models in our collection.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hz-qa","layout":{"type":"default"}} -->
<div class="wp-block-group hz-qa"><!-- wp:heading {"level":3,"className":"hz-qa__q"} -->
<h3 class="wp-block-heading hz-qa__q">Can my music teacher or parent join me inside the booth?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Yes. We encourage students to bring their music teachers or parents into the booth. Having an instructor present helps evaluate tonal response, ergonomics, and instrument mechanics in real time. Our booths comfortably seat two people alongside instrument stands. Staff remain outside in the hallway to preserve your privacy, but Tomás Ruiz, Sofia Brandt, Leila Haddad, Kenji Arai, or Mara Ellison are always nearby if your teacher wants technical details about setups or ongoing instrument care.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hz-qa","layout":{"type":"default"}} -->
<div class="wp-block-group hz-qa"><!-- wp:heading {"level":3,"className":"hz-qa__q"} -->
<h3 class="wp-block-heading hz-qa__q">What should I do if I need more than forty-five minutes?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A single session lasts 45 minutes, which is generally ideal for focused listening without ear fatigue. If you are deciding between major instruments and feel you need more time, you may book a second session on another day or speak with Nia Okoro at our desk to see if an adjacent slot is open later that afternoon. Taking time away between trials often helps players make clearer, more confident decisions without feeling pressured.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hz-qa","layout":{"type":"default"}} -->
<div class="wp-block-group hz-qa"><!-- wp:heading {"level":3,"className":"hz-qa__q"} -->
<h3 class="wp-block-heading hz-qa__q">Can I test amplifiers or brass instruments at full performance volume?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Yes. Our three sound booths are built with sound-dampening insulation specifically so musicians can test at genuine playing volumes. Sofia Brandt assists brass and woodwind players testing projection, while Tomás Ruiz and Mara Ellison set up amplifiers for electric guitars and basses. You can evaluate natural acoustic projection, dynamic range, and tonal warmth at real volumes without worrying about disturbing customers browsing downstairs on the ground or first floors.</p>
