<div class="wp-block-group hz-long__b sp-reveal sp-reveal--up"><!-- wp:paragraph -->
<p>When visiting Hazuki Instruments to evaluate an instrument, we encourage you to bring your own familiar accessories. Guitarists often bring their preferred pick or strap, string players bring their bow, and brass players bring their personal mouthpiece. You may also bring a current instrument for side-by-side comparison. Having your everyday gear on hand gives you a reliable baseline for judging comfort, weight, and tone. If you do not have your own accessories with you, our staff can provide sanitized mouthpieces, bows, and picks so you can test comfortably.</p>
