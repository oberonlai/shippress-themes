<!-- wp:heading {"className":"mk-section__title"} -->
<h2 class="wp-block-heading mk-section__title">We opened with one bowl and a borrowed machine.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kenta Morioka spent nine years cooking in other people’s ramen shops before he found an empty eight-stool counter at the back of Kaen-yokocho. The first ticket machine came from a closing soba shop down the road. It had one working button. We sold shoyu ramen and nothing else for six months.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Now the machine has eighteen buttons, the broth pot is twice the size, and Yui Nanase makes the noodles every morning on a machine older than she is. We still close when the soup runs out.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The counter seats eight. There are no bookings and no tables. If there is a line, it is along the wall, and it moves fast.</p>
