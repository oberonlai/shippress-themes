<p class="mk-dropcap">Before it was a ramen counter, the room was a tailor's shop for forty years. When Tomoe Hayase took it over, she kept the long cutting table, sanded it down to pale wood and turned it into the counter. The cupboard where bolts of cloth were kept now holds the bowls.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She had cooked in other people's kitchens for twelve years. What she wanted was a smaller one: a single pot, a menu that fits on a card, and a room quiet enough to hear the broth.</p>
