<!-- wp:paragraph {"className":"mk-dropcap"} -->
<p class="mk-dropcap">The pot goes on at five in the morning: whole chickens, a little pork bone, kombu from the north and water that has been filtered twice. It never boils. For eleven hours it moves just enough to turn the surface, and someone is always watching it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We skim by hand. We add the kombu late and take it out early. By the time the first noren goes up, the broth is clear enough to read through, and it tastes of nothing more than what went in.</p>
<!-- /wp:paragraph -->

<!-- wp:image {"sizeSlug":"large","align":"wide","className":"mk-figure"} -->
