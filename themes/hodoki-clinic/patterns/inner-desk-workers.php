<p class="hd-body hd-unwind__p">The third habit is reaching forward by bracing: chin toward the screen, ribs into the desk, arm stretched to a mouse that sits too far away. The shoulder works at its end point for hours. In the studio we call the alternative reaching without bracing. The arm should arrive at the keyboard with the neck still quiet.</p>
