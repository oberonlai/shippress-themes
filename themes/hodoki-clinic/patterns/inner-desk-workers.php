<div id="workstation-review" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Workstation review</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">A workstation review looks at the desk you actually use. We do it at your office or by video: 45 minutes, $80. The point is a few changes you will still see on Monday. Screen height. Where the mouse lives. Whether your feet reach the floor. How far you reach for the keyboard.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">We will not sell you a list of equipment. If a monitor arm, a laptop stand, or a footrest would change the day, we say which and why. If the chair is fine and the habit is the problem, we say that too. Lena's course for shoulder and neck ache included a review alongside six sessions over eight weeks. For a video review, bring daylight photos of the desk from the side and from the front.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hd-psec sp-reveal sp-reveal--up","layout":{"type":"default"},"anchor":"shoulders-that-never-quite-drop"} -->
<div id="shoulders-that-never-quite-drop" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Shoulders that never quite drop</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The first habit we watch is shoulders that stay slightly raised. Typing, concentrating, and carrying a bag can park the shoulder blades in a shrug. The neck then works overtime, and a headache may join by afternoon.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">In the clinic we loosen that brace before we ask you to strengthen. A chest opening in the studio shows the difference between forcing the shoulders back and letting them rest. Your home programme will be short. One movement between meetings is worth more than a list you save and forget. If the shoulder pain follows an operation rather than the desk, book Priya Nair. Tell Elena which history is yours.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hd-psec sp-reveal sp-reveal--up","layout":{"type":"default"},"anchor":"sitting-past-the-point-of-ease"} -->
<div id="sitting-past-the-point-of-ease" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Sitting past the point of ease</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The second habit is staying seated after the back has asked you to move. Stiffness that eases when you walk, then returns in the next meeting, is a pattern Amara treats often. A different chair does not cancel a long day. We help you notice the moment the back stops sharing, and give you a way to stand, hinge, and sit again that fits between meetings.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Desk Reset is where you can practise that with other people, for 50 minutes, if you want a set time and a small group. Individual follow-ups stay available at $75 for 45 minutes, or $55 for a short 30-minute visit when the plan is already clear and you only need a check.</p>
