<h3 class="wp-block-heading hd-h3">Desk Reset</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Desk Reset is a small-group class led by Sofia Lindgren, our exercise physiologist. It lasts 50 minutes, costs $28, and is limited to six people. The class meets on Tuesday and Thursday at 18:15, and on Saturday at 10:00, inside clinic hours.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">You practise what desk bodies lose: opening the chest, rolling the shoulders without hiking them, and standing from a chair with the hips sharing the work. It is not a fitness class, and it is not a substitute for assessment if you are in pain. Noor, 41, used Desk Reset for eight weeks for lower-back stiffness from sitting, plus three follow-ups with Amara. Wear clothes you can sit and stand in. If a class is full, Elena Duarte will offer the next date.</p>
