<h2 class="wp-block-heading hd-h2">What the desk asks of you</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">A desk rarely injures you in one moment. It asks for the same posture for hours: head forward, shoulders slightly up, back quiet, hands ahead of the body. By late afternoon the neck aches, the shoulder feels crowded, and standing is the first relief since lunch.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The first visit is still 60 minutes and $95. We watch you move, not only the chair you describe. Amara Osei treats back pain and desk-related pain. Clara Mendes treats neck and shoulder. Jonah Reed treats hand, wrist, and elbow when the keyboard is the loudest part. If the desk itself should change, a workstation review is 45 minutes at your office or by video.</p>
