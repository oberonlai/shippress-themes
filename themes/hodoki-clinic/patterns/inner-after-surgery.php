<div class="wp-block-group hd-col hd-col--c sp-reveal sp-reveal--up"><!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body"><span class="hd-runin">Protect.</span> The early phase is protection. The aim is not a hard session. It is to keep the joint safe while swelling settles and while you learn the movements your protocol allows. On the table that may be a careful heel slide, a supported bend, or a shoulder range that stays inside the angles you were given. We watch how you stand, how you get off the bed, and how you take weight.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">You leave with a short home programme and a clear stop-point: what should wait. A post-surgery session is 60 minutes. If something in the protocol is unclear, we pause rather than add a load the surgeon did not ask for. Strength that belongs to a later phase stays there.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body"><span class="hd-runin">Restore.</span> When the protocol allows more, we restore range you can use and the strength to carry it. A knee that bends on the table still has to bend on a stair. A shoulder that lifts in the bay still has to reach a shelf without the neck taking over.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">This is supported practice in the studio: loading you can repeat, gait, and steady work with a wall bar, checked against the surgeon's limits. Tomasz or Priya stays with the plan, so the person who measured you is the person who loads you. Follow-ups are usually every one to two weeks. We change the home programme when the tests change. At week six we ask whether the pace still fits the protocol and your week.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body"><span class="hd-runin">Return.</span> Return means the specific things you stopped doing. For many people that is the station stairs, a full day at a desk, or a walk that used to be ordinary. We practise those tasks rather than collecting exercises that never meet them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Marcus, 58, had a knee replacement and completed twelve rehab sessions over fourteen weeks with Tomasz. He walks to work again and takes the stairs at the station. That is his return, shared with his consent. Yours might be different, and we will name it in the written plan. If your surgeon has a date for driving, lifting, or a fuller load, we do not move that date to make the story neater.</p>
