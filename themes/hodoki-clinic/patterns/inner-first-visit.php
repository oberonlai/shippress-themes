<h3 class="wp-block-heading hd-h3">Assess</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The hour starts with history. What you cannot do this month that you could do before. What the workday looks like. What the surgeon allowed, if there was an operation. Then we test movement. A shoulder may be measured. A knee may be taken through a bend you use in real life. A back may be watched as you sit and stand.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">We do not start treatment before we have looked, and we do not spend the hour only talking. The tests give the session a direction. Wear clothes you can move in. Shorts help for a knee or hip, and a vest helps for a shoulder. Ordinary work clothes are fine if they let us see the joint we need to see.</p>
<!-- /wp:paragraph --></div>
