<h3 class="wp-block-heading hd-h3">Plan</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Before the day ends you receive a written plan. It names what we found, what we did, and what we are asking you to practise at home. The home programme is meant to be small enough to keep beside a normal week. The plan also says when we want to see you again. Follow-ups are usually every one to two weeks.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">You do not have to buy a package for the plan to exist. A block of five 45-minute follow-ups, used within four months, is $340 if you later want that clarity. A single follow-up is $75 for 45 minutes. A short follow-up is $55 for 30 minutes. We will say which length fits. Receipts carry treatment codes for your insurer.</p>
