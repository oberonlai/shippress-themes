<div id="review" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Review</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">At week six we review. The question is practical: are you closer to the thing you came for, and is the spacing of visits still right? Some people need less by then. Some need a different exercise, a workstation review at $80, or a move into Desk Reset. The review is a clinical conversation. It is not a meeting to sell the next block of time.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Stories on this site are consented composites. They are not a forecast. Lena's six sessions over eight weeks, Marcus's twelve sessions over fourteen weeks, and Noor's eight weeks of class with three follow-ups each ended in a change that person agreed to describe. Your review uses your tests, not their timelines.</p>
