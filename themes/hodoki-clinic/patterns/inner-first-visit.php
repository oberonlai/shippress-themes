<h3 class="wp-block-heading hd-h3">Treat</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Hands-on treatment starts in the same 60 minutes, once the tests have pointed somewhere. You should feel that something specific was tried, and we should be able to say whether the test changed. A first idea that does not hold is still a result. We would rather find that in the room than send you home with the wrong exercise.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The first visit, assessment and treatment together, costs $95. If you are coming straight into rehabilitation after an operation, the post-surgery session is 60 minutes at $90. Elena confirms which fee applies before you go into the bay. You pay for that visit. You are not asked to prepay a course you have not discussed.</p>
