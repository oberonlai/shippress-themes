<h2 class="wp-block-heading hd-h2">Untying, since 2015</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Clara Mendes opened Hodoki Clinic in 2015. The name is our word for untying: loosen what is held, then build strength. A shoulder braced over a keyboard, or a knee guarded since an operation, is often tied up in protection before it is truly weak. We listen, test how you move, and start treatment on the same day.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">There is one clinic, at 2F, 41 Alder Street, Fernhill. Five treatment bays and a small exercise studio share one corridor, so the assessment and the practice are not in different buildings. The first visit is sixty minutes. You do not need a referral, and you do not need to buy a package before anyone will see you.</p>
