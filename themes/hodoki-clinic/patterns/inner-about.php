<div id="then-build-strength" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Then build strength</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Guarding is useful for a short time and costly if it stays. After an operation the body protects the joint. After months at a desk the shoulders sit up by the ears and the back stops sharing the work. Strengthening on top of that brace often feels like effort without ease.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">So the early work is to untie. Calm the tissue that is holding on, restore a range you can use, then load it in the studio. Sofia Lindgren leads Desk Reset when the next step is practice in a small group. The physiotherapist who tested you stays with the plan. We do not name a number of weeks in advance. We name the next visit from what the tests showed.</p>
