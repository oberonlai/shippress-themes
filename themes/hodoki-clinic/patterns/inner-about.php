<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Hands-on treatment starts in that same hour, so you leave knowing what we tried and what changed. A written plan follows the same day. We would rather change one clear thing than hand you a long programme you will not keep. Follow-ups are usually every one to two weeks, with a review at week six.</p>
