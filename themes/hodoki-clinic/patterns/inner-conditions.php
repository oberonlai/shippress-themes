<div id="posture-headaches" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Posture headaches</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Some headaches we see start at the desk: pressure by mid-afternoon, tightness at the base of the skull, and shoulders that have crept up while you concentrate. They often travel with neck stiffness rather than arriving on their own.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Clara Mendes assesses these patterns with the neck and shoulder work she leads. If the history points more to a sitting back, Amara Osei may share the plan. We do not treat every headache. On the first visit we ask what brings it on and how the neck moves. If we find a movement problem, we treat that and send a written plan the same day. If it is not our work, we say so. Follow-ups, when needed, fall every one to two weeks, with a review at week six.</p>
<!-- /wp:paragraph --></div>
