<h3 class="wp-block-heading hd-h3">Lower back</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Lower-back stiffness here often builds from sitting, eases when you walk, and returns when the meetings stack up. It is not always a dramatic injury. The back has stopped sharing work with the hips, and the chair has become the place you endure.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Amara Osei treats back pain and desk-related pain. We look at how you hinge, how long you sit before you shift, and whether the hips do their share. Treatment may be hands-on work, a different way of standing up, and practice in the studio or in Desk Reset. Noor, 41, came with stiffness from sitting, joined Desk Reset for eight weeks, and had three follow-ups with Amara. Your spacing is set after we test you, then reviewed at week six.</p>
<!-- /wp:paragraph --></div>
