<div id="who-sees-which-problem" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Who sees which problem?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Neck and shoulder: Clara Mendes, or Priya Nair when the shoulder follows surgery. Lower back and desk-related pain: Amara Osei. Hand, wrist, and elbow: Jonah Reed. Hip and knee, including replacement and ligament repair: Tomasz Wolski. Posture headaches that sit with the neck: Clara Mendes. Desk Reset classes: Sofia Lindgren.</p>
