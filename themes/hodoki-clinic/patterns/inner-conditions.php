<h2 class="wp-block-heading hd-h2">Neck and shoulder</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Neck and shoulder trouble in our rooms is often a desk pattern. The head sits forward, the shoulders stay slightly lifted, and by afternoon the side of the neck aches. Reaching for a bag, or turning to look behind you, feels narrower than it used to.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Clara Mendes treats neck and shoulder. On the first visit we measure how you move, watch how you describe a day at the screen, and start hands-on treatment in the same hour. The plan may include a short set of movements and, if the desk is part of the cause, a workstation review. Priya Nair sees shoulders after surgery. Say so when you book if an operation came first. Lena, a software tester of 34, returned to full days at her desk after six sessions over eight weeks plus a workstation review. That course was hers, not a timetable we hand to everyone.</p>
