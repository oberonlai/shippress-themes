<div id="hip-and-knee" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Hip and knee</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Hip and knee pain may follow an operation, or it may be a joint that avoids load while you sit and then overdoes it when you walk. Stairs, low chairs, and the first minutes after standing are the complaints we hear most.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Tomasz Wolski leads post-surgery rehabilitation for knee and hip. If you have had a replacement or a ligament repair, bring the surgeon's protocol. We work inside it. If there has been no operation, we still test how you take weight before we add strength. Marcus, 58, walks to work again and takes the stairs at the station after twelve rehab sessions over fourteen weeks with Tomasz. His course is his own. Yours is written from your tests and your protocol.</p>
<!-- /wp:paragraph --></div>
