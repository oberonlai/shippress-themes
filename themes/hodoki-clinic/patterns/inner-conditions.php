<div id="after-surgery" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">After surgery</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">A knee, hip, or shoulder replacement, or a ligament repair, needs a period of protection before ordinary strength work is useful. We do not improvise around your surgeon's instructions. Tomasz Wolski sees knee and hip rehabilitation. Priya Nair sees shoulders after surgery.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">The post-surgery session is 60 minutes and costs $90. Early visits focus on what the protocol allows: swelling, safe range, and the way you walk or reach. Later visits restore strength and return you to stairs, desks, and ordinary walking. Protect, Restore, and Return are described on our after-surgery page. Tell Elena Duarte the operation and the date so the right therapist is in the room.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

