<div id="wrist-and-elbow" class="wp-block-group hd-psec sp-reveal sp-reveal--up"><!-- wp:heading {"level":3,"className":"hd-h3"} -->
<h3 class="wp-block-heading hd-h3">Wrist and elbow</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Wrist and elbow pain here often comes from hours of keyboard and mouse: a forearm that stays tight, a wrist that aches by evening, an elbow that complains when you lift a kettle. The arm is doing a small job at its end point, over and over.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"hd-body"} -->
<p class="hd-body">Jonah Reed treats hand, wrist, and elbow. We test grip and wrist range, and we look at how the arm is supported, before we treat. Hands-on work is paired with a few changes you can keep: where the mouse sits, how hard you grip, when you stop and open the hand. A workstation review, at your office or by video, lasts 45 minutes and costs $80. You do not need a referral to start.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

