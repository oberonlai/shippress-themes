<h3 class="wp-block-heading kg-step__title">A dry boil</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kg-step__text"} -->
<p class="kg-step__text">Never heat a kettle empty. Keep the flame inside the base and the water above a third.</p>
