<h3 class="wp-block-heading kg-step__title">Standing water</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kg-step__text"} -->
<p class="kg-step__text">Water left overnight is what rusts a kettle. Empty it warm and let it dry open.</p>
