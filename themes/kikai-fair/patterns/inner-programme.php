<!-- wp:heading {"className":"kf-value__h"} -->
<h2 class="wp-block-heading kf-value__h">How are live cutting demos and lunch talks structured?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Live machinery demonstrations run throughout the day on the dedicated Demo Stage hosted by Lena Vogt. Demonstrations provide 30-minute operational slots where manufacturers process solid timber, composite panels, and veneers under full workshop loads while Lena Vogt explains cutterhead speeds, feed rates, and tooling tolerances. At 12:30 each day, Stage B hosts technical lunch talks addressing dust extraction standards, panel optimization, and shopfloor workflow design. These midday presentations allow engineers, master joiners, and workshop managers to examine practical production challenges before returning to machinery stands for individual consultations and trial cuts.</p>
