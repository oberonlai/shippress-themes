<!-- wp:heading {"className":"kf-value__h"} -->
<h2 class="wp-block-heading kf-value__h">What are the stand rates and build-up hours for exhibitors?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Exhibitors can select between turn-key shell schemes and open raw floor space. A standard shell stand of 9 square metres costs €2,700 and includes perimeter walls, standard lighting, and power connectivity. Raw floor space is priced at €240 per square metre, with a minimum stand booking of 18 square metres for custom machine foundations. Exhibitors wishing to run scheduled public demonstrations can reserve a 30-minute live demonstration slot on the Demo Stage for €180. Exhibitor freight delivery and stand build-up take place on Monday 8 March 2027 between 07:00 and 20:00 under the supervision of floor safety manager Kwame Asante.</p>
<!-- /wp:paragraph -->

