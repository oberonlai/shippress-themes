<h2 class="wp-block-heading kf-value__h">What is the history and scope of Kikai Fair since 2011?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kikai Fair was established in 2011 as a dedicated biennial platform for the commercial woodworking industry. Across eight completed editions, the fair has maintained a practical focus on operating machinery rather than static showroom displays. The 2027 event represents our 9th edition and gathers 180 exhibitors across 22,000 square metres of exhibition space in Hall 4 of the Riverside Exhibition Centre. Visitors inspect 62 machines running under active power across four designated floor zones: Zone A for Panel and CNC processing, Zone B for Edgebanding and Solid wood, Zone C for Finishing, and Zone D for Dust extraction and Tooling. Every edition connects equipment engineers directly with joinery workshop owners.</p>
