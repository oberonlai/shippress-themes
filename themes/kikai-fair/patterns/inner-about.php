<h1 class="wp-block-heading">About Kikai Fair</h1>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kikai Fair is a three-day trade fair for woodworking machinery in Hall 4 of Riverside Exhibition Centre, Lindmark. Since 2011 it has had one rule: machines run under real production load instead of standing silent as showroom pieces.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Who runs it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The fair is organised by a small office of five people led by Mireille Tanaka, with technical advice from a panel of three joinery workshop owners and two machine engineers. They set the demonstration schedule and decide which stands get floor power.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What happens on the floor</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sixty-two machines are under power across three days: panel saws, CNC routers, edgebanders, finishing booths and dust extraction. A lunch talk on each day gives buyers a chance to hear from the people who run these machines every week.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Who comes</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Independent joinery shops, millwork studios and cabinet manufacturers walk the aisles beside equipment engineers. Entry is by pre-registered pass only; <a href="/#pass">request a pass</a> before 21 February 2027.</p>
<!-- /wp:paragraph -->

