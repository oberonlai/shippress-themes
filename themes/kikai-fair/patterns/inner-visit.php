<h2 class="wp-block-heading kf-value__h">What are the opening hours and pass rates for trade visitors?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The fair welcomes visitors from 09:00 to 17:30 on Tuesday 9 March and Wednesday 10 March, and from 09:00 to 16:00 on Thursday 11 March 2027. All visitors must hold a valid pass before arriving at the gates. A pre-registered trade day pass costs €25, while a three-day trade pass covering the entire fair is €45. Apprentice and student day passes cost €10 upon presentation of valid school identification. Commercial workshops sending multiple colleagues can purchase a group pass for 5 people for one day at €100. Online pass requests close on Sunday 21 February 2027.</p>
