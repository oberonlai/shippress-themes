<h2 class="wp-block-heading kf-floor__title kf-floor__title--left">What safety equipment is required on the exhibition floor?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kf-floor__lead kf-floor__lead--left"} -->
<p class="kf-floor__lead kf-floor__lead--left">Because 62 machines operate under live power across 22,000 square metres, strict personal safety standards apply across all four floor zones. Hearing protection is required near all running equipment, and free ear defenders are supplied at every stand. Visitors must remain behind marked floor barrier lines whenever cutting heads or feeding belts are engaged. Hall 4 is fully accessible to wheelchair users with step-free entrances, level aisles, and accessible restroom facilities. A staffed cloakroom at the north entrance provides secure storage for coats, luggage, and personal workwear during your time inside the exhibition centre.</p>
