<h2 class="wp-block-heading kf-value__h">How do I reach Hall 4 by public transport and car?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Riverside Exhibition Centre is situated at 12 Harbour Road in Lindmark. Public transit passengers can take tram line 3 directly to the Harbour Road stop, which is located just a four-minute walk from the Hall 4 entrance. For visitors arriving by automobile, vehicle parking is available in lot P2 at a flat daily parking fee of €12 per day. Dedicated bicycle racks are positioned directly outside the Hall 4 north entrance for attendees cycling to the venue. The main exhibition hall entrance opens into a wide foyer with direct access to ticketing scanners, an attended cloakroom, and visitor assistance desks.</p>
