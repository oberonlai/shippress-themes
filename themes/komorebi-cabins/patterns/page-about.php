<h2 class="wp-block-heading kc-sec__h sp-reveal sp-reveal--up">How was the forest village founded?</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"kc-sec__body","layout":{"type":"default"}} -->
<div class="wp-block-group kc-sec__body"><!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">Komorebi Cabins was founded in 2014 by Ilse Marten and Ruben Okafor on thirty-eight hectares of neglected mixed woodland in Hollin Vale. The land was dense with cedar and tall beech trees, and our intention from the start was to create a quiet retreat where architecture stepped back into the canopy. The word komorebi describes the interplay of sunlight filtering down through forest leaves, a phenomenon that defines life in the woods every afternoon. Rather than creating a busy resort, Ilse and Ruben designed self-catering timber dwellings where guests could chop their own kindling, cook unhurried meals on induction stoves, and sleep with open windows facing the trees. We remain dedicated to low-impact management, allowing native undergrowth, ferns, and moss to thrive undisturbed between the cabins.</p>
