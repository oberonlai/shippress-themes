<h2 class="wp-block-heading kc-sec__h sp-reveal sp-reveal--up">What are the milestones of Komorebi Cabins?</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"kc-sec__body","layout":{"type":"default"}} -->
<div class="wp-block-group kc-sec__body"><!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">Our forest village developed deliberately across three key milestones over the past decade. In 2014, we built our first four cabins, establishing our initial timber building principles and laying the gravel lanes that wind from Larch Gate. In 2017, we constructed eight more cabins, bringing the village to its permanent total of twelve whole cabins across four distinct sizes. This deliberate cap of twelve cabins ensures our woodland density remains exceptionally low and peaceful. In 2022, we built the woodshed office near the entrance, creating a central workshop for timber repairs, seasoned log storage, and guest welcomes. Every structure has been crafted from local wood by co-founder Ruben Okafor and carpenter Tobias Klein, ensuring the cabins age gracefully alongside the surrounding forest.</p>
