<p class="sp-reveal sp-reveal--up">Standard check-in takes place between fifteen o'clock and nineteen o'clock at the woodshed office, where our host will hand over your cabin key and explain the wood stove and trail routes. If you anticipate arriving after nineteen o'clock, there is no need to rush. Please notify us by email or phone during the day, and we will email you the four-digit security code for your cabin's private key box located beside the porch door. Exterior porch lights will be switched on, and your first basket of firewood and kindling will be waiting inside the hearth. For any immediate arrival questions, our phone line at +44 1632 960 418 is staffed until nineteen o'clock. We kindly remind guests that village quiet hours begin at twenty-two o'clock to ensure silence across the woodland.</p>
