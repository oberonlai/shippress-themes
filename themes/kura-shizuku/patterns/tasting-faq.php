<details class="wp-block-details"><summary>Do I need to book?</summary><!-- wp:paragraph -->
<p>Not for one to three guests. For four or more, a day's notice helps us keep the counter calm for everyone.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can children come?</summary><!-- wp:paragraph -->
<p>Yes, children are welcome with an adult and get a cup of amazake. We pour sake only for guests of legal drinking age and may ask for ID.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I am driving. Can I still taste?</summary><!-- wp:paragraph -->
<p>Please do not. Take a bottle home instead, and enjoy an amazake or koji soda on us while you choose.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I buy what I taste?</summary><!-- wp:paragraph -->
<p>Every flight is poured from bottles in the cellar, and we are happy to ship to your home.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is the tasting room accessible?</summary><!-- wp:paragraph -->
<p>The counter and the cellar shop are on one level with a step-free entrance from the gate. The brewery tour has stairs.</p>
