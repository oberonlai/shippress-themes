<p>Gsm is the weight of a square metre of the sheet. It is the figure printed beside each paper so you can tell the six apart. It is not a measure of thickness. A heavier sheet is not automatically a thicker sheet, and a light sheet is not automatically a thin one in the hand. Leila Benali’s note in the journal says the same thing: weight is not thickness.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We do not publish caliper, opacity, brightness or ink-test numbers. The figures we do print are only the ones on the packs: 45, 80, 100, 120, 250 and 300 gsm, with the size and the sheet count. If two sheets feel different, hold them to the window. That is the comparison we trust at the counter.</p>
<!-- /wp:paragraph -->

