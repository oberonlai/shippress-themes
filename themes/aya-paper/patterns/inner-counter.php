<h2 class="wp-block-heading ap-subh">How do I bring a sample?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Bring the sheet, the envelope or the page you are trying to match. It can be something you already write on, a card you want to back, or an invitation size you need to repeat. Joris lays it on the mat and cuts a sample from the paper that fits the job, not from a paper we do not stock. If the job is a long letter abroad, the sample is Airmail Bank. If it is a fountain pen, the sample is Soft Wove. If it is a card, the sample is Grey Card. You can also come with nothing and point at the drawer. Samples are cut in the morning. The shop is open Tuesday to Saturday, 10:00 to 18:00, at 17 Papierstraat, 9000 Ghent.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"className":"ap-subh"} -->
<h2 class="wp-block-heading ap-subh">What happens at the Thursday paper clinic?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>On Thursday the paper clinic runs from 16:00 to 18:00, inside ordinary opening hours. Greta Lindholm holds it. Bring a sample or a plain question about which of the six papers to use. The clinic does not add a new sheet and it does not replace the counter. Feel, cut and wrap still apply if you decide to buy. Leila Benali buys the papers from the mills. Greta’s hour is for the choice in front of you, not for a lecture and not for a measured test. We still will not quote thickness or opacity. If you cannot come on Thursday, the counter is open the rest of Tuesday to Saturday, and you can write to hello@ayapaper.example.</p>
