<p class="yg-chapter__label"><span class="yg-num">03</span> The mural</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"yg-chapter__title"} -->
<h2 class="wp-block-heading yg-chapter__title">A mountain above the water.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Above the tubs a painted mountain rises over a still lake, in soft blues that have faded with sixty years of steam. Every six years a painter comes on a closed Monday and repaints it in a single day, without a sketch.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Nobody looks at it for long. It is simply there when you lean back, the way a window is.</p>
<!-- /wp:paragraph -->

