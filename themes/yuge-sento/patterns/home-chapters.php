<p class="yg-chapter__label"><span class="yg-num">02</span> The tiles</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"yg-chapter__title"} -->
<h2 class="wp-block-heading yg-chapter__title">Small tiles, washed every night.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The bathing hall is lined with small pale tiles, laid by the founder in 1958 and mended one by one ever since. The grout lines are the only pattern; the light from the high windows does the rest.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Along the walls stand low taps with a mirror above each, and stacks of plastic stools and buckets. Take one of each, sit, and wash properly before you go near the water.</p>
<!-- /wp:paragraph -->

