<p class="yg-chapter__label"><span class="yg-num">05</span> Cold milk after</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"yg-chapter__title"} -->
<h2 class="wp-block-heading yg-chapter__title">A bottle from the cold case.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Back in the changing room, under the slow ceiling fan, there is a glass-fronted case of cold milk in small bottles: plain, coffee and fruit. You drink it standing, one hand on your hip, as everyone has since the bath opened.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Then a few minutes on the bench by the garden window, until your hair is dry enough to face the evening air.</p>
