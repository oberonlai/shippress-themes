<p class="yg-chapter__label"><span class="yg-num">04</span> The water</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"className":"yg-chapter__title"} -->
<h2 class="wp-block-heading yg-chapter__title">Two temperatures.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There are two tubs. The shallow one is kept at 41 degrees and is where most people start. The deep one is 44, and the regulars sit in it up to the chin, very still, as if waiting for a train.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Get in slowly. Keep your towel out of the water, on your head if you like. Five minutes is plenty the first time.</p>
<!-- /wp:paragraph -->

