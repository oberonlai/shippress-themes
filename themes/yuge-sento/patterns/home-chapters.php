<!-- wp:heading {"className":"yg-chapter__title"} -->
<h2 class="wp-block-heading yg-chapter__title">Through the noren.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The evening begins at a short indigo curtain over the door. You duck under it, step out of your shoes and slide them into a wooden locker with a key shaped like a paddle. The noise of the street stays outside with them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At the front desk Tadashi Arai takes your coins, hands over a towel if you need one, and asks after your mother. He has asked the same question of half the street for forty years.</p>
<!-- /wp:paragraph -->

