<!-- wp:paragraph -->
<p>Behind the bathing hall is the boiler room, warm in every season. The boiler burns clean timber offcuts from the joinery two streets away, and Kenta feeds it from one in the afternoon so the water is hot by opening.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>You can tell the bath is open from the station: a thin line of steam from the brick chimney, the tallest thing in Kitamachi 3-chome.</p>
