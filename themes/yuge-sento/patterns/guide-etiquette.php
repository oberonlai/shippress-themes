<!-- wp:heading {"className":"yg-sec__title"} -->
<h2 class="wp-block-heading yg-sec__title">Before, in and after the water.</h2>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true,"className":"yg-customs"} -->
<ol class="wp-block-list yg-customs"><!-- wp:list-item -->
<li><strong>Wash before you soak.</strong> Sit on a stool at a tap and wash your whole body, then rinse off every bit of soap. The tubs are for soaking only.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Keep towels out of the water.</strong> A small towel can come into the bathing hall; fold it on your head or leave it on the edge of the tub, never in it.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Tie long hair up.</strong> Hair should not touch the water. There are hair ties at the front desk if you forgot one.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Keep voices quiet.</strong> Talk softly, no phones in the bathing hall, and no splashing or swimming. Most people come here to be left in peace.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Drink water.</strong> Have a glass before and after; there is a jug in the changing room. Get out at once if you feel light-headed, and sit for a while.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

