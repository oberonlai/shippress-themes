<!-- wp:column {"width":"66.667%"} -->
<div class="wp-block-column" style="flex-basis:66.667%"><!-- wp:group {"className":"fj-qas sp-reveal sp-reveal--up","layout":{"type":"default"}} -->
<div class="wp-block-group fj-qas sp-reveal sp-reveal--up"><!-- wp:details {"className":"fj-qa"} -->
<details class="wp-block-details fj-qa"><summary>How is the planning fee worked out and what does travel usually cost?</summary>
<!-- wp:paragraph -->
<p>Our planning fee covers the time we spend designing your route and coordinating suppliers, kept entirely separate from your travel spending. Planning calls are free. Our fees are fixed: €290 for an anniversary weekend of two to four nights, €450 for a short escape of five to seven nights, €780 for a honeymoon of eight to sixteen nights, and €1,150 for a long journey of seventeen to thirty nights across two or more countries. Adding surprise planning is €120. Most honeymoons we plan cost between €6,000 and €14,000 for two, flights included. We never accept hotel commissions, ensuring every recommendation remains independent.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fj-qa"} -->
<details class="wp-block-details fj-qa"><summary>How do deposits, cancellations, and gifts work after booking?</summary>
<!-- wp:paragraph -->
<p>Payment of our planning fee is divided into two equal parts: fifty percent is due after we send your first tailored route, and the remaining fifty percent is due once all bookings are confirmed. If you choose to cancel before that first route is sent, there is no charge. Direct travel costs, such as lodging and transport, are paid straight to suppliers under their individual deposit terms. If friends or family members wish to contribute toward your journey, we can arrange gift contributions toward specific activities, private dinners, or rail legs.</p>
