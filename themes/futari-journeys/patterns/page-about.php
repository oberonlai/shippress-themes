<h2 class="wp-block-heading fj-h2 fj-h2--ch sp-reveal sp-reveal--up">How we work with hotels</h2>
<!-- /wp:heading --></div>
<!-- /wp:column -->

<!-- wp:column {"width":"66.667%"} -->
<div class="wp-block-column" style="flex-basis:66.667%"><!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">We operate with total independence from hotel chains and referral networks. We do not accept commissions, marketing rebates, or booking kickbacks from any lodging provider, rail operator, or local guide. By refusing commercial commissions, our planners remain free to recommend small guesthouses, historic farms, and quiet coastal lodgings chosen solely for their charm, hospitality, and quality. Whenever an accommodation partner offers a seasonal rate reduction or preferred price, that financial advantage is passed on entirely to you, keeping your interests at the center of every booking.</p>
