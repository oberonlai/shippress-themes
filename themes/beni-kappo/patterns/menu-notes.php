<details class="wp-block-details" open><summary>Can you cook around allergies?</summary><!-- wp:paragraph -->
<p>Yes, for most of them, if you tell us when you book. Dashi is made from kelp and bonito, and soy, wheat and sesame are in many dishes; we will say plainly if we cannot cook safely for you.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is there a vegetarian course?</summary><!-- wp:paragraph -->
<p>We cook a vegetable course with a kelp and shiitake dashi on the Hana and Tsuki menus, at the same price. Please ask three days ahead.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can children come to the counter?</summary><!-- wp:paragraph -->
<p>Guests aged twelve and over are welcome at both seatings and eat the full course. For younger children, ask us about booking the whole counter.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if I am running late?</summary><!-- wp:paragraph -->
<p>Every guest starts together, so please call us. We can hold the first course for about fifteen minutes; after that, we join you where the counter has reached.</p>
