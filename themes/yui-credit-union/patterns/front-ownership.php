<p>In 1961 a few dozen mill and market workers in Lindenport put five dollars each into a tin box so that nobody on their street had to borrow from a stranger. That box became Yui Credit Union, and it has never had an outside owner since.</p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p>Today 18,420 members each hold one share and one vote. They elect seven volunteer directors every March, and the directors answer to the members who elected them, not to a stock price.</p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p>We are a not-for-profit cooperative, so there is no profit to pay out. What is left after costs goes back to members as lower loan rates, higher savings rates and fewer fees.</p>
