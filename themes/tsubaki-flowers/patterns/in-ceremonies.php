<h2 class="wp-block-heading tf-cer__h">Three Formats for Intimate Gatherings</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">We specialize in three distinct ceremony formats: small weddings, naming days, and memorials. Rather than producing overwhelming arrangements, ceremony florist Aiyana Brooks focuses on scale, texture, and natural elegance. For intimate weddings, we create bridal bouquets with trailing ribbons and low table centerpieces that encourage conversation. For naming days, we choose tender blooms, soft herbs, and fresh greens that evoke new beginnings. For memorials, we compose understated foliage tributes and seasonal wreaths that offer quiet solace and honour memory with gentle dignity.</p>
