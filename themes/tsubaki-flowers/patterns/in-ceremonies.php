<h2 class="wp-block-heading tf-cer__h">The Small Ceremony Package</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">To provide clarity for couples and families, we offer a dedicated Small ceremony package starting from €420. This curated package includes one bespoke focal bouquet, low seasonal table arrangements designed for up to 30 seated guests, and 6 tailored buttonholes finished with natural twine. Every element is created using fresh market stems conditioned at our Linden Row workshop. We coordinate delivery within our 8 km radius, ensuring arrangements arrive perfectly hydrated and set in place well before your guests gather.</p>
