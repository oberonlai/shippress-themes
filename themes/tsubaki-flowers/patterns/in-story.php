<div class="wp-block-group alignfull tf-prose sp-reveal tf-fade"><!-- wp:heading {"level":2,"className":"tf-cer__h"} -->
<h2 class="wp-block-heading tf-cer__h">Why Camellia</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">The name Tsubaki is the Japanese word for camellia, chosen in honor of the sturdy shrub that has stood beside our front doorway at 14 Linden Row since before we took the keys. Camellias are winter-blooming, hardy, and understated, flourishing in cold coastal air while other garden plants sleep. That resilience reflects our floristry philosophy: we do not chase loud trends, forced blooms, or artificial dye. Instead, we let seasonal branches, garden foliage, and delicate petals speak with their authentic voices, providing steady botanical companionship throughout every season of the year.</p>
<!-- /wp:paragraph --><!-- wp:heading {"level":2,"className":"tf-cer__h"} -->
<h2 class="wp-block-heading tf-cer__h">Small on purpose</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">Our identity is defined by three enduring facts: first, we were founded in 2011; second, we have remained rooted at 14 Linden Row in Aldmere; third, our work is carried out by a tight-knit team of 7 people. These pillars anchor our daily decisions, from how early Felix departs for the flower market to the unhurried care Tomás brings to the conditioning bench. By remaining independent, local, and deliberately sized, we ensure every bouquet receives personal attention and every customer is known by name.</p>
