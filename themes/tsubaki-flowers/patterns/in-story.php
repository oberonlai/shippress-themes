<div class="wp-block-group tf-about__text sp-reveal tf-fade"><!-- wp:heading {"level":2,"className":"tf-cer__h"} -->
<h2 class="wp-block-heading tf-cer__h">The Beginning at Linden Row</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">In 2011, Mara Ellison founded Tsubaki Flowers at 14 Linden Row in Aldmere, starting with a single wooden workbench, zinc conditioning buckets, and an unwavering belief in simple, unforced floristry. The shop took its name from the mature camellia bush growing beside the entryway, whose glossy dark leaves and seasonal winter blossoms set a tone of calm permanence. From the first morning, Mara focused on flowers for ordinary household tables rather than grand formal spectacles, buying seasonal stems directly from growers and conditioning them with quiet discipline.</p>
<!-- /wp:paragraph --><!-- wp:heading {"level":2,"className":"tf-cer__h"} -->
<h2 class="wp-block-heading tf-cer__h">From Morning Market to Daily Tables</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"tf-body"} -->
<p class="tf-body">Over the years since 2011, our small business has grown steadily while keeping its working routines intact. What began as a personal project has evolved into an active team of seven florists, buyers, and delivery drivers, all united by respect for the plant's natural structure. We continue to welcome neighbours into the shop Tuesday through Saturday, providing loose seasonal stems, weekly household flower subscriptions, and tailored arrangements for small weddings and memorials. Every arrangement that leaves our Aldmere workroom is created to sit comfortably in a real room, bringing daylight, texture, and quiet character to family meals and quiet desks.</p>
