<!-- wp:paragraph {"className":"is-style-brush-note"} -->
<p class="is-style-brush-note">Kiyo Mizuhara taught her first class in her own kitchen, on a Tuesday morning, because the light was best then.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She had studied in a traditional house since she was a girl and wanted to teach the forms without the ceremony around them: no ranks, no gifts for the teacher, just the branches and a lot of looking. Her students brought their friends, and in 1998 the school moved into a former paper merchant's shop by the canal.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Her daughter Sayo took over in 2009. The Tuesday class still meets at ten.</p>
