<!-- wp:group {"className":"ih-faq","layout":{"type":"default"}} -->
<div class="wp-block-group ih-faq"><!-- wp:details -->
<details class="wp-block-details"><summary>Do the published fees include VAT?</summary>
<!-- wp:paragraph -->
<p>No. Every fee on this page excludes VAT at 23%. The HR health check is €1,450 fixed before VAT. The contract set is €980 fixed before VAT. The payroll compliance review is €1,900 fixed before VAT. The handbook and policies are €2,400 fixed before VAT. The investigation is from €3,800 before VAT. Retainer Essentials is €890 per month before VAT, and Retainer Growth is €1,850 per month before VAT.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The scoping call is €0, so there is no VAT on it. The written quote shows the published fee and states that VAT is extra. We do not convert these euro figures into another currency. A company instructing us from elsewhere in the EU pays the same euro amounts.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How fast is the quote, the report, and a reply?</summary>
<!-- wp:paragraph -->
<p>We reply to a new enquiry within 1 working day. After the free 30-minute scoping call, the written fixed quote arrives within 2 working days. The HR health check report is planned for 10 working days. A workplace investigation report is typically issued within 18 working days of the last interview. That investigation timing is typical of how we schedule the work.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Retainer clients receive a reply within 1 working day on both Essentials and Growth. Our working day is Mon–Fri 9:00–17:30, Irish time. The 30 days of follow-up questions included after a written handover use the same reply standard. Weekly check-ins sit inside the engagement and do not replace the written quote.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What does the free scoping call cover?</summary>
<!-- wp:paragraph -->
<p>The scoping call is 30 minutes. It is €0. You can take it by video or at the office, 24 Harcourt Lane, Dublin 2, D02 X940. We use the half hour to hear what is going on and to name which published item fits: health check, contract set, payroll review, handbook, investigation, or a retainer.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The call is not the paid work. Drafting, interviews, and payroll checks start only after you agree a written quote. That quote is sent within 2 working days. You can decide when it is in front of you. If we are the wrong firm, because the question is not Irish law or not one of these services, we will say so on the call.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can a company outside Dublin instruct you?</summary>
<!-- wp:paragraph -->
<p>Yes. We act for remote clients across the EU, and the scoping call is offered by video as well as at the Dublin office. Advice is limited to Irish law. If your question sits in another jurisdiction, we refer it to a partner firm. We do not publish those firms' names, and we do not advise on that other law ourselves.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The fees do not change with the client's city. A company in Cork pays the same €1,450, €1,900, or €2,400 as a company that walks to Harcourt Lane. Hours for calls are Mon–Fri 9:00–17:30, Irish time. The clients we take on employ 15 to 400 people. The written quote, the weekly check-in, and the handover are the same.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long is a retainer, and what is in the monthly fee?</summary>
<!-- wp:paragraph -->
<p>Both retainers run for a minimum of 3 months, then monthly. Essentials is €890 per month for up to 6 hours, with a reply within 1 working day. Growth is €1,850 per month for up to 14 hours, with a reply within 1 working day and a quarterly review included. VAT at 23% is extra on both.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>An hour is adviser time on your file: calls, drafting, and reading. The hour figures are caps. A retainer does not include a workplace investigation, a payroll compliance review, or a full handbook project. Those stay on their own published fees. Scope is agreed in writing before the first month, after the free 30-minute scoping call and a quote within 2 working days.</p>
