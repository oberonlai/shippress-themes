<p>Ito HR Partners was founded in 2014 in Dublin by Erika Ito, after twelve years in employment law. The practice advises companies of 15 to 400 people under Irish and EU employment law, on the work that sits beside the statute: payroll questions, handbooks, investigations and a retainer when you want someone who already knows the file.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Fees are fixed and agreed in writing before we start, so a health check, a handbook or an investigation does not drift into open-ended hours. Clients outside Dublin work with us by video from across the EU. The advice is limited to Irish law. Where a question belongs in another jurisdiction, we say so and turn to a partner firm, without naming that firm here. A written health check comes back in 10 working days.</p>
