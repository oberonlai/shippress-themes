<h2 class="wp-block-heading ih-h2">What counts as an hour</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ih-split__text","layout":{"type":"default"}} -->
<div class="wp-block-group ih-split__text"><!-- wp:paragraph -->
<p>An hour is time an adviser spends on your file. That includes calls, drafting, and reading the papers you send. The published figures are caps: up to 6 hours on Essentials and up to 14 hours on Growth. They are not targets we aim to exhaust.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We do not publish a rounding rule, a minimum slice, or a rate for hours beyond the cap. If a month is heading past the cap, we say so in the weekly check-in before extra work is done, and any extra scope is quoted in writing. Unused time is not described here as rolling forward or as lapsing. The contract you sign will state the cap you chose, and only that cap.</p>
<!-- /wp:paragraph --></div>
