<h2 class="wp-block-heading kb-chap__h">Shift hours and kitchen schedule</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kitchen operations run across three coordinated daily shift starts. The first brigade arrives at 07:00 to start long-simmered stocks, bake fresh breads, and receive seasonal deliveries. At 10:30, the second shift begins setting up the pass and prepping stations for lunch service at 11:30. The final shift commences at 16:00, refreshing mis-en-place for dinner and managing the pass through the late sitting until kitchen last orders at 23:15. This disciplined schedule allows every sauce, roast, and pastry to reach the pass in peak condition.</p>
