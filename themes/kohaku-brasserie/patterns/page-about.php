<h2 class="wp-block-heading kb-chap__h">The founding story from 2014 to today</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When Inès Marchetti and head chef Tomasz Lindqvist opened Kohaku Brasserie in 2014, their ambition was to establish an unhurried, enduring dining room for Lowmarket. Situated at 14 Arcade Row in the Old Exchange Quarter, the room began with 64 seats arranged along wide windows and dark wood paneling. In 2019, the partners expanded the dining experience by introducing 8 counter seats directly overlooking the kitchen pass. Today, the room continues to operate under the same founding commitment to hospitality, offering a warm and steady sanctuary that carries guests seamlessly through every hour of the service day.</p>
