<!-- wp:group {"className":"kb-page__cols","layout":{"type":"default"}} -->
<div class="wp-block-group kb-page__cols"><!-- wp:group {"className":"kb-page__col","layout":{"type":"default"}} -->
<div class="wp-block-group kb-page__col"><!-- wp:paragraph -->
<p>Kohaku Brasserie opened in 2014 on Arcade Row in the Old Exchange Quarter of Lowmarket. Inès Marchetti ran the floor and Tomasz Lindqvist cooked, and they agreed on one rule from the first week: the room does not close between lunch and dinner.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In 2019 we added eight counter seats at the pass, so guests can watch a plate leave the kitchen. Today the main room seats 64, the bar seats 8, and the Lantern Room takes groups of 14 seated or 20 standing.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"kb-page__col","layout":{"type":"default"}} -->
<div class="wp-block-group kb-page__col"><!-- wp:paragraph -->
<p>Lunch is a daily routine of two- and three-course set menus. The room turns quiet at 14:30 for afternoon plates and coffee, fills for dinner at 18:00 and slows again for the late sitting from 22:00 under candlelight.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Hours are Tuesday to Saturday 11:30–00:00 and Sunday 11:30–17:00. We are closed on Mondays.</p>
<!-- /wp:paragraph --></div>
