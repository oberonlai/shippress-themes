<h2 class="wp-block-heading kb-ellipse__h sp-reveal sp-reveal--up">Who founded Kohaku Brasserie?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kb-ellipse__p sp-reveal sp-reveal--up"} -->
<p class="kb-ellipse__p sp-reveal sp-reveal--up">Kohaku Brasserie was founded by Inès Marchetti and Tomasz Lindqvist, who envisioned a neighborhood establishment where hospitality and kitchen discipline carry equal weight. Inès brings decades of intuitive front-of-house warmth, training staff to anticipate guest needs with subtlety and care. Tomasz directs the culinary vision, insisting on sound classical technique, seasonal honesty, and unhurried broths. Together, they designed every detail of 14 Arcade Row to ensure the room never feels like a transient stage set, but rather a permanent civic fixture where regulars and first-time visitors feel immediately settled from their first step inside.</p>
