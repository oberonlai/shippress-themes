<h2 class="wp-block-heading kb-chap__h">The pass and the counter</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>At the back of the room sits the open pass, where head chef Tomasz Lindqvist and the brigade assemble every plate under focused heat lamps. Added in 2019, the 8 counter seats bring guests into close proximity with the rhythm of the kitchen line without interrupting its deliberate focus. From these high wooden stools, diners observe the disciplined choreography of pan, board, and seasoning, enjoying dishes handed across the counter the moment they are finished. It represents the active heart of the brasserie, bridging the craft of the kitchen directly with the life of the dining room.</p>
