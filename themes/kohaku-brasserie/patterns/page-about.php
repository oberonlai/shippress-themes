<h2 class="wp-block-heading kb-chap__h">The main dining room</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The main room holds 64 seats, dressed in crisp white linen and set with dark stoneware plates crafted for durability and quiet elegance. Tall windows bring daylight across the tables at lunch, while evening brings dim pools of warm tungsten lamplight that reflect softly against clove-brown wood surfaces. The atmosphere is calm, purposeful, and unpretentious, designed for real conversation rather than spectacle. Front of house co-founder Inès Marchetti guides the service with measured grace, ensuring that whether guests arrive for a quick two-course lunch or settle in for hours, the room feels welcoming, grounded, and attentive.</p>
