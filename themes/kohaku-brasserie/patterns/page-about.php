<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kb-page__lead"} -->
<p class="kb-page__lead">One dining room, lit from lunch to the last orders, run by two people who wanted a place that never felt hurried or shut.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

