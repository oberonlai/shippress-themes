<!-- wp:paragraph -->
<p>The bar is walk-in, always. Lunch, dinner and Sunday tables can be booked if you are eating. A drink at the counter never needs a booking, including between 21:30 and last orders. If you are a group of more than eight and you want the back room, that is the Private Room, asked for through the Book page. Children are welcome in the house until 20:00. Dogs are welcome in the bar.</p>
