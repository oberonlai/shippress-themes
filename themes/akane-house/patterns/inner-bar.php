<!-- wp:paragraph -->
<p>Three keg lines sit beside the cask: lager, stout and cider. They are there for anyone who does not want the bitter, and they run through the same sittings as the rest of the bar. We do not list a separate keg price on this page. Ask at the counter for what is on.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Jonah Whitfield works the bar in the evenings, from dinner through to close. The bar sitting itself is 21:30–23:00, after the kitchen has shut, but the taps are open from lunch onwards. Nothing on the taps is booked. Come to the counter. The room does not hold a table for a drink alone.</p>
