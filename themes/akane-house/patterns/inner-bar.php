<!-- wp:paragraph -->
<p>Callum Reid keeps the cellar and the bar. There are two house casks and one guest cask. The cellar is held at 12°C, and he checks the casks by hand. The guest cask changes; The House Letter names it on the first Thursday of each month.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>House cask bitter is £5.40 a pint. In the afternoon the cheese on toast comes with a half of it, at £12 for the plate and the half together. Cask is poured from when the doors open at 12:00 until last orders. On Tuesday to Saturday last orders are at 22:45. On Sunday the bar closes at 18:00. At 23:30, after a full day, the cellar is checked.</p>
