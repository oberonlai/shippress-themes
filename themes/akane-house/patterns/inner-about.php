<!-- wp:paragraph -->
<p>The day starts before the doors. At 08:30 the kitchen makes bread and stock. At 11:00 the pie of the day goes in. At 12:00 the doors open for lunch, which runs until 15:00. Afternoon begins at 15:00. At 17:30 the staff sit down to their meal together, before service. Dinner starts at 18:00. The kitchen closes at 21:30. Last orders are at 22:45. The doors close at 23:00. At 23:30 the cellar is checked.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Sunday is the short version of the same room: open 12:00–18:00, roast 12:00–17:00, seatings at 12:30 and 15:00. Monday is closed. Tuesday to Saturday the hours are 12:00–23:00.</p>
