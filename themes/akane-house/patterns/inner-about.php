<p class="ak-bracket">1890s</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The building is the 1890s lodge of the old madder dye works on Tanner's Row in Eastbridge. The brick is the red that gave the house its name. Akane means madder red. The lodge is one long room: bar, tables and the pass, with a back room that became the Private Room in 2016.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The front is red brick, a dark green door and two small-paned windows. Tram line 2 stops at Dye Works, three minutes' walk away. There are six bike stands outside, and the entrance and the toilet are step-free. The address is 3 Tanner's Row, Eastbridge. The house has stayed one room on purpose, open from noon to eleven on the days it is open.</p>
