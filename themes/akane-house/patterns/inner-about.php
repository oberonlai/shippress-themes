<p class="ak-bracket">Ruth and Tomas</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In 2014 Ruth Okafor and Tomas Brandt reopened the lodge as a pub with one kitchen. Ruth is co-founder, licensee and front of house. Tomas is co-founder and head cook. They kept the brick, the long room and a single bar rather than splitting the building into separate dining rooms.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The pie of the day has been on the lunch menu since that first day. The beef and ale pie is the one that stayed. In 2016 the back room became the Private Room, for tables of eight to fourteen. The Tuesday knitting group took the window table that same year, and they are still there on Tuesday afternoons. The House Letter, on the first Thursday of each month, is how we tell regulars what has changed.</p>
