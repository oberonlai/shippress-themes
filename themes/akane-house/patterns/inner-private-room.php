<p>The Private Room is the back room of the 1890s lodge, behind the long room at 3 Tanner's Row. It seats 8–14 guests at one table. It was opened as the Private Room in 2016, two years after Ruth Okafor and Tomas Brandt reopened the house.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There is no hire fee from Tuesday to Thursday. On Friday and Saturday there is a minimum spend of £150. The room is part of the same kitchen and the same bar as the rest of the house, not a separate venue. Sunday seatings in the main room are a different booking. If you are fewer than eight, book an ordinary table instead.</p>
