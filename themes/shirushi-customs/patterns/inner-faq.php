<div class="wp-block-group sc-qas"><!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>Who is the importer of record?</summary><!-- wp:paragraph -->
<p>The importer of record is the legal entity or individual responsible for ensuring that imported goods comply with all statutory customs laws, filing complete declarations, and paying assessed duties and taxes. In most commercial importations, your business serves as the importer of record, holding legal ownership of the consignment upon entry. Shirushi Customs acts as your authorized customs broker, preparing and lodging entries in your name under power of attorney, while you retain legal title and liability for the underlying commercial goods.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>Do you handle export declarations?</summary><!-- wp:paragraph -->
<p>Yes, we prepare and lodge export declarations for outbound commercial shipments, return consignments, and servicing. When small manufacturers return defective components or send machinery overseas for repair, proper export documentation is vital to secure outward processing relief or verify goods departure. We also prepare export declarations for goods previously imported under inward processing or temporary admission, ensuring customs authorities officially discharge bonded liabilities and close your customs files without outstanding penalties.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>What happens if goods are selected for examination?</summary><!-- wp:paragraph -->
<p>Border authorities periodically select consignments for physical examination, document auditing, or non-intrusive container scanning based on random risk algorithms or specific commodity profiles. When cargo is flagged at Port Ardale, our dock liaison Ravi Patel attends the examination facility at Shed 11 in person. We supervise carton handling, liaise with inspecting customs officers, clarify invoice details, and expedite post-examination documentation to minimize cargo holding times and prevent demurrage charges.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>How are import duties and taxes paid?</summary><!-- wp:paragraph -->
<p>All import duties, excise taxes, and national value-added taxes assessed by border authorities are passed through strictly at cost, with zero brokerage mark-up or handling surcharges. We advance duty payments directly through our customs bond account to secure immediate cargo release, then bill the exact disbursement to your monthly invoice. Account holders settle disbursements within our standard net 14-day payment terms, supported by itemized government assessment notices.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>What is your daily cut-off time for lodging declarations?</summary><!-- wp:paragraph -->
<p>Our standard daily lodgement cut-off is 14:00 Monday through Friday. If your complete shipping documentation—including commercial invoices, packing lists, and transport bills—is received at our desk by 14:00, our brokers audit and lodge the entry with customs authorities on the same working day. Documents received after 14:00 are scheduled for lodging first thing the next morning. This working rule ensures every declaration receives unhurried line-by-line verification.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>When should tariff classification be determined?</summary><!-- wp:paragraph -->
<p>We strongly advise establishing tariff classifications before ordering foreign components or signing supplier contracts. Having senior broker Tomás Reyes issue a formal tariff classification opinion at $120 per product allows you to calculate accurate landed costs, anticipate regulatory licence requirements, and verify trade agreement preferential rates in advance. Classifying goods after cargo arrives at Port Ardale risks unexpected duty rates, documentation discrepancies, and preventable terminal storage fees.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>How does temporary admission work for trade fairs?</summary><!-- wp:paragraph -->
<p>Temporary admission allows workshops to import exhibition samples, demonstration equipment, or tools for repair without paying full import duties and taxes, provided the goods depart within an agreed statutory timeframe. We prepare temporary admission entries for $140, posting required customs security and registering identifying serial numbers with border officers. When the goods depart, we verify re-export documentation to ensure customs authorities release pledged securities cleanly.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>Can small workshops use inward processing relief?</summary><!-- wp:paragraph -->
<p>Yes, small manufacturing workshops frequently benefit from inward processing relief when importing raw materials or specialized parts intended for assembly and eventual re-export. Lukas Brandt compiles the authorization application for $280, establishing product yield metrics and throughput accounting formulas. By suspending duty on components that are transformed into finished export goods, small workshops preserve operating working capital while staying strictly compliant with customs regulations.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>Where to deliver physical paperwork or commercial samples?</summary><!-- wp:paragraph -->
<p>Digital copies of standard invoices and waybills should be emailed to desk@shirushi-customs.example. If your clearance requires original documents, certified paper certificates of origin, or physical product samples for customs inspection, deliver them directly to our drop-off counter at Door 4, Shed 11, North Quay, Port Ardale. Our counter is staffed Monday through Friday from 08:30 to 17:00, closed on public holidays.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details sc-qa"><summary>What are your billing and payment terms?</summary><!-- wp:paragraph -->
<p>Shirushi Customs issues monthly itemized invoices managed by our accounts lead Sofia Moreau. Our invoices detail individual entry fees, line additions, and exact pass-through government duties and taxes supported by official customs vouchers. Standard payment terms are net 14 days from the invoice date via corporate bank transfer. For recurring clients, our monthly desk account provides up to 12 entries for $890 per month.</p>
