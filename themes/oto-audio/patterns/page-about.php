<p class="sp-reveal sp-reveal--up">The house range is eight products, and most of what we sell you can hear first. Three headphones, two amplifiers, one DAC, two speaker pairs. That is small enough to keep in one room and to describe without a catalogue of borrowed claims.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">The headphones are the H1 Open at €349, the H2 Closed at €299 and the P7 Planar at €890. The amplifiers are the A10 at €420 and the A40 at €1,290. The DAC is the D2 at €260. The speakers are the S5 at €780 a pair and the S8 at €2,150 a pair. Tomasz designs the two amplifiers. The rest of the range is chosen and tuned to sit with them, which is why the comparison tables keep naming the same partners: P7 with the A10 or the A40, S5 and S8 with the A40, D2 in front of either amplifier.</p>
