<h2 class="wp-block-heading oa-h2 sp-reveal sp-reveal--up has-x-large-font-size">Listening, then measuring.</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"oa-prose","layout":{"type":"default"}} -->
<div class="wp-block-group oa-prose"><!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">We tune by listening first, then measuring. The listening happens in the room, at a matched volume, on the same tracks, and the note we keep for the shop is a phrase a customer can use. Airy and wide, light bass. Close and warm, firm bass. Even and detailed, deep bass. Quiet and controlled. Relaxed and full. Neutral, low noise. Open midrange. Full range, easy bass.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">Measurement comes after that, and it is how the published figures stay fixed: driver size, impedance, weight, power, sensitivity, room size. We do not replace the words with the numbers. The H2 can measure one way and still be the headphone that keeps sound in. The S5 can be the right pair because the room is 14 m², inside its 10–20 m² span, even when someone prefers the deeper sound of the S8 on paper.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"sp-reveal sp-reveal--up"} -->
<p class="sp-reveal sp-reveal--up">The same order is what a visitor gets. You hear the difference. The table is there when you want the ohms, the watts and the grams.</p>
