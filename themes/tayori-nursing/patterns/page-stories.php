<h2 class="wp-block-heading tn-h2">Mr. Delacroix: Mastering Daily Insulin</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>After receiving a diagnosis requiring daily insulin injections, Mr. Delacroix felt overwhelmed by pen dials, needle disposal, and blood glucose monitoring. Sofia Brandt began visiting his home three times a week. Sitting beside him at his dining table, Sofia guided his hands through priming the pen, checking cartridge levels, and rotating injection sites across his abdomen. They kept a clear logbook beside his morning tea mug. As Mr. Delacroix grew comfortable reading blood glucose numbers and calculating correct dosages, visits gradually tapered from three times weekly to two, and eventually to a single check-in. Having clinical guidance in his own kitchen allowed him to develop confidence and establish a calm, predictable daily routine without hospital visits.</p>
