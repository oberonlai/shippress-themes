<h2 class="wp-block-heading tn-h2">Rosa's Rehabilitation: Walking to the Bakery</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>At 82 years old, Rosa returned home to Linden Vale following a complex hip operation. Unfamiliar stairs and hallway thresholds felt daunting, and simple tasks like boiling a kettle required substantial effort. Our physiotherapist Priya Raman initiated a six-week programme of home rehabilitation visits. Early sessions focused on safe transfers between bed and chair, followed by balancing drills using the kitchen counter. Within three weeks, Rosa was practicing steady laps along her interior corridor with a walking frame. As strength improved, Priya accompanied Rosa outside onto the pavement. By the sixth week, Rosa felt confident navigating curbs and walking down the street to her neighborhood bakery with a single walking stick. Her experience illustrates how patient, home-based rehabilitation helps restore everyday mobility step by step.</p>
