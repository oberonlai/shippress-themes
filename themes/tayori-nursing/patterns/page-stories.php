<h2 class="wp-block-heading tn-h2">The Haddad Family: Supported at Home</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>During their father's final weeks with advanced illness, the Haddad family wished for him to remain resting in his own bedroom, surrounded by familiar photographs and the presence of his grandchildren. Lead nurse Jonah Abebe coordinated a comprehensive palliative visit schedule, managing medication administration, skin comfort, and symptom relief. Crucially, the family was enrolled in our 24-hour on-call line. When questions arose late in the evening regarding breathing changes or dose timing, Tomás Ferreira and Jonah provided immediate phone guidance and conducted evening visits whenever necessary. This steady clinical presence enabled the family to focus on companionship and quiet farewells, confident that professional medical assistance was always within reach just down the road in Linden Vale.</p>
