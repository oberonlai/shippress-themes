<h2 class="wp-block-heading tn-h2 tn-trow__h">How We Work in Your Home</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"tn-trow__p"} -->
<p class="tn-trow__p">We believe home healthcare must adapt to your domestic rhythm rather than disrupting it. Our visits are scheduled with sufficient time for thorough clinical observation, unhurried conversations at the kitchen table, and practical assistance. We coordinate closely with your attending physician, sharing our visit notes and medication updates directly so that care remains coherent. Because we operate within a tight 8 km service area, our nurses spend less time in transit and more time listening, checking vitals, and supporting your family through every stage of treatment.</p>
