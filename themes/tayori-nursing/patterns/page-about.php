<h2 class="wp-block-heading tn-h2 tn-trow__h">Founded on Quiet, Everyday Care</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"tn-trow__p"} -->
<p class="tn-trow__p">In 2017, registered nurse Mira Castell founded Tayori Nursing to provide unhurried, personal clinical care in the rooms where people already live. The Japanese word tayori means someone to rely on, and our small practice was built on that quiet premise. After years in acute hospital settings, Mira recognized that recovery, long-term illness, and end-of-life care often proceed best in familiar surroundings. From our single office at 14 Orchard Row in Linden Vale, our team travels to households within an 8 km radius, ensuring every patient receives calm and steady attention.</p>
<!-- /wp:paragraph --></div>
