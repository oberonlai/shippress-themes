<h2 class="wp-block-heading">Five steps, one <em>minute</em></h2>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true,"className":"is-style-steps"} -->
<ol class="wp-block-list is-style-steps"><!-- wp:list-item -->
<li>Boil the water, then pour it into the cups first: it cools by about ten degrees each time it is poured.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Put 4 g of leaf per cup into the warmed pot.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Pour the water from the cups onto the leaf and wait one minute. Don't stir.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Pour a little into each cup in turn, back and forth, so every cup is equally strong.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Shake out the last drop: it is the best one. Leave the lid off so the leaf can breathe.</li>
