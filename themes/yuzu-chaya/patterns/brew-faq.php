<div class="wp-block-group yc-faq"><!-- wp:details -->
<details class="wp-block-details"><summary>Do I need a thermometer?</summary><!-- wp:paragraph -->
<p>No. Boiling water poured into a cup and then into the pot drops to about 80°C; pour it through one more cup for 70°C.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What water should I use?</summary><!-- wp:paragraph -->
<p>Soft tap water is fine, filtered if it tastes of chlorine. Very hard mineral water makes green tea flat and dull.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Why does my sencha taste bitter?</summary><!-- wp:paragraph -->
<p>Almost always it is too hot or too long. Try 70°C for one minute before you use less leaf.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How should I store the tea?</summary><!-- wp:paragraph -->
<p>Sealed, cool and away from light and smells. Opened matcha belongs in the fridge; everything else in a cupboard, used within two months.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I brew it in a mug?</summary><!-- wp:paragraph -->
<p>Yes: use a strainer or a tea bag you fill yourself, and take the leaf out on time. A kyusu just makes the second cup easier.</p>
