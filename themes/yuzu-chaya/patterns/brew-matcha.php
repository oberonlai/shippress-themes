<!-- wp:list {"ordered":true,"className":"is-style-steps"} -->
<ol class="wp-block-list is-style-steps"><!-- wp:list-item -->
<li>Soak the whisk in warm water for a minute, and warm the bowl.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Sift 2 g of matcha (two small scoops) into the empty, dry bowl.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Add 70 ml of water at 80°C.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Whisk fast from the wrist in an M shape for fifteen seconds, then lift the whisk from the middle of the foam.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

