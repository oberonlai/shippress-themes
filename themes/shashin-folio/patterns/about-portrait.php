<div class="wp-block-group sf-about__bio"><!-- wp:paragraph {"className":"is-style-lead"} -->
<p class="is-style-lead">Born in Kanazawa in 1988, I came to photography late and sideways — through a darkroom class taken to fill the winter after leaving an architecture office.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Since 2014 I have made long, slow series about places at the edges of the day: beaches before sunrise, platforms after the last train, rooms in the minutes before anyone wakes. I work almost entirely on black-and-white film, and print everything myself in a small darkroom in Kiyosumi.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Alongside my own work I photograph for magazines, architects and a few hotels and brands that are happy to wait for the right light. Two books, <em>Last Train</em> and <em>Low Tide</em>, are published by Hiru Press.</p>
