<!-- wp:paragraph {"className":"hl-prow__note"} -->
<p class="hl-prow__note">This residential project transformed an awkward structural alcove beneath a flight of stairs into a dedicated evening reading nook. Space constraints ruled out a freestanding floor lamp, so we specified a single Lantern Wall Light at €310. Mounted directly onto the lime-plaster wall, its brass swing-arm mechanism allows the reader to pull the light forward over an armchair or push it flush against the wall when not in use. The natural linen cone shade shields peripheral glare, casting direct 2700K illumination solely onto open books.</p>
