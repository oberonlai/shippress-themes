<!-- wp:paragraph {"className":"hl-prow__note"} -->
<p class="hl-prow__note">Designed for a busy family household, this project illuminated a solid oak kitchen table for six. The lighting needed to support cooking tasks, homework, and evening meals without overpowering the room. We installed two Quay Pendants (€280 each), spaced evenly along the table's centerline. Their 32 cm spun-aluminium domes cast clean pools of 2700K downward light over dinner plates while preventing glare into neighbouring open-plan living areas. Controlled by an inline dimmer, the pendants transition effortlessly from bright dinner preparation to intimate evening conversation.</p>
