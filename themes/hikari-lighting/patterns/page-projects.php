<!-- wp:paragraph {"className":"hl-prow__note"} -->
<p class="hl-prow__note">Café Noor is a neighbourhood dining room seating 28 guests. The challenge was to deliver enough light for dining and reading menus while preserving a warm, calm evening ambience throughout the room. We hung four Low Pendant Trios (€760 each) across the dining floor, positioned between 65 and 75 cm above the oak dining tables. Each fixture's three 18 cm smoked-glass pendants soften bulb brightness while focusing warm 2700K light cleanly onto tabletops. The arrangement maintains clear eye lines between seated patrons while lending privacy to every table.</p>
