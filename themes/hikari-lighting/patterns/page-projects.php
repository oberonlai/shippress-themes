<!-- wp:paragraph {"className":"hl-prow__note"} -->
<p class="hl-prow__note">Completed in 2025, this project involved a stone bay living room in the Kralingen district of Rotterdam. The owners required an evening setting that felt intimate without leaving dark corners unaddressed. We positioned a Bay Floor Lamp (€690) beside the low sofa, casting a warm downward pool through its natural linen drum shade onto the floor. Across the room, two Cairn Table Lamps (€420 each) were placed on stone side ledges. Together, the three fixtures establish balanced 2700K layers across lime-plaster surfaces without requiring any harsh central ceiling illumination.</p>
