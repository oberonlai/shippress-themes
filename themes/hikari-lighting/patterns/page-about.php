<!-- wp:heading {"level":2,"className":"hl-h3"} -->
<h2 class="wp-block-heading hl-h3">Workshops, Materials, and Bench Repairs</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hl-prose__r","layout":{"type":"default"}} -->
<div class="wp-block-group hl-prose__r"><!-- wp:paragraph -->
<p>We commission our lighting directly from six independent workshops: Atelier Vermeul, Norrland Spun Metal, Casa Trevi Ceramica, Lindgren Paper Shades, Oakhurst Turnery, and Studio Pellan. These makers craft our spun aluminium shades, turned timber components, ceramic bases, and hand-finished paper screens using honest, durable materials.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>To ensure our pieces last for decades, we operate an active repair bench at Steenkade 14. Here, vintage lamps are rewired from €65, and replacement shades or cords are fitted to ensure that well-made lighting stays in service across generations.</p>
