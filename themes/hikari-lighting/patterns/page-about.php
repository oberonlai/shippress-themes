<!-- wp:heading {"level":2,"className":"hl-h3"} -->
<h2 class="wp-block-heading hl-h3">Our Founding and Approach</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"hl-prose__r","layout":{"type":"default"}} -->
<div class="wp-block-group hl-prose__r"><!-- wp:paragraph -->
<p>Founder Ines Varga established Hikari Lighting at Steenkade 14 in Rotterdam in 2016. Her conviction was that light should serve as the quietest furniture in the room, creating warmth and spatial balance without visual noise. Instead of offering hundreds of mass-produced fixtures, we focus on six pieces at a time, each chosen for one specific room.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Every fixture we provide is calibrated to 2700K warm white, casting gentle illumination over limestone, oak, and plaster surfaces. We believe rooms should not be flooded with uniform brightness, but defined by thoughtful, low pools of light.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
