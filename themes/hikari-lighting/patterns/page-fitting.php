<h2 class="wp-block-heading hl-h3">Four questions</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3,"className":"hl-faq__q"} -->
<h3 class="wp-block-heading hl-faq__q">How does the seven-day home trial work?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>You may select up to three pieces from our current showroom floor to borrow for seven days with a refundable deposit of €50. This trial lets you observe how the fixtures illuminate your actual walls, furniture, and finishes once night falls. If you decide to keep a piece, your €50 deposit is credited directly to your order total. If the lamps do not suit your space, simply return them to Steenkade 14 within the seven-day period for a full refund.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"className":"hl-faq__q"} -->
<h3 class="wp-block-heading hl-faq__q">What is included in a written light plan?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A written light plan provides a comprehensive layout drawn by lighting planner Tomasz Rehn. It specifies precise mounting coordinates, suspension heights, dimmer circuits, and 2700K bulb assignments for every room. The plan costs €480 for private homes up to 6 rooms and €650 for small dining rooms or cafés up to 40 seats. The documentation provides clear guidance that you or your electrician can implement directly, ensuring consistent warmth and balance throughout the property.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"className":"hl-faq__q"} -->
<h3 class="wp-block-heading hl-faq__q">Can you rewire an existing or vintage lamp?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Yes. At our Steenkade 14 workshop, technician Sam Okoro undertakes the rewiring and repair of vintage lamps starting from €65. We disassemble aged fittings, inspect sockets, replace frayed wiring with new 2.5 m braided cords, install modern grounded European plugs, and ensure dimmer compatibility. We test every fixture on the bench before returning it to you, allowing cherished historic lighting to function safely with modern 2700K bulbs.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"className":"hl-faq__q"} -->
<h3 class="wp-block-heading hl-faq__q">Who handles the physical installation?</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Physical installation is carried out by our partner electrician, Joris van Dalen, starting from €85 per fitting. Joris handles ceiling pendant suspensions, wall sconce bracket mounting, cable routing, and compatible dimmer integration. Having our partner electrician complete the work ensures every piece is safely secured, aligned with your light plan, and adjusted to the correct hanging height.</p>
