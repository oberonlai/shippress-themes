<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Wire, <em>then wait.</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Styling is mostly waiting. Copper or aluminium wire guides a branch for one season, never longer, and comes off before it bites the bark.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We wire in late autumn and winter, when the tree is resting and a branch bends without cracking.</p>
<!-- /wp:paragraph --></article>
<!-- /wp:group -->

