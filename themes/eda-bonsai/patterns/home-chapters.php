<p class="is-style-label">Chapter IV · Repotting</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Every few <em>springs.</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Young trees every two years, old ones every four or five, just as the buds swell in March.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We comb out a third of the roots, refresh the soil and settle the tree back into the same pot, or one a little larger.</p>
