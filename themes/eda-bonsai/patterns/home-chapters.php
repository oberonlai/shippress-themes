<!-- wp:heading -->
<h2 class="wp-block-heading">A trunk thickens <em>a ring at a time.</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every spring a tree lays down one thin ring of wood. Our trees stay in the ground for years, sometimes a decade, so the trunk can thicken before it is lifted into a pot.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The age on each label is counted from the cutting or the seed, and written in the nursery book beside the bed it grew in.</p>
<!-- /wp:paragraph --></article>
