<p class="is-style-label">Chapter III · Watering</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:heading -->
<h2 class="wp-block-heading">The daily <em>rhythm.</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Water when the surface of the soil turns pale, not by the clock: in July that can be twice a day, in January once a week.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Water until it runs from the holes, then once more a minute later, so the whole root ball drinks.</p>
<!-- /wp:paragraph --></article>
<!-- /wp:group -->

