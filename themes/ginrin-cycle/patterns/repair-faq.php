<details class="wp-block-details"><summary>Do you repair bicycles you did not build?</summary><!-- wp:paragraph -->
<p>Yes. Most of our repair bench is other people's bicycles: commuters, old road frames, folding bikes. We do not work on electric motors or suspension forks.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long will I wait?</summary><!-- wp:paragraph -->
<p>Small jobs are often done while you wait or the same day. A full service takes about three days. The ticket always has a date on it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you fix a cracked steel frame?</summary><!-- wp:paragraph -->
<p>Usually. Steel can be re-brazed and reinforced; we look at it first and tell you honestly whether it is worth it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you sell parts?</summary><!-- wp:paragraph -->
<p>We fit good, serviceable parts at cost and show them to you before they go on. Bring your own if you prefer.</p>
