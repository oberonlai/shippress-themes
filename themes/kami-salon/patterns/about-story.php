<h2 class="wp-block-heading">Ten years of fashion shoots, then one room of our own</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Mika Kirishima spent a decade cutting hair for magazines, runways and music videos. The work was fast and exciting, and nobody ever came back. Kami was the opposite idea: a small room where people return, and the cut grows out as well as it looks on day one.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We still borrow from that world: a hard line, an honest mirror, colour that is not shy. But we cut for real life. You will be asked how you dry your hair, how long you have in the morning, and what you never want again.</p>
<!-- /wp:paragraph -->

