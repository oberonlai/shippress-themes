<!-- wp:paragraph -->
<p>Aki Morisawa draws every frame at full scale on gridded paper. Ren Tobita cuts and solders the titanium; Yui Kanzaki polishes the acetate and fits each pair at the counter. Runs are small: forty or fifty of each frame a season.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We use beta titanium for temples that spring back, pure titanium for rims that hold their shape, and plant-based acetate for colour.</p>
