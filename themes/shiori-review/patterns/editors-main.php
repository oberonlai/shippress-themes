<p class="is-style-lead">Shiori means bookmark. We chose the name because a quarterly is read slowly, over weeks, and the ribbon sewn into every issue keeps your place between sittings.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The review publishes essays and poems only: no reviews, no interviews, no news. Each issue gathers around one plain subject, chosen a year ahead and announced in the letter between issues.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We are funded by subscribers and by a small printing grant from the fictional Hinoe Arts Fund. There is no advertising, and there never will be.</p>
