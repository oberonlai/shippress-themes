<h2 class="wp-block-heading fl-h fl-h--l">Biographical Note</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"fl-lead"} -->
<p class="fl-lead">Clara Hsu is an essayist based in Taipei whose writing examines ordinary spaces, urban solitude, and morning routines. Her second collection, Small Hours, is published by Fumi Press.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"fl-proc"} -->
<p class="fl-proc">Clara Hsu was born in 1986 in Kaohsiung and currently lives and works in Taipei. Her writing focuses on the intersections of urban life, personal memory, and sustained daily observation. Working primarily in the early morning hours, Hsu has developed a reputation for measured, reflective prose that captures the overlooked textures of Taiwanese cities. Small Hours: Essays from a Corner Table represents four years of daily writing at a neighborhood café in Da'an District, following the progression of seasons and city life between 2022 and 2026.</p>
