<h2 class="wp-block-heading fl-h fl-h--l">Publishing History and Working Method</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"fl-proc"} -->
<p class="fl-proc">Hsu's publishing history traces a steady dedication to independent small-press literature. In 2014, she published her first essay in a small-press zine, establishing her interest in short personal essays. In 2018, Fumi Press published her debut collection, Window Seat. Beginning in 2022, Hsu committed to writing at the same café table every morning, producing the essays that culminated in her 2027 collection Small Hours. She drafts entirely by hand using a fountain pen and lined notebooks, focusing on the immediate sensory details of her surroundings.</p>
