<!-- /wp:image -->

<!-- wp:paragraph {"className":"fl-label"} -->
<p class="fl-label">The Corner Table: Part Two</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">To write here is not to withdraw from the city, but to sit quietly inside its preparation. First comes the hollow clatter of metal roll-up shutters being pulled upward two doors down. Then the wet hiss of a street cleaner's broom sweeping fallen leaves into small mounds against the curb. A cyclist in a yellow raincoat glides past without pedaling, coasting down the gentle slope toward Da'an Forest Park. In these early hours, before conversation fills the room, every sound carries a distinct weight and clarity.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-label"} -->
<p class="fl-label">The Corner Table: Part Three</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">I have kept this morning routine since 2022, sitting at the exact same corner table with a fountain pen and a lined notebook. One does not need extraordinary events to understand a neighborhood; one only needs to remain in place long enough for the ordinary to reveal its pattern. The sunlight arrives around seven, cutting an ivory diagonal across the paper and illuminating the dust motes suspended in the quiet room. By the time the second pot of coffee brews, the first page is finished.</p>
