<p class="fl-lead">Read the opening essay from Small Hours: Essays from a Corner Table by Clara Hsu. Written in the stillness of dawn, this piece introduces the quiet observation that anchors the collection.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-label"} -->
<p class="fl-label">The Corner Table: Part One</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess fl-first"} -->
<p class="fl-ess fl-first">The chair is bentwood, polished smooth at the armrests by years of coats and elbows. By six in the morning, the streetlamps along the avenue are still casting amber circles on the pavement, but the bakery across the lane has already switched on its fluorescent tubes. I sit here before the milk delivery arrives, watching the steam rise from my first cup of black coffee. The table itself is round, small enough that my notebook and saucer occupy almost the entire marble surface.</p>
<!-- /wp:paragraph -->

<!-- wp:image {"aspectRatio":"3/2","scale":"cover","sizeSlug":"full","linkDestination":"none","className":"fl-ph sp-reveal sp-reveal--zoom"} -->
