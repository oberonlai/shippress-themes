<h1 class="wp-block-heading fl-h fl-h--xl">The Corner Table</h1>
<!-- /wp:heading --><!-- wp:paragraph {"className":"fl-label"} -->
<p class="fl-label">From the first essay · Small Hours, Fumi Press, 2027</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"fl-ess fl-first"} -->
<p class="fl-ess fl-first">The light enters Da'an District along the wet asphalt before the first scooter passes. At seven in the morning, the corner table is already wiped down, cool to the palm, holding a circle of grey sky from the high eastern window.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">To sit in the same chair every morning for four years is not an exercise in discipline so much as an agreement with stillness. You learn the precise interval between the bakery shutters rattling upward and the arrival of the number twenty bus. You watch how rain gathers on the awning above the fruit stall opposite, hesitating at the seam before dropping onto the paving stones in rhythm.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">Everything that matters in an essay begins as something too ordinary to mention. A cup of black coffee cooling beside an open notebook, the sound of spoons against porcelain, the unfamiliar quiet of a capital city before its machinery turns over. In these small hours, before the day demands an account of itself, the world presents its surfaces without insistence.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">The woman who runs the counter has stopped asking what I want. She sets the cup down on the left, where my hand will find it without looking, and returns to her radio, which murmurs a weather report no one is listening to. We have never exchanged more than a dozen sentences. It is, I think, one of the more durable friendships of my adult life.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">I used to believe that writing required distance, that one had to leave a place in order to describe it. The corner table taught me the opposite. Attention is a kind of travel, and the shortest journeys are often the strangest: from the saucer to the window, from the window to the man folding his umbrella in the doorway, from the umbrella to a memory of my grandmother's kitchen in Kaohsiung, where the same grey light fell on a different table.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">By eight the room begins to fill. Chairs scrape, a laptop opens, someone laughs too loudly at a message and then looks around, embarrassed. The hour I came for is over, and what remains is the ordinary day, which I am now ready, a little, to meet.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"fl-ess"} -->
<p class="fl-ess">The notebook stays open for a minute longer. Then I close it, finish the coffee, and leave the chair exactly where I found it, for tomorrow.</p>
