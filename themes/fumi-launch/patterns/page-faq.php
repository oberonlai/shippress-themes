<h2 class="wp-block-heading fl-h fl-h--xl">Frequently asked questions</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"fl-lead"} -->
<p class="fl-lead">Find answers to common questions regarding editions, shipping, launch events, and reading groups for Small Hours. For further assistance, our studio team is available throughout the working week.</p>
<!-- /wp:paragraph --><!-- wp:details {"className":"fl-faq","showContent":true} -->
<details class="wp-block-details fl-faq" open><summary>When will Small Hours be published and when do pre-orders ship?</summary><!-- wp:paragraph -->
<p>Small Hours will be officially published on 18 March 2027 in both English and Traditional Chinese editions. Pre-orders close on 10 March 2027. All pre-ordered signed hardcover copies, book-club packs, and launch bundles will ship on 11 March 2027 directly from our studio in Da'an District, Taipei. Digital editions, including the EPUB ebook and author-read audiobook, will be delivered via email download links on publication day.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>What is included in the signed first printing hardcover edition?</summary><!-- wp:paragraph -->
<p>The signed first printing of Small Hours is strictly limited to 1,500 numbered hardcover copies in English, priced at USD 34. Each copy is printed on quality book paper, measures 14 × 21 cm across 248 pages, and includes an individualized hand-numbered colophon signed by Clara Hsu. Cover design and typography are created by Noor Haddad. Once these 1,500 copies sell out, subsequent hardcover printings will not be signed or numbered.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>Can I cancel or refund my pre-order if my circumstances change?</summary><!-- wp:paragraph -->
<p>Yes, all pre-orders placed through Fumi Press are fully refundable until pre-orders officially close on 10 March 2027. If you need to cancel your order, change your delivery address, or switch editions, simply send an email to hello@fumipress.example with your order details. Our team processes refund requests within two working days, returning funds directly to your original payment method without deduction or cancellation fees.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>How much does shipping cost and how long does international delivery take?</summary><!-- wp:paragraph -->
<p>Orders ship worldwide from Taipei using tracked postal and courier services. Delivery typically takes between 5 and 12 working days depending on destination customs clearance. Shipping rates are calculated at checkout based on destination country and parcel weight. Pre-ordered copies ship on 11 March 2027 so that readers receive their books as close as possible to the official 18 March 2027 publication date.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>What does the Launch Bundle include and how do event seats work?</summary><!-- wp:paragraph -->
<p>The Launch bundle is priced at USD 58 and includes three items: a signed and numbered hardcover copy of Small Hours, a custom blank canvas tote bag, and one reserved seat at a launch reading of your choice. Bundle holders receive an email confirmation two weeks before their selected city's event date with check-in instructions. Event seats are available in Taipei, Tokyo, Paris, or Berlin.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>What is included in the Book-club pack and printed reading guide?</summary><!-- wp:paragraph -->
<p>The Book-club pack costs USD 110 and contains six paperback copies of Small Hours alongside a printed reading guide. You may select paperbacks in English, Traditional Chinese, or an even mix of both. The guide provides background context on the collection's four-year creation, suggested pacing across three reading sessions, and ten structured discussion questions developed with input from teachers and reading group organizers.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>Are the launch events free and how do I reserve a seat?</summary><!-- wp:paragraph -->
<p>All four launch events—in Taipei, Tokyo, Paris, and Berlin—are free of charge, with attendance strictly capped at 60 seats per venue to maintain an intimate atmosphere. All readings begin at 19:30 local time. Bundle holders receive priority seat reservations two weeks prior to the date. Remaining seats can be booked by sending an email to hello@fumipress.example indicating your preferred city and guest details.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>Who narrates the audiobook edition and what is its running time?</summary><!-- wp:paragraph -->
<p>The audiobook edition of Small Hours is narrated directly by the author, Clara Hsu, providing an authentic interpretation of her prose rhythms. Recorded in a quiet studio in Taipei, the complete unabridged reading has a total duration of 6 hours and 40 minutes. The audiobook is priced at USD 18 and will be delivered on 18 March 2027 as high-bitrate, DRM-free audio files.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>Is the ebook compatible with standard e-readers and tablets?</summary><!-- wp:paragraph -->
<p>Yes, the Ebook edition is priced at USD 12 and comes as a universal, DRM-free EPUB file compatible with all standard e-readers, tablets, and reading applications. Uniquely, the digital purchase includes complete text files for both the English and Traditional Chinese editions, allowing bilingual readers to compare translations side by side. Download links are distributed via email on publication day, 18 March 2027.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>What early reader feedback has Small Hours received?</summary><!-- wp:paragraph -->
<p>Early copies were shared with select readers and booksellers. Mina Cho, a bookseller in Taipei, described the essays as a companion that returns dignity to solitary city routines. Rafael Ortiz, a teacher and reading group host, found that the text invited his students to observe their daily commutes with newfound patience. Hanna Weber, a reader in Berlin, noted how the quiet tone settled her busy evenings.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>How can I contact Fumi Press with questions or press inquiries?</summary><!-- wp:paragraph -->
<p>You can contact Fumi Press by emailing hello@fumipress.example. Our studio in Da'an District, Taipei operates Monday through Friday from 10:00 to 18:00 GMT+8. Our team reads every message and responds within two working days. For international rights, translation licensing, and media interview requests, our rights manager Elena Brandt handles inquiries directly from our Berlin press office.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"fl-faq"} -->
<details class="wp-block-details fl-faq"><summary>Are there any plans for additional translations or subsequent editions?</summary><!-- wp:paragraph -->
<p>Small Hours launches on 18 March 2027 simultaneously in English and Traditional Chinese, reflecting Clara Hsu's bilingual readership. Fumi Press focuses entirely on these two primary editions alongside the signed first printing of 1,500 numbered hardcovers. Additional translation rights and international licensing inquiries are managed through Elena Brandt in Berlin. Any future announcements regarding foreign language editions will be shared through our reader newsletter.</p>
