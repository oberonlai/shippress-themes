<h2 class="wp-block-heading fl-h fl-h--xl">About the Collection</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"fl-lead"} -->
<p class="fl-lead">Small Hours: Essays from a Corner Table brings together twenty-one essays by Clara Hsu, observing city life from morning light to evening rain. Published simultaneously in English and Traditional Chinese, the collection reflects four years of sustained attention.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"fl-proc"} -->
<p class="fl-proc">Written between 2022 and 2026 at a single café table in Da'an District, Taipei, Small Hours gathers twenty-one essays across 248 pages. Clara Hsu records the subtle rhythm of early mornings, street vendors setting up their stalls, passing commuters, and the quiet transitions of weather. The book offers calm reflections on solitude, ordinary routines, and the gradual passage of time in a modern metropolis. Designed with a format of 14 × 21 cm, the volume is presented as an intentional physical object meant to be read slowly over quiet mornings.</p>
