<details class="wp-block-details hk-faq__item"><summary>My carbon knife has turned grey and blue. Is it rusting?</summary><!-- wp:paragraph -->
<p>No: that is patina, a thin oxide layer that actually protects the steel. Orange spots are rust. Rub them off with a cork and a little baking soda, then dry and oil.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"hk-faq__item"} -->
<details class="wp-block-details hk-faq__item"><summary>How often should I sharpen?</summary><!-- wp:paragraph -->
<p>A home cook: three or four times a year on a 1000 stone, with a few light strokes on a strop in between. If a ripe tomato skin starts to slide, it is time.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"hk-faq__item"} -->
<details class="wp-block-details hk-faq__item"><summary>Can I use a honing steel?</summary><!-- wp:paragraph -->
<p>Gently, on stainless knives only. On hard carbon blades a steel can chip the edge. A leather strop or a fine stone is kinder.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

