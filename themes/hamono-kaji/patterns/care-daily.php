<h2 class="wp-block-heading">Wash, dry, <em>put away</em></h2>
<!-- /wp:heading -->

<!-- wp:image {"aspectRatio":"3/2","scale":"cover","sizeSlug":"full","linkDestination":"none","className":"is-style-plate"} -->
