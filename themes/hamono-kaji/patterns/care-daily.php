<!-- wp:list {"ordered":true,"className":"is-style-steps"} -->
<ol class="wp-block-list is-style-steps"><!-- wp:list-item -->
<li><strong>Wash by hand, straight after use.</strong> Warm water, a soft sponge, a little soap. Wipe from the spine towards the edge.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Dry it at once.</strong> Carbon steel rusts if it sits wet. A dry cloth along both faces, then the handle.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Never the dishwasher.</strong> Heat, salt and rattling dull the edge and crack the handle in a single cycle.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Cut on wood.</strong> Hinoki, cypress or soft end-grain. Glass, stone and steel boards chip a hard edge.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Oil carbon steel now and then.</strong> One drop of camellia oil on a cloth, wiped thin, before it goes away for a while.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Store it covered.</strong> In a wooden saya, a linen wrap or on a magnetic rack, never loose in a drawer.</li>
<!-- /wp:list-item --></ol>
