<!-- wp:paragraph -->
<p>Ruth is 78. One morning she brought her medicines to Queen Street East in a canvas shopping bag, twelve boxes and bottles in a heap on the consultation table. Some had come from this counter. Some she had kept at home and was no longer sure about. Leila Haddad sat with her and they sorted the boxes into rows.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>This was a medicine review, not a sales conversation. The appointment is 30 minutes and the fee is $35.00. Together they made one list instead of twelve boxes, talked through what might change, and Ruth took her own copy home. Leila phoned afterwards, the follow-up call that closes a review. Ruth said she felt more confident telling the boxes apart. Leila did not promise that the list would do more than that, and this pharmacy does not promise results.</p>
<!-- /wp:paragraph -->

