<h2 class="wp-block-heading ib-prose__h">The ninety-minute schedule</h2>
<!-- /wp:heading --><!-- wp:paragraph -->
<p>Your initial appointment follows a structured sequence designed to avoid unnecessary delays. For an 08:30 arrival, check-in takes ten minutes at reception, followed by fifteen minutes with our cardiac nurse for vital signs, resting blood pressure, and a twelve-lead electrocardiogram. At 08:55, chief cardiac sonographer Priya Natarajan conducts a thirty-minute transthoracic echocardiogram. At 09:25, you spend twenty-five minutes with your cardiologist reviewing ultrasound images and clinical history. The final ten minutes, concluding at 10:00, are dedicated to agreeing on a treatment plan and scheduling follow-up reviews.</p>
