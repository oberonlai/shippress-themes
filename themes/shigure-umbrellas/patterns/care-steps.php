<h3 class="wp-block-heading sg-step__title">Furl it loosely</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"sg-step__text"} -->
<p class="sg-step__text">Wrap the canopy round the shaft without twisting, and close the tie over the gores, not over the ribs.</p>
