<h3 class="wp-block-heading sg-step__title">Mind the wind</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"sg-step__text"} -->
<p class="sg-step__text">Turn into a gust rather than away from it. If the canopy inverts, close it slowly so the ribs fold back on their own.</p>
