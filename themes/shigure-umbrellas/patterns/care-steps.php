<!-- wp:heading {"level":3,"className":"sg-step__title"} -->
<h3 class="wp-block-heading sg-step__title">Open it to dry</h3>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"sg-step__text"} -->
<p class="sg-step__text">Never furl a wet umbrella. Open it halfway in a hall or bath, out of the sun, until the fabric is dry to the touch.</p>
