<p class="dk-body sp-reveal sp-reveal--up">Denki Components B.V. began in 1987 with fourteen people and one line of disc capacitors in a rented hall on the edge of Eindhoven. Today 420 colleagues run the plant in three shifts, around the clock, making multilayer ceramic capacitors, thick-film chip resistors, power inductors and ferrite chip beads under one roof, from powder to taped reel.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"dk-body sp-reveal sp-reveal--up"} -->
<p class="dk-body sp-reveal sp-reveal--up">Ingrid Vass, our managing director since 2004, puts it simply: a part is only useful if the thousandth reel behaves like the first. So we measure every lot, publish the figures each month and keep the catalogue to the 1,240 part numbers we can make repeatably. Engineers building hearing devices, motor controllers and meters order from us because the next delivery looks like the last one.</p>
