<h2 class="wp-block-heading ba-ib__h ba-grad">What Should You Bring to Class?</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>Students should bring a clean, durable notebook and a reliable pen for recorded observations. All glassware, spittoons, tasting sheets, bottles, and lunch provisions are provided by the academy. Wearing standard service black clothes is completely optional; comfortable, clean casual clothes suitable for standing practice are entirely appropriate. Please do not wear any perfume, scented cologne, scented hand creams, or fragranced aftershave on Monday mornings. Strong scents disrupt sensory evaluation for all twelve tasters sitting around the oak table. Arrive well rested and ready to taste precisely at 09:30.</p>
