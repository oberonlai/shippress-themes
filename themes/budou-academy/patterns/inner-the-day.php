<h2 class="wp-block-heading ba-ib__h ba-grad">Morning: Palate, Blind Flight, and Regional Law</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>The school day begins promptly at 09:30 with coffee and palate warm-up exercises to awaken the senses. At 10:00, students face Flight one: six wines blind. Instructors guide the table through structural analysis, focusing on acid, tannin, alcohol, and fruit profile without bottle labels. At 11:30, we move to The map: region, grape, law. This segment connects sensory observations to appellation rules, soil types, and climate traditions. Rather than memorizing dry geographical facts, students understand precisely why a wine tastes as it does based on its place of origin and regional legal requirements.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"ba-ib__row sp-reveal sp-reveal--up","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__row sp-reveal sp-reveal--up"><!-- wp:heading {"level":2,"className":"ba-ib__h ba-grad"} -->
<h2 class="wp-block-heading ba-ib__h ba-grad">Afternoon: Paired Lunch, Service Drills, and Costing</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>At 13:00, the school sits down for staff lunch: pair it, defend it. Working alongside guest chefs, students select and justify wine pairings for dishes in front of their peers. At 14:15, Service practice begins: open, decant, pour twelve even glasses. We drill corkscrew dexterity, bottle presentation, decanting under candlelight, and fluid movement around guests. At 15:30, we address The list: cost it, price it, write it. Led by experienced floor managers, students calculate margins, balance cellar allocations, and draft clear descriptions. The day concludes at 16:30 with notes home.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

