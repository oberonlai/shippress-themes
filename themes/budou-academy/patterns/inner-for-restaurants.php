<h2 class="wp-block-heading ba-ib__h ba-grad">The Team Training Day</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>Budou Academy offers dedicated private training days conducted directly at your restaurant venue. Capped at up to 8 staff members, the session costs €1,200 for 1 full day, running from 10:00 to 16:00 on a Monday when your dining room is closed. Having your entire front-of-house team learn together builds unified service standards and consistent tasting vocabulary. Instead of sending staff individually, team training ensures that senior captains, junior servers, and bartenders share identical methods for bottle presentation, decanting, and menu pairing.</p>
