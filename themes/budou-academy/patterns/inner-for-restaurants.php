<h2 class="wp-block-heading ba-ib__h ba-grad">What Do We Cover During the Session?</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>Our instructor tailors the 10:00–16:00 syllabus directly to your restaurant's actual wine list and current seasonal food menu. Morning work focuses on blind structural tasting, helping your staff describe acidity, body, and regional character in concise, appealing language to diners. Midday training explores specific food pairings with dishes prepared from your kitchen. Afternoon modules drill physical floor mechanics: opening sparkling wines silently, decanting sediment cleanly under candlelight, serving without drips, and pouring twelve even measures. We also review upselling techniques and cellar storage procedures.</p>
