<h2 class="wp-block-heading ba-ib__h ba-grad">Founded by Hélène Marchetti</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Hélène Marchetti founded Budou Academy in Bordeaux in 2014 after spending eighteen years working as a head sommelier. During nearly two decades on dining room floors, she saw talented servers struggle to find wine education suited to service realities. Most courses demanded daytime hours during the trading week or focused entirely on academic theory divorced from cellar work and guest interaction. Budou Academy was built specifically around the working calendar of the restaurant industry. Every class takes place on Mondays, the single day when dining rooms, wine bars, and bistros typically keep their doors closed. Here, education works alongside your active career rather than competing with your shifts.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"className":"ba-ib__h ba-grad ba-ib__h--next"} -->
<h2 class="wp-block-heading ba-ib__h ba-grad ba-ib__h--next">Why We Sit at One Long Table</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Teaching happens around one long light oak table with twelve seats per class. We do not use lecture auditoriums or isolated examination desks. In hospitality, wine exists within a communal environment where bottles are shared, evaluated, and discussed in real time. Sitting face to face allows twelve working servers and bartenders to debate structure, acidity, and balance together under an instructor's guidance. The twelve-seat limit ensures that every student tastes from the same bottles, participates directly in flight discussions, and decants under the instructor's close observation. The room functions as a shared cellar workshop where practical palate discipline develops through continuous dialogue and guided tasting.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->

