<h2 class="wp-block-heading ba-ib__h ba-grad">What We Do Not Promise</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ba-ib__body","layout":{"type":"default"}} -->
<div class="wp-block-group ba-ib__body"><!-- wp:paragraph -->
<p>We do not publish placement statistics or promise instant promotions to cellar director. Wine service requires continuous discipline, physical repetition, and years of attentive hospitality on the dining room floor. Our responsibility is to give you accurate vocabulary, solid tasting foundations, and sound financial understanding for wine lists. What you do with those tools depends entirely on your daily dedication during service. We do not hand out hollow credentials or teach shortcuts to passing theoretical tests without practical ability. If you join us on a Monday, you arrive to taste rigorously, discuss openly, and refine the craft you practice every evening.</p>
