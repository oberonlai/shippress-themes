<h2 class="wp-block-heading">How is your meat wrapped, and what is inside the Week box?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every order is prepared with traditional parcel wrapping. Each piece is cut and weighed precisely to 10 g, then folded inside heavy white waxed butcher paper that lets the meat breathe while preventing moisture loss. Parcels are secured with natural cotton string and finished with a handwritten label recording the cut name, exact weight, calculated price, and packing date. Wrapped orders rest at 2 °C on our chilled pickup shelf. Many customers choose our Week box for two, priced at €58.00/box. This 2.4 kg selection includes 600 g braising chuck, 500 g chuck and brisket mince, 6 coarse pork and sage sausages weighing approximately 480 g, 2 dry-aged sirloin steaks totaling approximately 420 g, and 400 g bone-in shin.</p>
