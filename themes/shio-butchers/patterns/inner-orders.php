<h2 class="wp-block-heading">How does the four-step pickup order process work?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Placing an order follows four straightforward steps designed around our daily cutting schedule. Step 01: submit your order by 18:00 using our online form, by phone on +00 0000 2009, or by emailing orders@shio-butchers.example. Step 02: we send you a confirmation by 19:00 noting your estimated parcel weights and collection time. Step 03: at 07:00 the following morning, your meat is cut fresh, weighed, and securely wrapped. Step 04: collect your parcel from 07:30 Tuesday through Friday, or from 07:00 on Saturday, and pay at the counter by card or cash according to the exact weight. Orders are held on our dedicated chilled shelf until the close of business on that collection day, ensuring your meat remains in optimal condition.</p>
<!-- /wp:paragraph --></div>
