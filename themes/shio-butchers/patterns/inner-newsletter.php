<h2 class="wp-block-heading">What information is included in the Friday email?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Saturday list is dispatched every Friday afternoon at 17:00. This straightforward notice gives you first sight of what our counter will hold when our doors open at 07:00 on Saturday morning. The email lists every available cut alongside its exact per-kilogram price, including dry-aged 21 days rib on the bone, sirloin steaks, fresh chuck, bone-in shin, and the morning's batch of pork and sage sausages. It also details the precise components of that weekend's 2.4 kg Week box for two at €58.00/box. Finally, each newsletter includes a brief note from one of our three suppliers—Harrow Lane Farm, Millbrook Pastures, or Oaken Ridge—outlining current herd conditions and pasture progress.</p>
