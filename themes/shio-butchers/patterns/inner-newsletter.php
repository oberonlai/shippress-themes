<h2 class="wp-block-heading">How do you join and receive the Saturday list?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Joining the distribution list is simple and without marketing clutter. Enter your email address into our subscription form, or send an email message directly to orders@shio-butchers.example with the subject line requesting to join. When using our fallback subscription link, it opens your email application so you can send the request to join the Saturday list; please note you are not on the list until the message is sent and confirmed. Once registered, you will receive our single weekly email on Friday at 17:00. You can reply directly to that email until 18:00 to reserve your cuts for Saturday morning collection from 07:00, or unsubscribe at any time by sending a one-line note.</p>
