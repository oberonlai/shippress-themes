<h2 class="wp-block-heading">Oaken Ridge</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our seasonal lamb is raised at Oaken Ridge by Sofia Brandt, located 41 km from our shop, marking the furthest distance on our supply rail. Sofia tends her flocks across open hill pastures, bringing whole carcasses to our counter on Tuesday mornings between March and November. When the seasonal grazing period concludes each winter, lamb disappears from our display until spring arrives. Working with only 3 farms—Harrow Lane Farm, Millbrook Pastures, and Oaken Ridge—keeps our supply line short, dependable, and transparent. We know the farmers personally, understand how their animals are tended throughout the seasons, and schedule our butchery week to match their regular deliveries to 14 Market Row.</p>
