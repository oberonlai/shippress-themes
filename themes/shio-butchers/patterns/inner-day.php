<h2 class="wp-block-heading">What is the daily schedule at the block?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our working day begins at 05:30 when deliveries are checked, weighed, and hung on the cold rail. At 06:00, primary carcass breaking starts on the main wooden block. By 07:00, orders placed the previous evening are sliced, weighed, and wrapped for collection. The shop doors open and the display counter is filled at 07:30 Tuesday through Friday, and at 07:00 on Saturday. At 11:00, fresh trim from the morning breakdown is prepared into house sausages and coarse mince. The cold ageing room is inspected and carcasses turned at 14:00. Every Friday at 17:00, we send out the Saturday list email to our customers. Orders for the following day close at 18:00, after which the butcher block is scrubbed thoroughly with coarse salt, ahead of our 18:30 closing time. On Saturdays, our doors close at 15:00.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"sb-note","layout":{"type":"default"}} -->
<div class="wp-block-group sb-note"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">How is the cutting week organized across the days?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Our week is organized around whole carcass arrivals from 3 partner farms, located no further than 41 km away. While the shop is closed to the public on Monday, beef sides arrive from Harrow Lane Farm and are broken down for hanging. On Tuesday, lamb arrives from Oaken Ridge between March and November. Wednesday brings fresh outdoor-reared pork halves from Millbrook Pastures. Thursday is dedicated to turning and inspecting the cold room, where prime beef hangs on the hook for 21 days of dry-ageing. On Friday, we pack our Week boxes for two alongside custom weekend orders. Saturday is focused entirely on the busy counter service from 07:00 to 15:00, before we close for Sunday and Monday to allow the cold room and cutting floor to reset.</p>
