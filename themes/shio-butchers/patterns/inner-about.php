<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What is the history of Shio Butchers?</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->

<!-- wp:paragraph {"className":"sb-lede"} -->
<p class="sb-lede">Shio Butchers opened its doors in 2009 at 14 Market Row, Saltgate, founded on the principle of breaking whole carcasses on end-grain timber blocks. In 2014, we expanded our butchery capabilities by installing a dedicated cold room and custom steel ageing rail, allowing us to dry-age beef sides on the bone for 21 days. In 2019, we built an adjoining temperature-controlled sausage room to produce our coarse-ground pork sausages and fresh mince from the daily trim. Growth at the shop has remained steady and deliberate. In 2025, we welcomed our first apprentice butcher to pass down traditional carcass breaking and seam butchery techniques to a new generation.</p>
<!-- /wp:paragraph -->

