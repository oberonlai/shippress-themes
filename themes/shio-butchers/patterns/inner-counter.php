<div class="wp-block-group sb-note"><!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">How do we weigh and price each cut?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We believe you should only ever pay for the exact meat you take home. Meat is an irregular natural product, so portions cannot be stamped into identical factory weights. When you select a cut at our counter or place an order in advance, we slice it on the block and weigh it to the nearest 10 g. Your final price is calculated strictly from this actual weighed measurement, including VAT, rather than an arbitrary estimate. Once weighed, cuts are wrapped cleanly and priced clearly on a handwritten label. If you wish to reserve specific cuts before arriving at the shop, submit your request before 18:00 for collection the following morning.</p>
