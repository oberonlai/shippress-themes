<h2 class="wp-block-heading tp-qa__h">How should natural wallpapers be hung?</h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"tp-qa__b","layout":{"type":"default"}} -->
<div class="wp-block-group tp-qa__b"><!-- wp:paragraph -->
<p>Hanging woven and grasscloth papers demands patient surface preparation. For Linen-Weave, apply paste directly to a sound, primed wall using a medium roller, position the drop strictly plumb, and smooth outwards from the centre. For Grasscloth, apply adhesive evenly to the paper backing and allow it to relax before hanging, taking rigorous care never to get paste onto the woven natural face. Always butt edges gently without overlapping. Tomás Herrera advises trimming ceiling and skirting margins with a fresh, sharp blade on every drop.</p>
