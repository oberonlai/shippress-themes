<!-- wp:paragraph {"className":"kc-lede"} -->
<p class="kc-lede">Founded in 2017 by Noor Halvorsen, Kaoru Cocoa is a neighbourhood chocolatier and cocoa cafe at 14 Linden Arcade in Harrowfield. The name means scent, chosen for the aroma of chocolate being tempered on our marble slab at ten each morning.</p>
