<h2 class="wp-block-heading kc-h2">The scent of the morning marble slab</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"kc-body"} -->
<p class="kc-body">Kaoru Cocoa began in 2017 when founder Noor Halvorsen opened our doors at 14 Linden Arcade in Harrowfield. The name translates as scent, reflecting the aroma of chocolate being tempered on the marble slab at ten in the morning. The room accommodates twenty-four seats arranged around our central workspace, where the white marble slab stands four metres from the counter behind a low glass screen. We wanted visitors to experience the living craft of chocolate making without barriers, smelling the beans as they roast and watching the molten chocolate cool beneath the palette knife. By keeping our making process in the open shop, we ensure that every visitor shares in the daily transformation of single-origin cocoa from raw bean to finished bar.</p>
