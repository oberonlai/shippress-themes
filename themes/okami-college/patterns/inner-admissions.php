<h2 class="wp-block-heading ok-h2 ok-h2--left ok-col__h">What Happens During a Saturday Shift Trial?</h2>
<!-- /wp:heading --><!-- wp:paragraph {"className":"ok-copy"} -->
<p class="ok-copy">The Saturday shift trial is the core of our admissions process, coordinated by Admissions Officer Sofia Andersen. Rather than judging candidates solely through academic transcripts, we invite applicants to spend three active hours on the floor of Okami House on a Saturday morning. You will shadow a current student at the front desk, banquet room, or kitchen, helping with real hospitality tasks such as checking linens, setting dining covers, or observing guest arrivals. We do not look for prior hotel experience; instead, we assess curiosity, communication, punctuality, and how comfortably you interact with guests and fellow team members.</p>
