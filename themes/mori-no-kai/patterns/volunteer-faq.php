<details class="wp-block-details is-style-faq"><summary>What if it rains?</summary><!-- wp:paragraph -->
<p>We work in light rain; the forest is beautiful in it. If heavy rain or wind is forecast, we cancel by 18:00 the evening before and email everyone signed up.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Do I need to be fit?</summary><!-- wp:paragraph -->
<p>No. There is always work on level ground near the road, and you can take breaks whenever you like. Tell us in the form and we will plan your day around it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Can I come on my own?</summary><!-- wp:paragraph -->
<p>Most people do, the first time. By lunch you will know half the group.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Is there a minimum age?</summary><!-- wp:paragraph -->
<p>Children from eight can join with an adult. Teenagers from sixteen can come on their own with a signed note from a parent.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Can I volunteer outside the work days?</summary><!-- wp:paragraph -->
<p>Yes: the nursery needs help on Wednesday mornings, and we always need people for the newsletter, photographs and the accounts.</p>
