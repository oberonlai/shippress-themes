<p class="is-style-lead">We bring light back to the forest floor, one slope at a time, so the old mixed woodland can return on its own.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That means careful thinning, planting oak, beech and maple where the cedar comes out, keeping the deer away from the young trees, and opening the streams so fish can climb again. None of it is fast. A forest measures progress in decades, and so do we.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We are owned by nobody. The trust is run by four staff, a board of local volunteers, and more than three hundred members who give a little money, a few Saturdays, or both.</p>
