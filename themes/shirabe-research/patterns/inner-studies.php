<h3 class="wp-block-heading sr-study__q">Why did members stop opening the app?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"sr-study__sum"} -->
<p class="sr-study__sum">In early 2025, a regional grocery cooperative commissioned Shirabe Research to resolve a critical operational question: ‘Why did members stop opening the app?’ While digital download metrics remained steady, active daily usage had declined sharply across established membership tiers. Our fieldwork investigated member shopping rituals across three cities, completing twenty-four in-depth interviews and logging forty-one hours of detailed recordings. The investigation uncovered six primary behavioral findings, demonstrating that member disengagement stemmed from store connectivity failures and a strong preference for printed in-store circulars over digital interfaces during physical shopping trips.</p>
