<!-- /wp:heading -->
<!-- wp:paragraph {"className":"sr-study__sum"} -->
<p class="sr-study__sum">In 2023, a metropolitan municipal library system engaged Shirabe Research to evaluate facility utilization with the question: ‘Who comes in after 18:00, and why?’ Across five municipal branch libraries, our team conducted thirty-two in-person evening interviews with patrons, students, and local workers. The fieldwork yielded four comprehensive findings detailing how branch facilities functioned outside traditional borrowing hours. Rather than checking out catalogued literature, evening visitors sought quiet, well-lit spaces equipped with reliable desk power outlets and local community reference materials.</p>
