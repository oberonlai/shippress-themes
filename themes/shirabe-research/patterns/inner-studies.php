<!-- wp:paragraph {"className":"sr-study__sum"} -->
<p class="sr-study__sum">During 2024, an independent bicycle manufacturer retained our team to answer an essential retail puzzle: ‘What does a first-time buyer check before paying?’ Rather than relying on post-purchase online surveys, our researchers conducted eighteen in-store observational visits across two countries. By shadowing novice shoppers and conducting immediate on-site intercept dialogues, we identified nine distinct friction points. The study revealed that purchase decisions were driven not by technical gear ratios or frame alloy specifications, but by intuitive ergonomic comfort, brake lever reach, and anxieties surrounding roadside maintenance.</p>
