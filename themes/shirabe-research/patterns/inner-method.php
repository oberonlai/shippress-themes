<p class="sr-eyebrow">03</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3,"className":"sr-item__title"} -->
<h3 class="wp-block-heading sr-item__title">Stage 4 and Stage 5: Chart on Paper and Readout</h3>
<!-- /wp:heading --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"sr-row__body","layout":{"type":"default"}} -->
<div class="wp-block-group sr-row__body"><!-- wp:image {"sizeSlug":"large","linkDestination":"none","className":"sr-row__img"} -->
<figure class="wp-block-image size-large sr-row__img"><img src="<?php echo esc_url( get_theme_file_uri( 'assets/images/p08.webp' ) ); ?>" alt="Headphones beside a laptop showing an audio waveform and printed transcript pages."/></figure>
<!-- /wp:image -->
<!-- wp:paragraph -->
<p>Week four is dedicated to physical analysis. Our research team and your stakeholders assemble in our Northbank studio to chart evidence directly onto paper walls. We review interview transcripts, extract verbatim quotes, and arrange findings into thematic patterns using printed cards and wall charts. This collaborative exercise eliminates the disconnect between agency and client, ensuring shared ownership of emerging insights. In week five, we deliver the final readout and comprehensive written report. Led by Clara Wendt and Jonah Mensah, the readout presentation walks your leadership through synthesized findings, supporting quotes, and direct strategic observations, providing an authoritative reference for executive decision-making.</p>
