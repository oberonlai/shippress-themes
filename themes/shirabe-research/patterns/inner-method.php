<p class="sr-eyebrow">02</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3,"className":"sr-item__title"} -->
<h3 class="wp-block-heading sr-item__title">Stage 3: Moderated Fieldwork</h3>
<!-- /wp:heading --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"sr-row__body","layout":{"type":"default"}} -->
<div class="wp-block-group sr-row__body"><!-- wp:paragraph -->
<p>Fieldwork occurs across weeks two and three, taking place either within our dedicated interview studios, Studio A and Studio B, or on site through in-context visits. Sessions are conducted one-to-one by senior moderators Clara Wendt and Nadia Haddad, supported by head of fieldwork Tomás Ibarra. Each session lasts sixty minutes, allowing participants sufficient time to settle, reflect, and share detailed personal experiences without feeling rushed. Client team members can observe live interviews through discreet audio-visual links or attend in-context visits where appropriate. All sessions are recorded with high-fidelity audio equipment, with Wei-Lin Chou managing immediate verbatim transcription to support rapid analytical turnaround.</p>
