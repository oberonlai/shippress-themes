<h3 class="wp-block-heading sr-item__title">Stage 1 and Stage 2: Brief and Recruit</h3>
<!-- /wp:heading --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"sr-row__body","layout":{"type":"default"}} -->
<div class="wp-block-group sr-row__body"><!-- wp:image {"sizeSlug":"large","linkDestination":"none","className":"sr-row__img"} -->
<figure class="wp-block-image size-large sr-row__img"><img src="<?php echo esc_url( get_theme_file_uri( 'assets/images/p03.webp' ) ); ?>" alt="A moderator listens with her chin on her hand while a participant sits blurred in the foreground."/></figure>
<!-- /wp:image -->
<!-- wp:paragraph -->
<p>Every project begins in week zero with a ninety-minute brief alignment meeting where we define research questions and participant profiles with your core team. In weeks one and two, recruitment lead Ingrid Solberg oversees custom screening to recruit the exact twelve participants required for the study. Rather than using generic consumer panels, we screen candidates individually against behavioural criteria and verified usage habits. Clients receive daily recruitment updates and screener logs to ensure full alignment before fieldwork starts. By the conclusion of week two, interview schedules are locked, participant profiles are shared with client observers, and interview guides prepared by our senior moderators are finalized.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->
