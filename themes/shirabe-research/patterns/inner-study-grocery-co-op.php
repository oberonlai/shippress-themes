<h3 class="wp-block-heading sr-statement">Brief and Research Approach</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The cooperative faced puzzling analytics: member accounts were active and store footfall was robust, yet their loyalty mobile app was rarely opened inside store aisles. The leadership team required qualitative evidence to determine whether members found the interface confusing, irrelevant, or redundant. Our fieldwork spanned three cities and involved twenty-four in-depth interviews totaling forty-one hours of audio recordings. Tomás Ibarra coordinated fieldwork across varied store formats, while Nadia Haddad conducted unhurried interviews with long-standing co-op members. We observed customers planning weekly meals at home and accompanied them through physical aisles to document exactly where mobile interactions broke down.</p>
