<h3 class="wp-block-heading sr-statement">The Commercial Brief and Fieldwork</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The client, an independent bicycle manufacturer, observed substantial foot traffic in partner dealer showrooms that failed to convert into sales among novice cyclists. The management team commissioned Shirabe Research to answer: ‘What does a first-time buyer check before paying?’ Rather than distributing post-visit questionnaires, our fieldwork team deployed to retail showrooms across two countries. Tomás Ibarra and Clara Wendt conducted eighteen in-store contextual visits, shadowing prospective purchasers as they browsed display floors and engaged with sales staff. We recorded natural customer hesitations, physical contact points with display bicycles, and the specific questions buyers voiced before stepping away.</p>
