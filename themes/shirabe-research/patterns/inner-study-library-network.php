<h3 class="wp-block-heading sr-statement">The Municipal Question and Study Setup</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Municipal library administrators faced budgetary pressure regarding operating hours and sought qualitative clarity on evening operations: ‘Who comes in after 18:00, and why?’ Rather than relying on simple automated turnstile counts, Shirabe Research was engaged to investigate the motivations of evening visitors. Fieldwork was conducted across five distinct municipal branches. Senior moderator Nadia Haddad and fieldwork lead Tomás Ibarra spent three weeks on site, conducting thirty-two semi-structured interviews with patrons present between 18:00 and closing time. Researchers noted desk occupancy, lighting preferences, equipment usage, and the spatial distribution of individuals throughout each facility.</p>
