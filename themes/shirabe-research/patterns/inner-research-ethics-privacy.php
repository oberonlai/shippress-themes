<h3 class="wp-block-heading sr-item__title">Informed Consent and Participant Welfare</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Participant trust forms the foundation of all qualitative inquiry at Shirabe Research. Prior to entering Studio A, Studio B, or participating in an in-context visit, every individual receives a comprehensive written briefing outlining the research purpose, session length, and recording methods. Participation is entirely voluntary, and participants may decline to answer specific questions, request that recording pause, or withdraw from the session at any time without penalty or loss of compensation. We ensure fair financial incentives are paid promptly upon session conclusion to honor the time and insights participants contribute to each commercial study.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3,"className":"sr-item__title"} -->
<h3 class="wp-block-heading sr-item__title">Recordings Retention and Secure Storage</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Audio and video recordings collected during customer interviews are subject to strict data governance standards. All digital media files are stored on secure, encrypted servers with access restricted exclusively to the seven permanent members of our research practice. We enforce a firm recordings retention period: all raw audio and video files are permanently deleted twelve months following the formal delivery of the final study readout. Clients receive access to secure observation streams and verbatim text transcripts, but raw customer footage is never distributed or used for external promotional purposes.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3,"className":"sr-item__title"} -->
<h3 class="wp-block-heading sr-item__title">Anonymisation and Data Protection</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Protecting personal anonymity is a strict operating rule across all project deliverables. Transcripts prepared by Wei-Lin Chou replace full participant names, workplace identifiers, and specific residential addresses with standardized pseudonyms before analysis begins. Paper charts displayed on studio walls and included in executive readouts show only anonymized verbatim quotes and behavioral observations. We never sell, trade, or repurpose participant contact details for marketing or commercial re-contact. When study findings are presented to client leadership, customer confidentiality is completely safeguarded while preserving the authentic emotional resonance of primary testimony.</p>
