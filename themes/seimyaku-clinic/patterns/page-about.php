<h2 class="wp-block-heading">Founding and Background</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Dr Ilse Marchetti founded Seimyaku Clinic in 2013 after years working within a hospital renal unit, where she repeatedly saw patients only after irreversible kidney damage had already occurred. Hospital clinics were structured around acute episodes, leaving little time to identify gradual changes in renal function or discuss blood pressure patterns in depth. Seimyaku Clinic opened in a single room with a simple premise: kidney disease and hypertension develop over decades, so their medical care must be measured over years rather than isolated appointments. By dedicating adequate time to every consultation, reviewing lab trends side by side with patients, and following individuals across long spans, we aim to prevent avoidable decline before acute intervention is ever required.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Growth and Continuity</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In 2018, we introduced our structured home blood pressure diary programme, enabling patients to track morning and evening readings in familiar daily environments between clinical visits. Today, Seimyaku Clinic has grown into a cohesive team of seven clinicians and coordinators operating from our quiet space on Alder Row. Despite our growth, our core method remains unchanged: the same physician reads your test results across successive visits, eliminating the disorientation of retelling your history to new staff each season. Our practice values rest on three clear commitments: continuity of care over years / transparent review of laboratory trends / unhurried appointments paced to your health. We remain anchored at 2nd floor, 41 Alder Row, Wrenfield.</p>
