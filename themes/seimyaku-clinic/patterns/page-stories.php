<h2 class="wp-block-heading">After a kidney stone</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Amara, aged 38, sought care at Seimyaku Clinic following an episode of acute kidney stone pain that required hospital emergency admission. Once the stone had passed, she wanted to understand how to prevent recurrence and protect her renal function. Amara attended an initial consultation with Dr Asante to evaluate her baseline filtration rates, followed by a detailed forty-five-minute nutrition session with our renal dietitian, Priya Nair. Together, they reviewed Amara's daily fluid habits, mineral balance, and dietary salt intake. Amara now attends a routine yearly review each autumn to check urine electrolyte levels and verify ongoing renal health, enjoying peace of mind through structured annual oversight.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She has one visit each autumn and no more questions than she brings with her.</p>
