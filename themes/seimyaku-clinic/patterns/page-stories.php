<h2 class="wp-block-heading">Ruth and Daniel: Long-Term Oversight</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ruth, aged 64, arrived at Seimyaku Clinic after a routine health check revealed stage 3a chronic kidney disease. For eight years, she has attended consultations every six months with Dr Marchetti. Each appointment pairs regular blood and urine panels with an annual renal ultrasound performed by Elena Varga, confirming structural stability without sudden changes. Daniel, aged 47, was referred after elevated blood pressure was flagged during an occupational screening. We initiated a 24-hour blood pressure monitor, followed by daily morning and evening logging in our home diary. In his first year, Daniel attended reviews every three months while Dr Reyes fine-tuned his medication; with blood pressure stabilized, his appointments now occur every six months.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Amara: Recovery and Prevention</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Amara, aged 38, sought care at Seimyaku Clinic following an episode of acute kidney stone pain that required hospital emergency admission. Once the stone had passed, she wanted to understand how to prevent recurrence and protect her renal function. Amara attended an initial consultation with Dr Asante to evaluate her baseline filtration rates, followed by a detailed forty-five-minute nutrition session with our renal dietitian, Priya Nair. Together, they reviewed Amara's daily fluid habits, mineral balance, and dietary salt intake. Amara now attends a routine yearly review each autumn to check urine electrolyte levels and verify ongoing renal health, enjoying peace of mind through structured annual oversight.</p>
