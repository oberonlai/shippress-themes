<!-- wp:paragraph -->
<p>Our published fees apply to all self-paying patients, while insured patients receive itemized receipts billed under their private health plan. The initial ninety-minute consultation costs €180, which includes your thorough physician assessment and comprehensive blood and urine panel. Regular follow-up consultations lasting thirty minutes are €75. A standalone blood and urine panel covering eGFR, serum creatinine, electrolytes, and urine ACR is €48. A detailed diagnostic kidney ultrasound with our sonographer is €120. Fitting and analyzing a 24-hour blood pressure monitor costs €95. An individual forty-five-minute nutrition consultation with our renal dietitian is €70. All results calls and home blood pressure diary evaluations are fully included without additional fees.</p>
