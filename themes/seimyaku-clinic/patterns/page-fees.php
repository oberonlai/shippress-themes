<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What are your billing and cancellation terms?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We believe financial clarity is an essential part of calm medical care. Following every consultation or diagnostic test, Samuel Obi provides a fully itemized receipt detailing diagnostic codes and services rendered for submission to private insurance carriers. If you are covered under an independent medical plan, please check reimbursement limits with your insurer prior to your appointment. For appointment changes or scheduling conflicts, we ask for reasonable advance notice so another patient can utilize the clinical time. Cancellations made up to 24 hours before your scheduled appointment incur no cancellation fee. Appointments cancelled with less than 24 hours notice or missed without communication may be subject to standard billing charges.</p>
