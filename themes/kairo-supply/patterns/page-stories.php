<h2 class="wp-block-heading ks-case__name">Lucas Ferreira: sole trader EV charging and locker access</h2>
<!-- /wp:heading --><!-- wp:paragraph -->
<p>Lucas Ferreira operates as an independent electrical contractor specializing in domestic and small commercial EV charging installations. After launching his specialized business in 2025, Lucas needed reliable access to protective devices, chargers, and heavy gauge flex without maintaining a large personal inventory. He submitted his company details, VAT number, and trade reference online, and Mei Lin Hart had his trade account approved within two working days.</p>
<!-- /wp:paragraph --><!-- wp:paragraph -->
<p>Lucas frequently starts installations before standard trade counter hours, making our automated collection lockers essential. His orders are staged in secure lockers from 06:00, allowing him to collect equipment before heading to his first charging appointment. With five-metre minimum cuts on heavy cable and no cut fees on account, Lucas purchases only what each driveway installation requires, keeping his overhead low and his van organized.</p>
