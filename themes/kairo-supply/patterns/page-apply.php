<!-- /wp:group -->

<!-- wp:group {"className":"ks-tsec__b","layout":{"type":"default"}} -->
<div class="wp-block-group ks-tsec__b"><!-- wp:paragraph -->
<p>The account process takes two working days from start to finish. Step one is submitting your application online or in person at the counter, which takes roughly ten minutes. Step two is our credit check, handled the same day by Mei Lin Hart in accounts. Step three sets up your counter card and records your named buyers by the next working day. Step four is placing your first order on account. There is no fee to open or maintain the facility, and credit starts at up to €5,000 on thirty-day statement terms.</p>
