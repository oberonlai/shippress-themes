<h3 class="wp-block-heading sf-faq__group">Tests</h3>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do we both need tests before starting?</summary><!-- wp:paragraph -->
<p>Yes, in almost every case. A fertility assessment looks at both partners: an AMH blood test and an ultrasound scan of the ovaries, a day 2–5 hormone panel, and a semen analysis. Together they show what is happening today, so the plan fits you. Results arrive within 5 working days.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is the HyCoSy tubal check painful?</summary><!-- wp:paragraph -->
<p>Most people describe it as a period-like ache that passes within minutes. It takes about 15 minutes, we explain every step first, and you can ask us to pause at any moment. You may take a simple painkiller beforehand, and we give you a short aftercare sheet.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How soon after the first visit can tests be done?</summary><!-- wp:paragraph -->
<p>Blood tests for the hormone panel are taken on cycle day 2–5, so the timing depends on your next period. Many people book the scan and semen analysis in the same week. If your cycles are irregular, the nurse coordinator will plan a day that works.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:heading {"level":3,"className":"sf-faq__group"} -->
<h3 class="wp-block-heading sf-faq__group">IVF steps</h3>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What actually happens during an IVF cycle?</summary><!-- wp:paragraph -->
<p>Roughly: 10–12 days of stimulation injections at home, three or four monitoring scans, egg collection (about 20 minutes under light sedation), five days of embryo culture in the lab, then a transfer of about 15 minutes. A pregnancy test follows 12 days later. A nurse is on call throughout.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will the injections be difficult to give myself?</summary><!-- wp:paragraph -->
<p>Most people find them easier than expected. A nurse shows you the pen, watches you do the first one, and gives you a written schedule. Your partner is welcome to learn too. If you would rather not, we can arrange a visit for each injection.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I keep working during treatment?</summary><!-- wp:paragraph -->
<p>Many patients do. Monitoring scans are short and early in the morning, usually before 9:00. The day of egg collection and the following morning are best kept free. We can give you a letter for your employer that says only that you are attending appointments.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:heading {"level":3,"className":"sf-faq__group"} -->
<h3 class="wp-block-heading sf-faq__group">Costs</h3>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How much does a first consultation cost?</summary><!-- wp:paragraph -->
<p>The first consultation costs €180 for both partners and lasts 60 minutes. We review your history, explain the tests that make sense and agree on next steps. The 30-minute plan review after your assessment is included, so there is nothing extra to pay for that conversation.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What does an IVF cycle cost in total?</summary><!-- wp:paragraph -->
<p>Our IVF cycle fee is €4,800. It covers monitoring, egg collection, laboratory work and one fresh embryo transfer. ICSI is an add-on at €1,100 when it is advised. Medication is billed separately by the pharmacy and is usually €1,200–2,500 per cycle.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I pay in instalments?</summary><!-- wp:paragraph -->
<p>Yes. Treatment fees can be paid in two parts: half when you book the cycle, the rest before egg collection. We do not charge interest. If a cycle is cancelled before it starts, we explain in writing what is refunded, before you pay anything.</p>
<!-- /wp:paragraph --></details>
