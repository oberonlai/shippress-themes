<!-- wp:heading -->
<h2 class="wp-block-heading">Twenty minutes, <em>twice a year</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When water no longer beads on the top, or the wood looks dry and pale where hands rest, it is time. Use the hardwax oil from our care kit, or any clear hardwax oil without solvents.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"ordered":true,"className":"is-style-ruled"} -->
<ol class="wp-block-list is-style-ruled"><!-- wp:list-item -->
<li>Wipe the piece with a damp cloth and let it dry for an hour.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>For marks and rings, sand lightly along the grain with 320-grit paper.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Rub in a thin coat of oil with a cotton cloth, following the grain.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>After fifteen minutes, wipe off everything that has not soaked in. Leave it overnight.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Spread oily cloths flat outside to dry before you throw them away: they can catch fire when bunched up.</li>
<!-- /wp:list-item --></ol>
