<h2 class="wp-block-heading">From <em>8:00</em> to dusk</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The stove is lit at eight. Mornings are for cutting joints, while the light is low and hands are steady; afternoons for fitting, sanding and oil. At four everyone stops for tea at the long bench, and pieces that are finished that day are signed in front of the others.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>You are welcome to watch. Workshop visits are by appointment, an hour long and free; ask in the showroom or write to us.</p>
