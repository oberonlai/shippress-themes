<!-- wp:heading {"className":"wm-chapter__title"} -->
<h2 class="wp-block-heading wm-chapter__title">Made to be <em>mended</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Wood moves. A chair will settle in its first winter, a table top will darken where the sun reaches it, and a ring from a hot mug will appear the week guests come. None of that is a fault: it is the piece becoming yours.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When something does need us, bring it back. Every piece is signed and numbered underneath, and the first re-oil and any re-tightening are free for the first year. After that our repair bench charges by the hour, and nothing is ever too old.</p>
<!-- /wp:paragraph -->

