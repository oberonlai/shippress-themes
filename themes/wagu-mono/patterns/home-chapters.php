<h2 class="wp-block-heading wm-chapter__title">Locked, <em>not screwed</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A joint is where furniture fails, so it is where we spend our time. Legs meet rails in through-tenons locked with walnut wedges; drawers are dovetailed; long benches are pegged so they can be taken apart and carried through a narrow door.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Every joint is cut with a saw and a chisel and fitted dry before any glue goes near it. Look for the dark keys and wedges: they are not decoration, they are what holds the piece together.</p>
<!-- /wp:paragraph -->

