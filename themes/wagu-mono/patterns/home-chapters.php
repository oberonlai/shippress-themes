<!-- wp:heading {"className":"wm-chapter__title"} -->
<h2 class="wp-block-heading wm-chapter__title">Three coats, <em>by hand</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We finish in hardwax oil, rubbed in with a cotton cloth in three thin coats a day apart. It soaks into the grain instead of sitting on top like a varnish, so a scratch is a small thing you can rub out at home, not a crack in a plastic skin.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The pale oak pieces can be soaped instead: a flake soap that keeps the wood almost white, and which you renew with a bucket of warm water twice a year.</p>
<!-- /wp:paragraph -->

