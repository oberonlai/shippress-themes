<h2 class="wp-block-heading wm-chapter__title">A year of <em>patience</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>White oak and black walnut come to the yard from two family sawmills within sixty miles. Every board is quarter-sawn, stickered and left to air-dry for a full year before it comes inside, then rests another month beside the bench so it is used to the room.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Quarter-sawn wood shows its rays as a quiet silver fleck, and it moves far less with the seasons. It is slower and costs more. It is also why our table tops stay flat.</p>
<!-- /wp:paragraph -->

