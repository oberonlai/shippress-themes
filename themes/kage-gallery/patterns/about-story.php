<p class="is-style-lead">Kage is the Japanese word for shadow, and for the shape something leaves behind. We opened in 2014 in a former print shop on Sumiyoshi-d&#333;ri: one long room, two smaller ones, high windows and a concrete floor that still shows where the presses stood.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We show four or five exhibitions a year, mostly painting, works on paper and small sculpture, by artists who work slowly. We would rather show eleven works well than forty in a hurry. Every exhibition is free to visit, and every work has a wall label and a price list at the desk for anyone who asks.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Between exhibitions the gallery closes for a week. The walls are filled and painted white again, and the floor is waxed. The shadow of the last show is gone; the room is ready for the next.</p>
