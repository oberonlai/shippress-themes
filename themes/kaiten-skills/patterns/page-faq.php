<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>What does each course cost?</summary><!-- wp:paragraph -->
<p>Prices are in EUR and do not change by language. Clear Business Writing, Ines Carvalho, 24 lessons, suggested length 5 weeks, €129. Reports People Actually Read, Sofia Marín, 20 lessons, 4 weeks, €139. Presenting with Confidence, Tomasz Wierzba, 22 lessons, 5 weeks, €149. Spreadsheets from Zero, Amara Osei, 28 lessons, 6 weeks, €119. Spreadsheet Models for Decisions, Rahul Menon, 26 lessons, 6 weeks, €169. The Career Starter Bundle has no single tutor. It joins Clear Business Writing, Presenting with Confidence and Spreadsheets from Zero: 74 lessons, a suggested 16 weeks, €329. Lessons are 8 to 14 minutes. Lesson 1 of every course is free. Team licences have no public price. Ask hello@kaiten-skills.example.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>How do I buy a course and get access?</summary><!-- wp:paragraph -->
<p>Choose a course, or watch lesson 1 free first. Then use Buy course on the archive or Enrol on the course page. Both take you to checkout. When payment is complete you are enrolled and access is instant. You do not wait for a start date, and you do not travel to the studio. Access lasts 24 months from that purchase. The Career Starter Bundle is a single checkout at €329 for 74 lessons, not three payments. If the course does not appear, email hello@kaiten-skills.example. Learner support is open Monday to Friday 09:00 to 18:00 CET and Saturday 10:00 to 14:00 CET. Jonah Ellery looks after the platform and learner support.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>When can I ask for a refund?</summary><!-- wp:paragraph -->
<p>A refund is available within 14 days if fewer than 3 lessons were watched. Both conditions apply. The rule is the same for every course, from Spreadsheets from Zero at €119 to the Career Starter Bundle at €329. This page does not add a further promise beyond those two conditions. Write to hello@kaiten-skills.example, name the course, and send the note during support hours if you want a person to read it the same day: Monday to Friday 09:00 to 18:00 CET, Saturday 10:00 to 14:00 CET. Lena Hoffmann leads learner support. The studio at Kanaalstraat 21, 3531 Utrecht, Netherlands does not take refund requests in person. There are no walk-in classes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>Can my team buy licences?</summary><!-- wp:paragraph -->
<p>Team licences are arranged by contact. They are not a row in the price table, and there is no published team fee beside the six course prices of €129, €139, €149, €119, €169 and €329. Email hello@kaiten-skills.example and say which courses you need. The people who teach them are Ines Carvalho, Sofia Marín, Tomasz Wierzba, Amara Osei and Rahul Menon. Lena Hoffmann leads learner support, and she is the right person for a team question. Hours are Monday to Friday 09:00 to 18:00 CET and Saturday 10:00 to 14:00 CET. A team does not attend the studio at Kanaalstraat 21, 3531 Utrecht. Each person watches lessons of 8 to 14 minutes, available 24 hours a day, for 24 months from purchase.</p>
