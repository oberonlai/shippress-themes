<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>What kind of certificate will I receive?</summary><!-- wp:paragraph -->
<p>You receive a certificate of completion. It says you finished that course. It is not an accredited qualification. It is not offered as a diploma, a licence or a professional exam. This is true for all six items, including the Career Starter Bundle at €329 and 74 lessons. Completing the bundle is completion of that enrolment. The school was founded in 2017 by Ines Carvalho and Jonah Ellery. Nothing in that history adds an external accreditation to the certificate. If you need a form of study your workplace will fund, ask them what they accept, and read this answer to them as it stands. We will not rename the certificate to suit a form.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>When is the certificate issued, and where do I find it?</summary><!-- wp:paragraph -->
<p>The certificate of completion is issued when you finish the course. No other delay is published, and the 5 working days you may have seen elsewhere belong to assignment feedback, not to the certificate. When it is issued, find it on My courses under Certificates. The same strip shows In progress and Completed, so you can tell a finished course from one you are still watching. Access lasts 24 months, which is the time you have to reach the end of the lesson list. If you have finished and the list is empty, email hello@kaiten-skills.example. Lena Hoffmann leads learner support. Hours are Monday to Friday 09:00 to 18:00 CET and Saturday 10:00 to 14:00 CET.</p>
