<h2 class="wp-block-heading ks-h2">Learning</h2>
<!-- /wp:heading -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>How long is a lesson, and can I try lesson 1 free?</summary><!-- wp:paragraph -->
<p>Every lesson is 8 to 14 minutes. That includes lesson 1, which is free on every course, before you pay. The free lesson is the same kind of video as the rest, not a separate trailer with a different length. Clear Business Writing has 24 lessons, Reports People Actually Read 20, Presenting with Confidence 22, Spreadsheets from Zero 28, Spreadsheet Models for Decisions 26, and the Career Starter Bundle 74. Suggested lengths are 5, 4, 5, 6, 6 and 16 weeks, in that order. The suggestion is a pace. You can watch lesson 1 of more than one course before you choose. Enrolment and the 24 months of access begin only when you buy.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>How long do I keep access to a course?</summary><!-- wp:paragraph -->
<p>Access lasts 24 months from purchase. During that time the lessons you bought stay available 24 hours a day, seven days a week. The 24 hours are about watching. They are not the hours when learner support is in the studio. Support answers Monday to Friday 09:00 to 18:00 CET and Saturday 10:00 to 14:00 CET. A suggested length of 4, 5, 6 or 16 weeks is shorter than 24 months on purpose, so a paused week does not end the course. Access is for that enrolment. It does not extend itself, and a refund is a different rule: 14 days, and fewer than 3 lessons watched. Email hello@kaiten-skills.example if a course you paid for will not open.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>When is learner support open, and when can I watch?</summary><!-- wp:paragraph -->
<p>You can watch lessons 24 hours a day, any day, throughout the 24 months of access. Learner support is human hours only: Monday to Friday 09:00 to 18:00 CET, and Saturday 10:00 to 14:00 CET. The email is hello@kaiten-skills.example. Lena Hoffmann is learner support lead. Jonah Ellery, co-founder, is responsible for the platform and learner support. Ines Carvalho, the other co-founder, teaches writing. The studio address is Kanaalstraat 21, 3531 Utrecht, Netherlands. You may write to that address, but you cannot attend a class there. There are no walk-in classes. A lesson is 8 to 14 minutes, which is the piece of study available in the evening when support has closed.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq"} -->
<details class="wp-block-details ks-faq"><summary>How does assignment feedback work?</summary><!-- wp:paragraph -->
<p>You practise, you send an assignment, and feedback is returned within 5 working days. Working days follow Monday to Friday. Saturday support hours do not add a sixth feedback day. The reply comes from the tutor of the course: Ines Carvalho for Clear Business Writing, Sofia Marín for Reports People Actually Read, Tomasz Wierzba for Presenting with Confidence, Amara Osei for Spreadsheets from Zero, and Rahul Menon for Spreadsheet Models for Decisions. The bundle draws on the three courses it contains. Notes you keep on the lesson page are for you. They are not automatically an assignment. Feedback is not the certificate. The certificate comes when you finish, and it is a certificate of completion.</p>
