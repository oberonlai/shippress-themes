<details class="wp-block-details" open><summary>Does it hurt?</summary><!-- wp:paragraph -->
<p>Rarely. Most people feel a light tap, then nothing, or a dull heaviness around the point. If anything feels sharp, say so and the needle comes out at once.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What should I wear?</summary><!-- wp:paragraph -->
<p>Anything comfortable. We have cotton gowns and towels, and you only uncover the part we are working on.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I eat before a treatment?</summary><!-- wp:paragraph -->
<p>A light meal an hour or two before is ideal. Please do not come very hungry, or straight after a large lunch.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How often should I come?</summary><!-- wp:paragraph -->
<p>There is no fixed course. Many people come every two to four weeks; some only at the turn of the seasons. We will never press you to book more.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you accept health insurance?</summary><!-- wp:paragraph -->
<p>We are a self-pay clinic and do not process insurance claims. We can give you a receipt for your records.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I come if I am pregnant?</summary><!-- wp:paragraph -->
<p>Please tell us when you book. We offer gentle treatments in some cases, and will always ask you to check with your midwife or doctor first.</p>
