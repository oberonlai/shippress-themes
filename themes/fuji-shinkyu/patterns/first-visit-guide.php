<ol class="wp-block-list fs-steps"><!-- wp:list-item -->
<li><strong>The form.</strong> When we confirm your time we send a short form about sleep, work, appetite and anything your doctor has told you. Fill it in at home; it saves ten minutes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Tea and a talk.</strong> Twenty minutes, sitting down, about how you feel and what you would like to feel instead.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Pulse and breath.</strong> Three fingers on each wrist, a look at the tongue and at how you breathe lying down.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>The treatment.</strong> Needles, moxa or hands, often a little of each. We tell you what comes next before each step.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Rest, and home.</strong> Twenty minutes under a blanket, tea, and one small thing to try before the next visit.</li>
<!-- /wp:list-item --></ol>
