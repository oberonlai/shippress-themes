<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Cognitive Behavioural Therapy for Insomnia (CBT-I)</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>For chronic insomnia and fractured sleep, Cognitive Behavioural Therapy for Insomnia is the internationally recommended first-line treatment. Led by sleep psychologist Dr. Priya Raman, our structured CBT-I programme consists of six weekly 50-minute individual sessions priced at $780. Rather than offering generic sleep hygiene tips, Dr. Raman works closely with your fourteen-day sleep diary data to implement targeted behavioral strategies. You will practice sleep restriction therapy to consolidate broken rest into continuous sleep, stimulus control to rebuild the mental association between bed and sleep, and cognitive reframing to dismantle nocturnal sleep anxiety. By establishing a fixed morning rise time and strengthening your natural homeostatic sleep drive, CBT-I creates lasting, drug-free improvements in sleep quality.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Continuous Positive Airway Pressure (CPAP) support</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>When an overnight study reveals obstructive sleep apnea, Continuous Positive Airway Pressure therapy provides gentle, pneumatic splinting of the upper airway to prevent breathing pauses and maintain steady nocturnal oxygenation. Successful CPAP therapy depends on comfortable equipment fitting and compassionate clinical guidance. Nurse Grace Lin leads our CPAP set-up and first-month coaching service, available for $210. Grace works with you to select an appropriate nasal or full-face mask, adjust pressure ramp settings, and troubleshoot early challenges such as mask leaks or nasal dryness. At the four-week mark, she performs an objective data download to review compliance hours and residual respiratory events, ensuring your transition to nightly therapy is comfortable and effective.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Circadian timing and light therapy</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Misalignments between your internal circadian pacemaker and your required waking schedule can severely disrupt sleep onset and morning alertness. For patients dealing with delayed sleep phase syndrome or rotating shift rosters, we formulate customized circadian realignment plans. These protocols combine strategically timed bright light exposure, daylight management using blue-light filtering glasses or blackout curtains, and precise scheduling of evening winding-down periods. By gradually shifting your core body clock markers, we help synchronize your biological sleep drive with your social and occupational demands. This approach provides sustainable, non-pharmacological support for shift workers, healthcare professionals, and late chronotypes striving to maintain dependable rest on demanding Seattle schedules.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Specialist referrals and collaborative care</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Not every sleep condition is best resolved through CPAP therapy or psychological counseling alone. When anatomical airway obstruction, enlarged tonsils, nasal septal deviations, or chronic sinus issues contribute to sleep-disordered breathing, Dr. Tomas Varga coordinates referrals to trusted ear, nose, and throat (ENT) surgeons for specialized surgical assessment. Similarly, for patients with mild to moderate obstructive sleep apnea who struggle with CPAP intolerance, we collaborate with qualified dental sleep specialists to fabricate custom mandibular advancement oral appliances. We also coordinate with neurology specialists when atypical movement disorders or narcolepsy are suspected. All treatment options and associated clinic consultation fees are clearly outlined on our fees page.</p>
