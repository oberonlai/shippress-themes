<div class="wp-block-group nc-prose">
<!-- wp:paragraph {"className":"nc-lead"} -->
<p class="nc-lead">Attending a sleep clinic for the first time should feel calm, clear, and reassuring. From your initial evening consultation to your diagnostic recording and follow-up plan, we guide you through each stage of care without rush or confusion.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Step 1: Booking your appointment</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Your care begins when you reach out by telephone at (206) 555-0142 or schedule an appointment through our website. Malik Hassan at our front desk will assist you in selecting an afternoon or evening consultation time that fits around your work commitments. Before you arrive at Suite 210 on Alder Lane, we ask you to prepare a complete list of your current medications, your photo identification, and any personal notes you have kept regarding your sleep difficulties. We ensure all preliminary intake details are handled smoothly so your appointment starts promptly.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Step 2: First consultation and two-week sleep diary</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Your first consultation is an unhurried, 60-minute meeting with a sleep physician, priced at $180. During this hour, we listen closely to your history, discussing when your sleep problems began, your daily energy levels, and your nighttime habits. We conduct a targeted physical and upper airway examination. At the conclusion of this visit, your physician provides you with our structured two-week sleep diary. Recording your daily bedtime, wake-up times, nocturnal awakenings, and daytime fatigue over fourteen consecutive days provides essential baseline data that informs our subsequent diagnostic and treatment decisions.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Step 3: Recording your night</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Depending on your specific symptoms, we arrange an objective recording of your sleep using either a portable home test or an overnight study in our Seattle clinic. For home testing, Lucía Ferrer provides your recorder kit and set-up guidance during an afternoon visit. For complex sleep difficulties, you stay overnight in our private room, checking in at 20:30. Senior technologist Owen Mbeki attaches painless scalp and body sensors to record sleep stages, breathing patterns, and heart rate while you sleep comfortably, concluding at 07:00 with fresh morning coffee.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Step 4: Results visit within 10 days</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Within 10 days of completing your overnight recording or home sleep test, you return to the clinic for a 45-minute results visit with your physician, priced at $140. Rather than simply delivering a diagnosis, your doctor sits with you to review your hypnogram and physiological recordings in detail. We examine sleep stages, oxygen stability, and micro-arousals together, translating complex scientific graphs into plain, understandable insights about how your body behaves during sleep and how those findings relate to your daytime exhaustion.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Step 5: Personalized plan and follow-up care</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Following your results review, we establish a personalized treatment plan tailored to your diagnosis, lifestyle, and preferences. For insomnia, you may begin our six-session CBT-I programme with sleep psychologist Dr. Priya Raman. For sleep apnea, nurse Grace Lin coordinates your CPAP mask fitting, pressure coaching, and four-week compliance check. Other patients benefit from circadian light protocols or specialist referrals to ENT surgeons and dental sleep providers. Follow-up consultations lasting 30 minutes are available at $95 to adjust your care as your sleep improves.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Do I need a referral from my primary care doctor to book an appointment?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>You do not need a physician referral to schedule an appointment at Nemuri Clinic. As an independent, self-pay medical practice, we welcome direct bookings from individuals seeking specialized sleep evaluations. However, if your primary care provider has already completed preliminary health screenings or documented specific medical concerns, we encourage you to bring those medical records or laboratory results to your first consultation. Having your previous clinical history allows our physicians to coordinate effectively with your overall healthcare team while assessing your sleep health.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What should I bring with me to my first consultation?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>For your initial 60-minute consultation, please bring a valid government-issued photo identification and a comprehensive, up-to-date list of all prescription medications, over-the-counter supplements, and vitamins you currently take, including dosage details. If you have kept a sleep diary, sleep log, or wearable device sleep summary over the past two weeks, please bring those notes along. These records offer valuable background information that helps our sleep physicians understand your baseline sleep patterns and daytime energy levels from your very first visit.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Will my health insurance policy cover consultations and sleep studies?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Nemuri Clinic operates strictly as a self-pay clinic, meaning we do not bill insurance carriers directly, and payment is collected at the time services are rendered. We provide an itemised receipt containing standardized diagnostic codes and billing descriptions for every consultation, home test, and overnight study. You can submit this receipt directly to your insurance company or flexible spending account for potential reimbursement. Because insurance policies and coverage terms vary significantly between different providers, we cannot promise what your insurer will reimburse.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Why are clinic consultations offered exclusively in the afternoon and evening?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Dr. Hana Ellery founded Nemuri Clinic specifically to serve working adults who find it difficult or impossible to take time off during standard daytime business hours. Taking half a day off from work to attend medical appointments frequently discourages patients from seeking necessary care. By scheduling consultations from 13:00 to 17:00 and 17:30 to 21:00 Tuesday through Friday, along with Saturday appointments from 09:00 to 15:00, we make specialized sleep medicine accessible without disrupting your professional schedule.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What happens if I have trouble falling asleep during the in-lab night study?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Many patients worry that sleeping in an unfamiliar clinic environment while wearing physiological monitoring sensors will prevent them from drifting off. Our Seattle study room is intentionally designed to feel quiet, dim, and welcoming, resembling a calm bedroom rather than a sterile hospital laboratory. Senior sleep technologist Owen Mbeki ensures all sensors are applied comfortably with gentle adhesives. Even if you sleep less than usual, modern polysomnographic recording captures hours of vital sleep architecture and respiratory data that provide significant clinical value.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">How do I return the portable home sleep test kit after my recording?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>After completing your one-night home sleep test, you simply place the recorder, chest belt, finger clip, and nasal sensor back into the protective carry pouch provided. You return the kit directly to our front desk at Suite 210, 88 Alder Lane the following morning during regular clinic operating hours. Sleep technologist Lucía Ferrer checks the equipment in, downloads your physiological recording data immediately, and prepares the study for physician analysis ahead of your scheduled results visit.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">What is your clinic cancellation and rescheduling policy?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We recognize that unpredictable work deadlines and family emergencies occur. If you need to cancel or reschedule an upcoming consultation, home test setup, or overnight night study, we require at least 24 hours of advance notice by telephone or email. This courtesy enables us to offer the reserved appointment time to another patient awaiting evaluation. Cancellations or missed appointments made with less than 24 hours of notice incur a fixed cancellation fee of $60.</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">How quickly will I receive the results of my sleep test?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We believe patients should never have to endure long, anxious waits for diagnostic test results. Following your home sleep test or in-lab polysomnography study, your physiological data is analyzed carefully and reviewed by our sleep physician. Your comprehensive 45-minute results visit is scheduled within 10 days of your study completion. During this visit, your physician personally explains your hypnogram and respiratory readings in detail, answering all of your questions and collaboratively mapping out your treatment plan.</p>
<!-- /wp:paragraph -->
