<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Dr. Tomas Varga — Sleep Physician</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Dr. Tomas Varga is a sleep physician specializing in sleep-related breathing disorders, complex sleep apnea, and nocturnal hypoventilation. Dr. Varga evaluates patient diagnostic recordings, reviews airflow and oxygenation data, and guides individuals toward appropriate airway therapies. He works in close coordination with ENT surgeons and dental specialists when patients require structural airway interventions or custom oral appliances to maintain open nocturnal respiration.</p>
