<h2 class="wp-block-heading">Dr. Priya Raman — Sleep Psychologist</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Dr. Priya Raman leads our Cognitive Behavioural Therapy for Insomnia (CBT-I) programme, helping adults overcome persistent sleep-onset difficulties and early morning awakenings. Over six weekly 50-minute sessions, Dr. Raman guides patients through evidence-based behavioral realignment, stimulus control, and sleep restriction techniques. Her compassionate, structured methods empower individuals to rebuild sleep efficiency and achieve sustained, drug-free restoration of natural nocturnal sleep patterns.</p>
<!-- /wp:paragraph -->
