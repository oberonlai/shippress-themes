<h2 class="wp-block-heading sr-h">Five words on every listing.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The same numbers, in the same order, on every sheet. Here is what each one means and how we measure it.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"sr-faq","layout":{"type":"default"}} -->
<div class="wp-block-group sr-faq"><!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>LDK, and the number in front of it</summary><!-- wp:paragraph -->
<p>The number is the bedrooms; L, D and K are a living room, a dining area and a kitchen, usually in one open room. A 2LDK has two bedrooms. An S is a study or storage room without a full-size window.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Floor area in m²</summary><!-- wp:paragraph -->
<p>Measured to the centre of the walls, as the advertising rules ask. Balconies, yards and shared corridors are not included. Houses also list the land.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Station walk</summary><!-- wp:paragraph -->
<p>Road distance to the nearest station entrance at 80 metres a minute, rounded up. Our journal posts give the real morning walk for some homes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Built</summary><!-- wp:paragraph -->
<p>The year the building was finished and its frame: timber, steel or reinforced concrete. New builds show the planned completion month instead.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Fees</summary><!-- wp:paragraph -->
<p>Every monthly fee and one-off payment is on the sheet in yen: the management fee and repair fund for flats, and deposit, key money and lease terms for rentals.</p>
<!-- /wp:paragraph --></details>
